#!/usr/bin/env python3
"""Write the Torment addon's world-map bounds, read from the client's WorldMapArea.dbc.

The pylon and shrine minimap pins (diablocraft-wylpu, P5 of `docs/proposals/pylons.md`, 6.8 (b))
stand on the minimap at the world position the object's own record carries
(`docs/contracts/pylon-messages.md`, record `S`). The 3.3.5a client hands an addon no world
coordinates of its own and no way to ask a map for its world rectangle, so the rectangle has to
ship with the addon: this reads the client's WorldMapArea.dbc and writes
`client-patch/addons/Torment/MapBounds.lua`, which `Pylons.lua` pairs with
`GetPlayerMapPosition` (that is the world -> minimap conversion Astrolabe does with its own
hardcoded copy of this same table).

The table is keyed by the id the client's `GetCurrentMapAreaID()` answers with, which on 3.3.5a is
the WorldMapArea.dbc row ID plus one (diablocraft-dm9vg.15: keyed by the row ID, the Kalimdor map read
row 14, the Eastern Kingdoms' rectangle, and the bounty markers stood a zone too far north on the designer's
playtest; ElvUI 6.09, pinned 8c0ac9d0, Modules/UnitFrames/UnitFrames.lua instanceMapIDs, names the
battlegrounds 402, 444, 462, 483, 513, 541, whose rows are 401, 443, 461, 482, 512, 540). Each row
also carries its world map id (the DBC's MapID), so a reader can tell Kalimdor from the Eastern
Kingdoms, whose rectangles overlap in yards.

The same file carries a second table for the bounty map panel (diablocraft-dm9vg.6, .15): for every
zone in `mod-diablocraft/data/d3/rift_open_zones.csv`, keyed by the row's own `key` (the zone key the
server puts in a bounty board's `C` and `W` records), the two world maps the zone is on, its source map and the
rift copy. The panel draws a zone's marker at the waypoint its `W` record carries, on any shown map of
one of those two (`docs/contracts/bounty-messages.md`; BountyMap.lua).

    python client-patch/build_map_bounds.py

Rerun after the DBC or rift_open_zones.csv changes (a new map, a moved area, a new open zone):
it writes the whole file from the inputs every time and is byte-stable, so a rerun over
unchanged input changes nothing.

Format (WDBC, 3.3.5a): 20-byte header, then 44-byte records, then the string block. The eleven
fields are ID, MapID, AreaID, AreaName (locale index), locLeft, locRight, locTop, locBottom,
DisplayMapID, DefaultDungeonFloor, ParentWorldMapID; the four loc fields are floats in world
yards. World X runs north (larger) to south and world Y runs west (larger) to east, so on a
north-up map locLeft/locRight are the west and east edges (in world Y) and locTop/locBottom the
north and south edges (in world X). The core reads the table the same way: WorldMapAreaEntry
names fields 4,5 `y1,y2` and 6,7 `x1,x2` (DBCStructure.h), and Map2ZoneCoordinates
(DBCStores.cpp) is the world <-> map-coordinate pair the client's own GetPlayerMapPosition
agrees with. Every row in the shipped file holds locLeft > locRight and locTop > locBottom, and
this refuses to write one that does not, because the addon's arithmetic assumes it.
"""
from __future__ import annotations

import csv
import struct
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
DBC = REPO_ROOT / "client-patch/dbc/WorldMapArea.dbc"
ZONES = REPO_ROOT / "mod-diablocraft/data/d3/rift_open_zones.csv"
OUTPUT = REPO_ROOT / "client-patch/addons/Torment/MapBounds.lua"

FIELDS = 11
CLIENT_ID_OFFSET = 1                    # GetCurrentMapAreaID() = row ID + 1 on 3.3.5a (above)
RECORD_SIZE = 44
MAP_ID, AREA_ID = 1, 2                  # of the DBC record
LEFT, RIGHT, TOP, BOTTOM = 4, 5, 6, 7   # locLeft, locRight, locTop, locBottom

# (row id, map_id, area_id, left, right, top, bottom)
Row = tuple[int, int, int, float, float, float, float]

HEADER = """-- GENERATED by client-patch/build_map_bounds.py - do not edit; rerun it instead.
--
-- The world rectangle of every world-map area, from the client's own WorldMapArea.dbc, keyed by
-- the id GetCurrentMapAreaID() answers with: the DBC row ID plus one on 3.3.5a (Kalimdor, row 13,
-- is [14]). {locLeft, locRight, locTop, locBottom, mapID}: the rectangle in world yards, the DBC's
-- own order, then the world map it is on. World X runs north (larger) to south and world Y runs
-- west (larger) to east, so on a north-up map a row's first two are its west and east edges and
-- the next two its north and south edges. Pylons.lua uses it with GetPlayerMapPosition to place the
-- pylon and shrine minimap pins; a 3.3.5a addon can ask the client for neither the bounds nor its
-- own world position (docs/contracts/pylon-messages.md).
--
-- Diablocraft.MapZones holds, for every zone in rift_open_zones.csv keyed by the zone key a bounty
-- board's C and W records carry, the world maps the zone is on: {sourceMap, riftCopyMap}. BountyMap.lua
-- draws the zone's marker at the W record's waypoint on a shown map of either
-- (docs/contracts/bounty-messages.md).

Diablocraft = Diablocraft or {}
Diablocraft.MapBounds = {
"""

ZONES_HEADER = """}
Diablocraft.MapZones = {
"""

FOOTER = "}\n"


def read_dbc(path: Path) -> list[Row]:
    data = path.read_bytes()
    magic, records, fields, record_size, _ = struct.unpack("<4sIIII", data[:20])
    if magic != b"WDBC":
        raise SystemExit(f"{path}: not a WDBC file")
    if fields != FIELDS or record_size != RECORD_SIZE:
        raise SystemExit(f"{path}: expected {FIELDS} fields of {RECORD_SIZE} bytes, got {fields}/{record_size}")
    rows = []
    for index in range(records):
        record = struct.unpack_from("<%dI" % FIELDS, data, 20 + index * RECORD_SIZE)
        left, right, top, bottom = (struct.unpack_from("<f", data, 20 + index * RECORD_SIZE + field * 4)[0]
                                    for field in (LEFT, RIGHT, TOP, BOTTOM))
        if not (left >= right and top >= bottom):
            raise SystemExit(f"{path}: area {record[0]} is stored the other way round "
                             f"(locLeft {left} / locRight {right}, locTop {top} / locBottom {bottom})")
        if left == right or top == bottom:
            continue  # a continent placeholder with no rectangle of its own
        rows.append((record[0], record[MAP_ID], record[AREA_ID], left, right, top, bottom))
    return rows


def zone_maps(rows: list[Row]) -> list[tuple[str, int, int]]:
    """One (key, source map, rift copy map) per rift_open_zones row; the zone must be a row of its source map."""
    if not ZONES.is_file():
        raise SystemExit(f"{ZONES} is missing")
    out = []
    with ZONES.open(newline="") as handle:
        for row in csv.DictReader(handle):
            source_map, area_id = int(row["source_map"]), int(row["zone_id"])
            found = [r for r in rows if r[1] == source_map and r[2] == area_id]
            if len(found) != 1:
                raise SystemExit(f"{ZONES}: zone {row['key']} (map {source_map}, area {area_id}) has "
                                 f"{len(found)} rows in {DBC.name}, expected 1")
            out.append((row["key"], source_map, int(row["map_id"])))
    return out


def rect(left: float, right: float, top: float, bottom: float) -> str:
    return ", ".join("%.2f" % value for value in (left, right, top, bottom))


def emit(rows: list[Row], zones: list[tuple[str, int, int]]) -> str:
    lines = [HEADER]
    for row_id, map_id, _, left, right, top, bottom in rows:
        lines.append("    [%d] = {%s, %d},\n" % (row_id + CLIENT_ID_OFFSET, rect(left, right, top, bottom), map_id))
    lines.append(ZONES_HEADER)
    for key, source_map, copy_map in zones:
        lines.append('    ["%s"] = {%d, %d},\n' % (key, source_map, copy_map))
    lines.append(FOOTER)
    return "".join(lines)


def main() -> int:
    if not DBC.is_file():
        raise SystemExit(f"{DBC} is missing; build the client DBCs first")
    rows = read_dbc(DBC)
    if not rows:
        raise SystemExit(f"{DBC}: no rows")
    zones = zone_maps(rows)
    OUTPUT.write_text(emit(rows, zones))
    print(f"{OUTPUT.relative_to(REPO_ROOT)}: {len(rows)} areas, {len(zones)} zones")
    return 0


if __name__ == "__main__":
    sys.exit(main())
