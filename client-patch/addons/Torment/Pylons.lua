-- luacheck: globals Diablocraft CreateFrame GetPlayerMapPosition GetCurrentMapAreaID
-- luacheck: globals SetMapToCurrentZone GetCVar GetPlayerFacing GetSpellTexture UnitName SendAddonMessage
-- Pylons and shrines: a minimap pin for each standing object (design:
-- docs/proposals/pylons.md 6.8 (b); the wire is docs/contracts/pylon-messages.md).
--
-- P3's objects whisper DCPYLON to their map's players: C drops every pin, S stands one at a world
-- position, U takes it away at the click. This draws one pin per standing object, with the kind's
-- own icon, and drops it on U.
--
-- A 3.3.5a addon has no world coordinates of its own and no call that turns a world point into a
-- minimap pixel, so the placement is Astrolabe's: GetPlayerMapPosition gives the player's position
-- on the map (0..1), the map's own world rectangle (Diablocraft.MapBounds, generated by
-- client-patch/build_map_bounds.py from the client's WorldMapArea.dbc) turns both that and the
-- object's wire position into world yards, and the minimap's zoom says how many yards it draws
-- across (the client's own diameter table, the numbers Astrolabe carries).
--
-- World X runs north (+) to south and world Y west (+) to east, so east is -Y and north is +X: the
-- core reads the same rectangle the same way (WorldMapAreaEntry names fields 4,5 `y1,y2` and 6,7
-- `x1,x2`, and Map2ZoneCoordinates is its world/map pair). The minimap is north-up unless the
-- player turned rotateMinimap on.

Diablocraft = Diablocraft or {}
local DC = Diablocraft
DC.Pylons = DC.Pylons or {}
local P = DC.Pylons

local PREFIX = "DCPYLON"
P.SIZE = 16          -- the pin, in pixels
P.INTERVAL = 0.2     -- seconds between two placements: a UI cadence, not a game number
-- The pin layer's switch, off: no pin draws until the placement is proven in a rift. The
-- list from the server is still kept, so turning it on (`/run Diablocraft.Pylons.ENABLED = true`)
-- draws the standing objects at once. test_pylon_pins.lua runs with it on.
P.ENABLED = false

-- The pin's icon is the buff's own: the record per kind (docs/contracts/pylon-messages.md).
local RECORD = {
    power = 83500, conduit = 83501, channeling = 83502, shield = 83503, speed = 83504,
    blessed = 83505, empowered = 83506, enlightened = 83507, fleeting = 83508,
    fortune = 83509, frenzied = 83510,
}

-- Yards the minimap draws across at zoom level 0..5, for each of its two scales: an instance uses
-- the indoor set, the open world the outdoor one. The client's own numbers (Astrolabe's MiniMapSize).
local DIAMETER = {
    indoor = { 300, 240, 180, 120, 80, 50 },
    outdoor = { 466.6667, 400, 333.3333, 266.6667, 200, 133.3333 },
}

local pins = {}    -- object guid -> {kind =, x = world X, y = world Y, frame =}
local areaID       -- the world-map area the player is on, or nil when it has no rectangle

-- The kind's icon, or nil when the record is not in this client's Spell.dbc yet.
local function iconFor(kind)
    local record = RECORD[kind]
    return record and GetSpellTexture(record) or nil
end

local function frameFor(pin)
    if pin.frame then return pin.frame end
    local frame = CreateFrame("Frame", nil, _G.Minimap)
    frame:SetSize(P.SIZE, P.SIZE)
    frame:SetFrameLevel(8)   -- above the minimap's terrain, with its own blips
    local icon = frame:CreateTexture(nil, "ARTWORK")
    icon:SetAllPoints(frame)
    local texture = iconFor(pin.kind)
    if texture then
        icon:SetTexture(texture)
    else
        -- No record means no icon to show; a plain gold square still marks the object, where an
        -- untextured pin would be invisible.
        icon:SetTexture(1.00, 0.82, 0.00)
    end
    pin.frame = frame
    return frame
end

local function drop(guid)
    local pin = pins[guid]
    if pin and pin.frame then pin.frame:Hide() end
    pins[guid] = nil
end

local function clear()
    for guid in pairs(pins) do drop(guid) end
end

-- The area the player stands in. GetPlayerMapPosition only answers for a map the world map is
-- pointed at, so the map is set to the player's zone here - the state it opens in anyway, so
-- nothing the player navigated to for reference is lost. While the world map is open it belongs
-- to the player, and the last answer stands until it closes.
local function resolveArea()
    local bounds = DC.MapBounds
    if not bounds then return end
    if _G.WorldMapFrame and _G.WorldMapFrame:IsShown() then return end
    SetMapToCurrentZone()
    local id = GetCurrentMapAreaID()
    areaID = bounds[id] and id or nil
end

-- Every pin at the object's place on the minimap: the player's own world position, the object's,
-- the difference in yards, then pixels. A pin the player is too far from rides the minimap's edge,
-- in its true direction.
local function placeMinimapPins()
    if not P.ENABLED then
        for _, pin in pairs(pins) do if pin.frame then pin.frame:Hide() end end
        return
    end
    local minimap = _G.Minimap
    if not (minimap and next(pins)) then return end
    if not areaID then resolveArea() end
    local row = areaID and DC.MapBounds and DC.MapBounds[areaID]
    local mx, my = GetPlayerMapPosition("player")
    if not row or not mx or (mx == 0 and my == 0) then
        -- No rectangle for the area (an instance the client has no world map for), or the client does
        -- not know where the player is on it: no pin can be placed, and one drawn before would stand
        -- frozen at a place that is no longer true.
        for _, pin in pairs(pins) do if pin.frame then pin.frame:Hide() end end
        return
    end
    local left, right, top, bottom = row[1], row[2], row[3], row[4]
    local playerY = left + mx * (right - left)
    local playerX = top + my * (bottom - top)

    local zoom = minimap:GetZoom()
    local outside = (GetCVar("minimapZoom") + 0) == zoom
    local perYard = minimap:GetWidth() / (outside and DIAMETER.outdoor or DIAMETER.indoor)[zoom + 1]
    local limit = minimap:GetWidth() / 2 - P.SIZE / 2
    local facing = GetCVar("rotateMinimap") ~= "0" and GetPlayerFacing() or nil

    -- Astrolabe's frame: x grows east (right), y grows SOUTH (down the map), so the rotation below is
    -- its own; the y is turned to the minimap's up-positive only at SetPoint (passed as is, a pin north
    -- of the player would draw south of it and run away from a player following it).
    for _, pin in pairs(pins) do
        local x = (playerY - pin.y) * perYard   -- east is -Y, and east is right
        local y = (playerX - pin.x) * perYard   -- north is +X, so a pin to the north has y < 0
        if facing then
            local sin, cos = math.sin(facing), math.cos(facing)
            x, y = x * cos - y * sin, x * sin + y * cos
        end
        local distance = math.sqrt(x * x + y * y)
        if distance > limit and distance > 0 then
            x, y = x * limit / distance, y * limit / distance
        end
        local frame = frameFor(pin)
        frame:ClearAllPoints()
        frame:SetPoint("CENTER", minimap, "CENTER", x, -y)
        frame:Show()
    end
end
P.Place = placeMinimapPins

-- C, S|<guid>|<kind>|<x>|<y>, U|<guid>; anything else (the bridge's X refusal, a newer record) is
-- not ours to read.
function P.Receive(message)
    local fields = {}
    for field in (message .. "|"):gmatch("(.-)|") do fields[#fields + 1] = field end
    if fields[1] == "C" then
        clear()
    elseif fields[1] == "S" and fields[2] and fields[3] then
        local x, y = tonumber(fields[4]), tonumber(fields[5])
        if x and y then
            local pin = pins[fields[2]] or {}
            pin.kind, pin.x, pin.y = fields[3], x, y
            pins[fields[2]] = pin
        end
    elseif fields[1] == "U" and fields[2] then
        drop(fields[2])
    end
end

function P.Ask()
    SendAddonMessage(PREFIX, "L", "WHISPER", UnitName("player"))
end

local watcher = CreateFrame("Frame")
watcher:RegisterEvent("CHAT_MSG_ADDON")
watcher:RegisterEvent("PLAYER_ENTERING_WORLD")
watcher:RegisterEvent("ZONE_CHANGED_NEW_AREA")
local elapsed = 0
watcher:SetScript("OnEvent", function(_, event, prefix, message, distribution, sender)
    if event == "CHAT_MSG_ADDON" then
        if prefix ~= PREFIX or distribution ~= "WHISPER" or sender ~= UnitName("player") then return end
        P.Receive(message)
        P.Place()
    elseif event == "PLAYER_ENTERING_WORLD" then
        resolveArea()
        P.Ask()      -- the map the player arrives on may have pushed its list before this addon loaded
        P.Place()
    elseif event == "ZONE_CHANGED_NEW_AREA" then
        resolveArea()
        P.Place()
    end
end)
watcher:SetScript("OnUpdate", function(_, delta)
    elapsed = elapsed + delta
    if elapsed < P.INTERVAL then return end
    elapsed = 0
    P.Place()
end)

resolveArea()
P.Ask()              -- a /reload drops the pins the server pushed; ask for the list again
