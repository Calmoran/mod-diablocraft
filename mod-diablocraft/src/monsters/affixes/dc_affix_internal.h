// ---------------------------------------------------------------------------
// 13-elite-affixes §6: the moving-hazard subsystem.
//
// Seven affixes are one primitive - a point, line, ring or wedge that moves on
// the map tick and hurts what it touches - and Fire Chains is the Link path.
// One implementation, each affix a client. A Burst stays the single delayed
// blast and a Zone the static ground; this is the shape that has to move.
//
// It is simulated server-side whether or not a client ever draws it: the visual step
// attaches a micro-stalker through `visualEntry`, so nothing here waits on art.
// ---------------------------------------------------------------------------
enum class HazardPath : std::uint8_t
{
    Ballistic,  // lobbed shell; impact is latched at launch (Mortar)
    Static,     // where it was put; a ring when innerRadius is set (Mortar impact)
    Linear,     // a point travelling outward (Electrified's bolts)
    GrowLine,   // an anchored segment whose far end advances (Poison Enchanted)
    Link,       // a segment between two living creatures (Fire Chains)
    Orbital,    // a point circling and spiralling out (Orbiter)
    Following,  // follows without settling (Thunderstorm strike sequence)
    Tracking,   // a point homing on a player, then settling (Frozen Pulse)
    Sweep,      // a beam whose angle rotates (Arcane Enchanted)
};

enum HazardTag : std::uint8_t
{
    TAG_NONE = 0, TAG_TRAIL, TAG_PULSE, TAG_CORE, TAG_SPHERE, TAG_POISON,
    TAG_BEAM, TAG_BOLT, TAG_MORTAR, TAG_CHAIN, TAG_POOL,
};

// Per-player escalation inside a stacking pool. Desecrator's and Plagued's
// damage doubles every damage_stack_interval while a player stays in it, to a
// cap, and the count resets after a grace delay out of it.
struct HazardStack
{
    ObjectGuid guid;
    std::uint32_t enteredAt = 0, lastSeenAt = 0;
    unsigned count = 1;
    std::uint32_t exposureMs = 0;
    bool inside = false;
};

struct Hazard
{
    std::uint32_t instanceId = 0, mapId = 0, shell = 0;
    unsigned tier = 1, grLevel = 0;
    std::string affixName;
    ObjectGuid caster;
    HazardPath path = HazardPath::Static;
    std::uint8_t tag = TAG_NONE;

    float originX = 0, originY = 0, originZ = 0;   // anchor / source / centre
    float x = 0, y = 0, z = 0;                      // moving point or far end
    float contactX = 0, contactY = 0;               // last bolt damage sample
    float impactX = 0, impactY = 0, impactZ = 0;    // latched ballistic destination
    float dirX = 0, dirY = 0;                       // unit direction, Linear/GrowLine
    float travelled = 0, maxLength = 0, length = 0; // travel cap / GrowLine / beam reach
    float speed = 0;                                // Linear, Tracking: yards per second

    float radius = 0;                               // contact radius, or outer ring
    float halfWidth = 0;                            // segment half-width; 0 = point
    float innerRadius = 0;                          // ring: inside this takes innerDamage
    double damage = 0, innerDamage = 0;
    std::uint32_t freezeMs = 0;
    unsigned strikesRemaining = 0;
    float slow = 0;                                 // 0 = no slow
    std::uint32_t slowSpell = 0;                    // the affix's own slow record

    // Stacking pools (Desecrator, Plagued): a tick's damage is the base times
    // stackMultiplier^(stacks-1), stacks grow every stackIntervalMs a player
    // stays in, cap at stackMax, and reset after stackResetMs out.
    bool escalating = false;
    double stackMultiplier = 1.0, stackIntervalMs = 0.0;
    unsigned stackMax = 1;
    std::uint32_t stackResetMs = 0, stackEntryMs = 0;
    std::vector<HazardStack> stackState;

    float angle = 0, sweepFrom = 0, sweepRate = 0, wedge = 0;      // Sweep
    float orbitRadius = 0, orbitStart = 0, orbitMax = 0, orbitSpeed = 0; // Orbital
    ObjectGuid target;                              // Tracking
    ObjectGuid linkA, linkB;                        // Link

    bool oneShot = false;                           // damage once, then retire
    bool oncePerTarget = false;                     // piercing: each player at most once
    std::vector<ObjectGuid> struck;

    std::uint32_t startAt = 0, armUntil = 0, endsAt = 0;
    std::uint32_t nextTick = 0, tickMs = 0, lastMove = 0;

    // Item 8 attaches a micro-stalker here; 0 and empty means the hazard is
    // simulated server-side and drawn by nothing yet.
    std::uint32_t visualEntry = 0;
    ObjectGuid visual;
};

