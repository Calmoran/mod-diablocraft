// 03 §5 elite look. Both are stock 3.3.5a cosmetic auras read out of the
// client's own Spell.dbc (client-patch/dbc/Spell.dbc, the SpellName field):
// "Glowy (Blue)" 22576 and "Glowy (Yellow)" 22580, from the Glowy (Red/Blue/
// Green/Black/Orange/Yellow/Purple) family. Both are a single APPLY_AURA of
// SPELL_AURA_DUMMY with DurationIndex 21, which SpellDuration.dbc gives as -1
// (infinite), and Attributes 0x180 = DO_NOT_DISPLAY | DO_NOT_LOG, so they show
// as a glow on the model and nothing in the aura bar or the combat log. The
// two carry different SpellVisual ids (6589 blue, 6592 yellow), so a champion
// pack and a rare pack never look the same. No client patch: an aura is a
// per-spawn effect the stock client renders (engine-facts.md Q3.5).
