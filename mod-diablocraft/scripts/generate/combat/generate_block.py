#!/usr/bin/env python3
"""Generate dc_block_tuning from the project-model rows of data/tunables/block.csv.

docs/research/block.md marks three things as PROJECT MODELS rather than
Blizzard-published figures: the 75% base Block Chance cap, the 100% total cap,
and the %-Block Amount scaling. They must not be compile-time constants and must
never be presented as sourced, so they live in one world table the designer can change
without a rebuild, in the same two-column shape dc_affix_tunables uses:

  d3_value    what D3 published. Always NULL here: Blizzard published none of
              these three. It exists so a later published figure has a home.
  tuned_value the designer's value. Seeded once from block.csv and never overwritten by
              a regeneration (ON DUPLICATE KEY UPDATE touches d3_value only).

The item-side Block Chance and Block Amount RANGES are not written here: they
are ordinary rolled affixes and live in affix_pools.csv -> dc_affix_pool, which
generate_sql.py owns.

Run from the repo root:

    python mod-diablocraft/scripts/generate/combat/generate_block.py
"""

import csv
from pathlib import Path

import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
import scripts_path  # noqa: E402,F401  (R5: every scripts/ folder on sys.path)
from applied_migrations import write_migration

MODULE = Path(__file__).resolve().parents[3]
DATA = MODULE / "data/d3"
# Phase 2 (Architect, 2026-09-19): this sheet is the designer's numbers, not D3's
# published reference data, so it moved to data/tunables/ and out of
# data/d3/. Its runtime home is unchanged - it is still this generator's
# table, not dc_tunables. data/tunables/README.md says so under "Files with
# their own table".
TUNABLES = MODULE / "data/tunables"
GENERATED = MODULE / "data/generated"
UPDATES = MODULE / "data/sql/db-world/updates"

# parameter -> (unit, what the number means). A parameter missing from this map
# is a typo in the CSV, not a new tunable: fail rather than write it.
PARAMETERS = {
    "block_chance_base_cap": "percent",
    "block_chance_total_cap": "percent",
    "block_amount_percent_scale": "multiplier",
}


def quote(value):
    return "'" + str(value).replace("\\", "\\\\").replace("'", "''") + "'"


def rows():
    with (TUNABLES / "block.csv").open(encoding="utf-8-sig", newline="") as stream:
        source = [row for row in csv.DictReader(stream) if row["row_kind"] == "project_model"]
    if not source:
        raise SystemExit("block.csv has no project_model rows")
    built = []
    for row in source:
        parameter = row["stat"]
        if parameter not in PARAMETERS:
            raise SystemExit(f"block.csv: unknown project_model parameter {parameter!r}")
        if row["value_min"] != row["value_max"]:
            raise SystemExit(f"block.csv: {parameter} is one value, not a range")
        built.append((parameter, float(row["value_min"]), PARAMETERS[parameter], row["notes"]))
    missing = set(PARAMETERS) - {row[0] for row in built}
    if missing:
        raise SystemExit("block.csv is missing project_model rows: " + ", ".join(sorted(missing)))
    return built


def main():
    built = rows()
    # The path in the generated header below still says data/d3 on purpose:
    # this delta has already been applied, and an applied delta must stay
    # byte-identical - generate_bags.py has an explicit guard that refuses
    # exactly this. The sheet is at data/tunables/ now; the next numbered
    # delta is where the comment gets corrected.
    sql = "-- Generated by generate_block.py from data/d3/block.csv project_model rows.\n"
    sql += "-- docs/research/block.md: every value here is a PROJECT MODEL, not published by Blizzard.\n"
    sql += ("CREATE TABLE IF NOT EXISTS dc_block_tuning ("
            "parameter VARCHAR(64) NOT NULL PRIMARY KEY, "
            "d3_value DOUBLE NULL, tuned_value DOUBLE NULL, "
            "unit VARCHAR(32) NOT NULL, notes TEXT NOT NULL);\n")
    sql += "INSERT INTO dc_block_tuning (parameter,d3_value,tuned_value,unit,notes) VALUES\n"
    sql += ",\n".join(
        "(" + ",".join([quote(parameter), "NULL", f"{value:g}", quote(unit), quote(notes)]) + ")"
        for parameter, value, unit, notes in built)
    # The CSV wins on every apply (ruling 2026-09-19): block.csv lives in
    # data/tunables/, so re-applying writes its numbers over the table's.
    # Refreshing d3_value alone left an edited tuned_value stranded in the
    # sheet on any world that already had the row.
    sql += ("\nON DUPLICATE KEY UPDATE d3_value=VALUES(d3_value), tuned_value=VALUES(tuned_value),"
            " unit=VALUES(unit), notes=VALUES(notes);\n")
    GENERATED.mkdir(parents=True, exist_ok=True)
    (GENERATED / "block_tuning.sql").write_text(sql, encoding="utf-8", newline="\n")
    write_migration(MODULE, UPDATES / "items_0006_block_tuning.sql", sql)
    print(f"dc_block_tuning: {len(built)} rows")


if __name__ == "__main__":
    import argparse
    argparse.ArgumentParser(description=__doc__).parse_args()
    main()
