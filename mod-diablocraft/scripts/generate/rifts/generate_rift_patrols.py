#!/usr/bin/env python3
"""the designer's recorded patrol routes as stock waypoint_data paths (diablocraft-tyt6, docs/proposals/monster-spawning.md 3.6, Part S5).

    python3 mod-diablocraft/scripts/generate/rifts/generate_rift_patrols.py                                   # sheet -> rift_patrols_0001.sql (offline)
    python3 mod-diablocraft/scripts/generate/rifts/generate_rift_patrols.py --export --mysql M --defaults-file D   # dev waypoint_data -> sheet

`.dc patrol record start|stop` (src/rifts/dc_rift_patrol.cpp) writes his walk on dev as waypoint_data rows in the id range
ROUTE_FIRST..ROUTE_LAST and a dc_rift_route row (source `alex`). `--export` brings the points into data/d3/rift_route_points.csv (the
route rows come home with generate_rift_survey.py --export). The default run turns the sheet into the migration that writes the same
rows into waypoint_data, and its DELETE stays inside his range, so no stock path and no other generator's row is touched. The 516 stock
patrol paths need no sheet: they are in waypoint_data already, and rift_routes.csv (source `survey`) ties them to anchors.
The range numbers are the same as dc_rift_patrol.h's (test_rift_patrol.py holds the two equal).
"""
import argparse
import csv
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
import scripts_path  # noqa: E402,F401  (R5: every scripts/ folder on sys.path)
from applied_migrations import write_coupled_outputs, write_migration  # noqa: E402

MODULE = Path(__file__).resolve().parents[3]
D3 = MODULE / "data/d3"
NAME = "rift_patrols_0001.sql"
COLUMNS = ("dungeon", "path_id", "point", "x", "y", "z")
ROUTE_FIRST, ROUTE_LAST = 900000000, 999999999


def read_csv(path):
    with Path(path).open(encoding="utf-8-sig", newline="") as stream:
        return list(csv.DictReader(stream, strict=True))


def write_csv(path, rows):
    with Path(path).open("w", encoding="utf-8", newline="") as stream:
        writer = csv.writer(stream, lineterminator="\n")
        writer.writerow(COLUMNS)
        writer.writerows([[r[c] for c in COLUMNS] for r in rows])


def check(points, routes):
    """The sheet's rules, as problems: each path in his range, numbered 1..n with two points at least, tied by a route row of source
    `alex` in the same dungeon; and every route of his has its points. A stock route (source `survey`) is no business of this sheet."""
    problems, paths = [], {}
    for r in points:
        paths.setdefault((r["dungeon"], int(r["path_id"])), []).append(int(r["point"]))
        if not ROUTE_FIRST <= int(r["path_id"]) <= ROUTE_LAST:
            problems.append(f"path {r['path_id']} is outside {ROUTE_FIRST}..{ROUTE_LAST}")
        for c in ("x", "y", "z"):
            if not re.fullmatch(r"-?\d+(\.\d+)?", r[c].strip()):
                problems.append(f"path {r['path_id']} point {r['point']}: {c} '{r[c]}' is not a number")
    for (dungeon, path), numbers in paths.items():
        if sorted(numbers) != list(range(1, len(numbers) + 1)):
            problems.append(f"path {path}: points are not numbered 1 to {len(numbers)}")
        if len(numbers) < 2:
            problems.append(f"path {path}: a route has two points at least")
    mine = {(r["dungeon"], int(r["path_id"])) for r in routes if r["source"] == "alex"}
    for key in sorted(set(paths) - mine):
        problems.append(f"path {key[1]} ({key[0]}) has points but no rift_routes.csv row of source alex")
    for key in sorted(mine - set(paths)):
        problems.append(f"route {key[1]} ({key[0]}) is the designer's but the sheet holds no points for it")
    return problems


def render(points):
    rows = sorted(points, key=lambda r: (int(r["path_id"]), int(r["point"])))
    parts = ["-- Generated by generate_rift_patrols.py from data/d3/rift_route_points.csv (diablocraft-tyt6); never edit.",
             "-- the designer's recorded patrol routes (docs/proposals/monster-spawning.md 3.6, Part S5) as stock waypoint_data paths, in the id range",
             f"-- {ROUTE_FIRST}..{ROUTE_LAST} reserved for them. The DELETE stays inside it.",
             f"DELETE FROM `waypoint_data` WHERE `id` BETWEEN {ROUTE_FIRST} AND {ROUTE_LAST};"]
    for start in range(0, len(rows), 500):
        values = ",\n".join(f"({r['path_id']}, {r['point']}, {r['x']}, {r['y']}, {r['z']})" for r in rows[start:start + 500])
        parts.append(f"INSERT INTO `waypoint_data` (`id`, `point`, `position_x`, `position_y`, `position_z`) VALUES\n{values};")
    return "\n".join(parts) + "\n"


def generate(directory=None):
    directory = Path(directory or D3)
    points, routes = read_csv(directory / "rift_route_points.csv"), read_csv(directory / "rift_routes.csv")
    problems = check(points, routes)
    if problems:
        raise SystemExit("rift_route_points.csv: " + "; ".join(problems))
    sql = render(points)
    target = MODULE / "data/sql/db-world/updates" / NAME
    write_migration(MODULE, target, sql)
    write_coupled_outputs(MODULE, target, sql, [(MODULE / "data/generated" / NAME, sql)], label="rift patrol routes")
    print(f"Generated {NAME}")


def export(db, directory=None):
    """The dev world database's recorded paths into the sheet. A path in his range with no dc_rift_route row has no dungeon: it stops the export."""
    lines = db.query("SELECT r.dungeon, w.id, w.point, w.position_x, w.position_y, w.position_z FROM waypoint_data w "
                     f"LEFT JOIN dc_rift_route r ON r.path_id = w.id WHERE w.id BETWEEN {ROUTE_FIRST} AND {ROUTE_LAST} ORDER BY w.id, w.point")
    rows = []
    for line in lines:
        dungeon, path, point, x, y, z = line.split("\t")
        if dungeon == "NULL":
            raise SystemExit(f"waypoint_data path {path} is in the range reserved for the designer's routes but has no dc_rift_route row")
        rows.append(dict(zip(COLUMNS, (dungeon, path, point, x, y, z))))
    write_csv(Path(directory or D3) / "rift_route_points.csv", rows)
    print(f"exported {len(rows)} points of {len({r['path_id'] for r in rows})} routes")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--export", action="store_true", help="bring the dev world database's recorded paths into the sheet")
    parser.add_argument("--mysql")
    parser.add_argument("--defaults-file")
    args = parser.parse_args()
    if args.export:
        import fixture_db
        from generate_area_copies import Database
        mysql, defaults = (args.mysql, args.defaults_file) if args.mysql and args.defaults_file else fixture_db.mysql_and_defaults([])
        export(Database(mysql, defaults, "acore_world"))
    generate()


if __name__ == "__main__":
    main()
