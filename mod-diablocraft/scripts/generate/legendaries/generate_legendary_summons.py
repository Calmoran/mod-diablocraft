#!/usr/bin/env python3
"""Emit the creature templates of the item-summoned allies from data/legendary_summons.csv (diablocraft-uisny).

One row an ally a legendary item summons: its entry, the donor creature whose row and model it copies, and the
ScriptName that gives it its AI (dc_legendary_ally fights, dc_legendary_pawn only stands where it is put). Each is the
donor's own row with the module's AI and no loot, gold, gossip or credit, the way the Wizard's summons are made
(generate_spells.py generate_wizard_summon_templates). Life, level, faction, owner, lifetime and damage are set at the
summon by the power that summons it (docs/contracts/legendary-world-pieces.md, N-SUMMON).

0001 is applied on dev and never changes. Its clone carried the donor's difficulty_entry_1..3 over (17429 lists the
heroic 18603, so the ally 900122 claimed it: "already listed as difficulty_entry_1 for another entry"), so 0002 resets
them on every ally (diablocraft-fah9d).

0001 and 0002 hold the eight allies of entries up to FIRST_BATCH_END and stay as applied. An ally past it is rendered, template
and difficulty reset together, into the next migration (0003), so a later ally never changes an applied file.
"""
import csv
from pathlib import Path

import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
import scripts_path  # noqa: E402,F401  (R5: every scripts/ folder on sys.path)
from applied_migrations import write_migration

MODULE = Path(__file__).resolve().parents[3]
SCRIPTS = ('dc_legendary_ally', 'dc_legendary_pawn')
# The entries already taken by the module's other summons (Ancients, the Wizard's sheet); a new entry never reuses one.
OTHER_SHEETS = ('data/d3/wizard_summons.csv', 'data/d3/monk_summons.csv', 'data/d3/crusader_summons.csv', 'data/d3/necromancer_summons.csv')
ANCIENTS = range(900100, 900103)
FIRST_BATCH_END = 900127   # the last entry of the first eight allies (0001, 0002: applied)


def read(module, name):
    with (module / name).open(encoding='utf-8', newline='') as stream:
        return list(csv.DictReader(stream, strict=True))


def rows(module=MODULE, later=False):
    """The sheet's allies: the first eight (0001, 0002), or with `later` the ones past them (0003)."""
    taken = set(ANCIENTS) | {int(r['entry']) for n in OTHER_SHEETS for r in read(module, n)}
    out = []
    for r in read(module, 'data/legendary_summons.csv'):
        where = f"legendary_summons.csv {r['summon']}"
        entry, donor = int(r['entry']), int(r['donor_creature'])
        if entry in taken:
            raise ValueError(f'{where}: entry {entry} is taken')
        taken.add(entry)
        if r['script'] not in SCRIPTS:
            raise ValueError(f"{where}: script is one of {', '.join(SCRIPTS)}")
        if not r['why']:
            raise ValueError(f'{where}: needs its reason')
        if (entry > FIRST_BATCH_END) == later:
            out.append((entry, r['summon'], donor, r['script']))
    return out


def render(module=MODULE, later=False):
    sql = "-- Generated by generate_legendary_summons.py from legendary_summons.csv; do not hand-edit.\n"
    for entry, name, donor, script in rows(module, later):
        sql += (f"DELETE FROM creature_template WHERE entry={entry};\n"
                "CREATE TEMPORARY TABLE dc_ally_clone LIKE creature_template;\n"
                f"INSERT INTO dc_ally_clone SELECT * FROM creature_template WHERE entry={donor};\n"
                f"UPDATE dc_ally_clone SET entry={entry},name='{name.replace(chr(39), chr(39) * 2)}',subname='',npcflag=0,"
                "unit_flags=0,unit_flags2=0,type_flags=0,faction=35,AIName='',"
                f"ScriptName='{script}',gossip_menu_id=0,lootid=0,pickpocketloot=0,skinloot=0,mingold=0,maxgold=0,"
                "KillCredit1=0,KillCredit2=0,flags_extra=0;\n"
                "INSERT INTO creature_template SELECT * FROM dc_ally_clone;\n"
                "DROP TEMPORARY TABLE dc_ally_clone;\n"
                f"DELETE FROM creature_template_model WHERE CreatureID={entry};\n"
                f"INSERT INTO creature_template_model SELECT {entry},Idx,CreatureDisplayID,DisplayScale,"
                f"Probability,VerifiedBuild FROM creature_template_model WHERE CreatureID={donor};\n")
    return sql


def render_difficulty_reset(module=MODULE, later=False):
    entries = ','.join(str(entry) for entry, *_ in rows(module, later))
    return ("-- Generated by generate_legendary_summons.py from legendary_summons.csv; do not hand-edit.\n"
            "UPDATE creature_template SET difficulty_entry_1=0,difficulty_entry_2=0,difficulty_entry_3=0 "
            f"WHERE entry IN ({entries});\n")


def generate(module=MODULE):
    reset = render_difficulty_reset(module)
    (module / 'data/generated/legendary_summons_0002_difficulty_entries.sql').write_text(reset, encoding='utf-8', newline='\n')
    write_migration(module, module / 'data/sql/db-world/updates/legendary_summons_0002_difficulty_entries.sql', reset)
    sql = render(module)
    (module / 'data/generated/legendary_summons_0001_templates.sql').write_text(sql, encoding='utf-8', newline='\n')
    write_migration(module, module / 'data/sql/db-world/updates/legendary_summons_0001_templates.sql', sql)
    if rows(module, later=True):
        later = render(module, later=True) + render_difficulty_reset(module, later=True).split('\n', 1)[1]
        (module / 'data/generated/legendary_summons_0003_later_allies.sql').write_text(later, encoding='utf-8', newline='\n')
        write_migration(module, module / 'data/sql/db-world/updates/legendary_summons_0003_later_allies.sql', later)


if __name__ == '__main__':
    import argparse
    argparse.ArgumentParser(description=__doc__).parse_args()
    generate()
