#!/usr/bin/env python3
"""Emit dc_legendary_gem_pet from data/legendary_gem_pets.csv (diablocraft-ml7y).

One row a skill that counts as a pet for a gem (today only Enforcer): the gem, the class and skill, the creature
entries of that skill's summons that enemies can target (`|` joined, empty when none can), how well the claim is
sourced and where. The table holds one row per (skill, entry), entry NULL for a skill with none. An empty sheet is a
valid list: the gem then does nothing. Sources: docs/research/enforcer-pets-web-sources.md. Contract:
docs/contracts/legendary-gems.md.
"""
import csv
from pathlib import Path

import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
import scripts_path  # noqa: E402,F401  (R5: every scripts/ folder on sys.path)
from applied_migrations import write_migration

MODULE = Path(__file__).resolve().parents[3]
COLUMNS = ('gem_id', 'class', 'skill', 'creature_entries', 'evidence', 'source', 'note')
EVIDENCE = ('corroborated', 'wiki-only')


def read(module, name):
    with (module / name).open(encoding='utf-8', newline='') as stream:
        return list(csv.DictReader(stream, strict=True))


def rows(module=MODULE):
    """[(gem_id, skill, entry or None)] in sheet order, validated against the gem and skill sheets."""
    gems = {r['gem_id'] for r in read(module, 'data/d3/legendary_gems.csv') if r['gem_id']}
    out, seen = [], set()
    for r in read(module, 'data/legendary_gem_pets.csv'):
        where = f"legendary_gem_pets.csv {r['gem_id']} {r['skill']}"
        if r['gem_id'] not in gems:
            raise ValueError(f'{where}: not one of the 21 legendary gems')
        skills = {s['skill_name'] for s in read(module, f"data/d3/{r['class'].lower()}_skills.csv")}
        if r['skill'] not in skills:
            raise ValueError(f"{where}: {r['class']} has no such skill")
        if (r['gem_id'], r['skill']) in seen:
            raise ValueError(f'{where}: listed twice')
        seen.add((r['gem_id'], r['skill']))
        if not r['source'].startswith('https://'):
            raise ValueError(f'{where}: needs a source url')
        if r['evidence'] not in EVIDENCE:
            raise ValueError(f"{where}: evidence is one of {', '.join(EVIDENCE)}")
        try:
            entries = [int(e) for e in r['creature_entries'].split('|')] if r['creature_entries'] else [None]
        except ValueError:
            raise ValueError(f'{where}: creature_entries are |-joined creature entries') from None
        out += [(r['gem_id'], r['skill'], e) for e in entries]
    return out


def render(module=MODULE):
    values = [f"('{gem}','{skill.replace(chr(39), chr(39) * 2)}',{'NULL' if entry is None else entry})"
              for gem, skill, entry in rows(module)]
    sql = ("-- Generated by generate_legendary_gem_pets.py from legendary_gem_pets.csv; do not hand-edit.\n"
           "DROP TABLE IF EXISTS `dc_legendary_gem_pet`;\n"
           "CREATE TABLE `dc_legendary_gem_pet` (gem_id VARCHAR(32) NOT NULL, skill VARCHAR(64) NOT NULL,"
           " creature_entry INT UNSIGNED NULL, KEY (gem_id)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;\n")
    if values:
        sql += "INSERT INTO `dc_legendary_gem_pet` (gem_id,skill,creature_entry) VALUES\n" + ',\n'.join(values) + ';\n'
    return sql


def generate(module=MODULE):
    sql = render(module)
    (module / 'data/generated/legendary_gems_0003_pets.sql').write_text(sql, encoding='utf-8', newline='\n')
    write_migration(module, module / 'data/sql/db-world/updates/legendary_gems_0003_pets.sql', sql)


if __name__ == '__main__':
    import argparse
    argparse.ArgumentParser(description=__doc__).parse_args()
    generate()
