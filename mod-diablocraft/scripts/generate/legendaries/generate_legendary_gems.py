#!/usr/bin/env python3
"""Emit dc_legendary_gem from the number columns of legendary_gems.csv.

A row with an empty gem_id is a gem outside the 21 (Boon of the Hoarder on hold, Red Soul
Shard out, Whisper of Atonement waiting; ruling 2026-10-05) and is not emitted. The columns
are checked against d3planner by scripts/tests/legendaries/test_legendary_gems.py. base_effect and rank_25_bonus are the sheet's
sentences for the tooltip (diablocraft-2mzw), the scaling number of base_effect written {v:N}. Every gem needs its
rank_25_bonus (Legacy of Dreams' is its Ancient doubling again since diablocraft-5s8z6). Contract:
docs/contracts/legendary-gems.md.

The table has one migration, legendary_gems_0007_table.sql (a full replace of the rows; 0001 and 0006 stay as shipped,
and a migration nobody has shipped is regenerated in place).
"""
import csv
import re
from pathlib import Path

import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
import scripts_path  # noqa: E402,F401  (R5: every scripts/ folder on sys.path)
from applied_migrations import write_migration
from generate_crafting import quote

MODULE = Path(__file__).resolve().parents[3]
NUMBERS = ('base_value', 'per_rank', 'base_value_2', 'per_rank_2', 'max_rank',
           'rank25_value_1', 'rank25_value_2', 'fixed_1', 'fixed_2', 'fixed_3')
NUMBER = re.compile(r'\d{1,3}(?:,\d{3})+(?:\.\d+)?|\d+(?:\.\d+)?')


def mark(text, value, per_rank, tag, name):
    """base_effect with the one number that is `value` (the rank-0 number) written {tag:N}: N its decimals as the
    text writes them, `{tag:N,}` when it groups thousands. The tooltip writes Value(rank) in with those decimals
    (contract). Refused when the number is not there exactly once or N would hide a per-rank decimal."""
    hits = [m for m in NUMBER.finditer(text) if float(m.group().replace(',', '')) == float(value)]
    if len(hits) != 1:
        raise ValueError(f'{name}: base_effect must write {value} exactly once, found {len(hits)}')
    m = hits[0]
    places = len(m.group().partition('.')[2])
    if places < len(per_rank.partition('.')[2].rstrip('0')):
        raise ValueError(f'{name}: {m.group()} shows fewer decimals than per_rank {per_rank}')
    return f"{text[:m.start()]}{{{tag}:{places}{',' if ',' in m.group() else ''}}}{text[m.end():]}"


def render(module=MODULE):
    with (module / 'data/d3/legendary_gems.csv').open(newline='', encoding='utf-8') as stream:
        rows = [r for r in csv.DictReader(stream) if r['gem_id']]
    ids = [r['gem_id'] for r in rows]
    if len(set(ids)) != len(ids):
        raise ValueError('legendary_gems.csv: duplicate gem_id')
    values = []
    for r in rows:
        for column in ('base_value', 'per_rank'):
            if not r[column]:
                raise ValueError(f"{r['gem_name']}: {column} is empty")
        name = r['gem_name'].replace("'", "''")
        effect = mark(r['base_effect'], r['base_value'], r['per_rank'], 'v', name)
        if r['base_value_2']:
            effect = mark(effect, r['base_value_2'], r['per_rank_2'], 'v2', name)
        if not r['rank_25_bonus']:
            raise ValueError(f'{name}: rank_25_bonus is empty')
        cells = ','.join(r[c] or 'NULL' for c in NUMBERS)
        values.append(f"('{r['gem_id']}','{name}',{quote(effect)},{quote(r['rank_25_bonus'])},{cells})")
    return ("-- Generated by generate_legendary_gems.py from legendary_gems.csv; numbers from d3planner, not tunables; texts from the sheet.\n"
            "SET NAMES utf8mb4;\n"
            "CREATE TABLE IF NOT EXISTS dc_legendary_gem (gem_id VARCHAR(32) PRIMARY KEY, gem_name VARCHAR(64) NOT NULL,"
            " base_effect VARCHAR(255) NOT NULL, rank_25_bonus VARCHAR(255) NOT NULL, base_value DOUBLE NOT NULL, per_rank DOUBLE NOT NULL, base_value_2 DOUBLE NULL, per_rank_2 DOUBLE NULL,"
            " max_rank INT UNSIGNED NULL, rank25_value_1 DOUBLE NULL, rank25_value_2 DOUBLE NULL,"
            " fixed_1 DOUBLE NULL, fixed_2 DOUBLE NULL, fixed_3 DOUBLE NULL);\n"
            "DELETE FROM dc_legendary_gem;\n"
            "INSERT INTO dc_legendary_gem (gem_id,gem_name,base_effect,rank_25_bonus," + ','.join(NUMBERS) + ") VALUES\n"
            + ',\n'.join(values) + ';\n')


def generate(module=MODULE):
    sql = render(module)
    (module / 'data/generated/legendary_gems_0007_table.sql').write_text(sql, encoding='utf-8')
    write_migration(module, module / 'data/sql/db-world/updates/legendary_gems_0007_table.sql', sql)


if __name__ == '__main__':
    import argparse
    argparse.ArgumentParser(description=__doc__).parse_args()
    generate()
