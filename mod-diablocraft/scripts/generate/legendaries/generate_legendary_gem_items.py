#!/usr/bin/env python3
"""Legendary gems part 9 (diablocraft-i1y1): the 21 gems as items.

Reads data/legendary_gem_items.csv (gem_id, item_entry, socket_slots; entries are append-only
project identities, like gem_items.csv) and emits two migrations:

  world        legendary_gems_0002_items.sql   dc_legendary_gem_item (entry -> gem_id, the base-item
                                               slots it may be socketed into) and the 21 item_template rows
  characters   legendary_gems_0001_rank.sql    dc_legendary_gem_rank (one gem item's own rank, by item
                                               guid) and dc_item_affix.legendary_rank (a socketed gem's)

The 21 gems are the ones of legendary_gems.csv that have numbers (ruling 1, ruling 2026-10-05).
Contract: docs/contracts/legendary-gems.md.
"""
import csv
from pathlib import Path

import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
import scripts_path  # noqa: E402,F401  (R5: every scripts/ folder on sys.path)
from applied_migrations import write_migration
from generate_crafting import ensure_column, quote
from tunable_values import integer as tunable_integer

MODULE = Path(__file__).resolve().parents[3]
ENTRY_FIRST, ENTRY_LAST = 103100, 103199  # after the 50 normal gems (103000-103049), before nothing else
DONOR = 36926      # a stock gem's template; the icon is the designer's, set by generate_gem_icons.py's migration (fpo9l),
                   # so a new render of these rows needs a new one of that too
QUALITY_LEGENDARY = 5   # the stock quality enum, not a tunable
FLAG_BOUND_TO_ACCOUNT = 134217728  # the flag the base items carry (generate_crafting.py)
BASE_SLOTS = {'onehand', 'twohand', 'offhand', 'head', 'waist', 'finger', 'torso', 'feet', 'wrists',
              'legs', 'hands', 'shoulders', 'neck'}  # dc_base_item.slot values (base_items.csv)
DESCRIPTION_LIMIT = 255  # item_template.description is varchar(255) (diablocraft-item-descriptions)


def read(module, name):
    with (module / name).open(encoding='utf-8', newline='') as stream:
        return list(csv.DictReader(stream, strict=True))


def items(module=MODULE):
    """[(gem_id, name, entry, socket_slots)] in gem_id order, validated against legendary_gems.csv."""
    names = {r['gem_id']: r['gem_name'] for r in read(module, 'data/d3/legendary_gems.csv') if r['gem_id']}
    rows = read(module, 'data/legendary_gem_items.csv')
    ids = [r['gem_id'] for r in rows]
    if sorted(ids) != sorted(names):
        raise ValueError('legendary_gem_items.csv must list exactly the gems that have numbers in legendary_gems.csv')
    entries = [int(r['item_entry']) for r in rows]
    if len(set(entries)) != len(entries) or not all(ENTRY_FIRST <= e <= ENTRY_LAST for e in entries):
        raise ValueError(f'legendary_gem_items.csv: entries must be unique, {ENTRY_FIRST}-{ENTRY_LAST}')
    out = []
    for r in sorted(rows, key=lambda r: r['gem_id']):
        slots = r['socket_slots'].split('|')
        if not r['socket_slots'] or not set(slots) <= BASE_SLOTS:
            raise ValueError(f"{r['gem_id']}: socket_slots must be |-separated base-item slots")
        out.append((r['gem_id'], names[r['gem_id']], int(r['item_entry']), r['socket_slots']))
    return out


def world_sql(rows, module=MODULE):
    # description is the stock tooltip's gold quoted line: the sheet's flavour_text (diablocraft-2mzw).
    # item_template.description is varchar(255): a flavour that does not fit is dropped whole, never
    # truncated mid-sentence (the diablocraft-item-descriptions rule, generate_sql.item_description).
    # Iceblink (284) and Mirinae (297) are longer than the column and ship no flavour line.
    flavour = {r['gem_id']: (r['flavour_text'] if len(r['flavour_text']) <= DESCRIPTION_LIMIT else '')
               for r in read(module, 'data/d3/legendary_gems.csv') if r['gem_id']}
    zero_stats = ','.join(f'stat_type{i}=0,stat_value{i}=0' for i in range(1, 11))
    price = tunable_integer('economy', 'gem_vendor_gold')   # what a vendor charges: no vendor sells them
    sell = tunable_integer('economy', 'legendary_gem_sell_gold', minimum=1)   # the designer, card q-1006-04
    sql = ['-- Generated by generate_legendary_gem_items.py from legendary_gem_items.csv; do not hand-edit.',
           'SET NAMES utf8mb4;',
           'DROP TABLE IF EXISTS `dc_legendary_gem_item`;',
           'CREATE TABLE `dc_legendary_gem_item` (entry INT UNSIGNED PRIMARY KEY, gem_id VARCHAR(32) NOT NULL UNIQUE,'
           ' socket_slots VARCHAR(64) NOT NULL) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;']
    for gem_id, name, entry, slots in rows:
        sql.append(f'INSERT INTO `dc_legendary_gem_item` VALUES ({entry},{quote(gem_id)},{quote(slots)});')
    for gem_id, name, entry, slots in rows:
        # One flat template per gem, never stacking: each item is one gem with its own rank row.
        sql += ['CREATE TEMPORARY TABLE dc_legendary_gem_template LIKE item_template;',
                f'INSERT INTO dc_legendary_gem_template SELECT * FROM item_template WHERE entry={DONOR};',
                f'UPDATE dc_legendary_gem_template SET entry={entry},name={quote(name)},class=7,subclass=4,'
                f'Quality={QUALITY_LEGENDARY},Flags={FLAG_BOUND_TO_ACCOUNT},FlagsExtra=0,'
                f'ItemLevel={tunable_integer("crafting", "gem_item_level", minimum=1)},'
                f'RequiredLevel={tunable_integer("crafting", "gem_required_level")},bonding=0,stackable=1,'
                f'BuyPrice={price},SellPrice={sell},GemProperties=0,{zero_stats},'
                f'spellid_1=0,spellid_2=0,spellid_3=0,spellid_4=0,spellid_5=0,description={quote(flavour[gem_id])};',
                'REPLACE INTO item_template SELECT * FROM dc_legendary_gem_template;',
                'DROP TEMPORARY TABLE dc_legendary_gem_template;']
    return '\n'.join(sql) + '\n'


def characters_sql():
    sql = ['-- Generated by generate_legendary_gem_items.py: a legendary gem item\'s own rank, by item guid, and'
           ' the rank a socketed one carries. Not dc_item_affix.gem_rank, which is a normal gem\'s tier.',
           'CREATE TABLE IF NOT EXISTS `dc_legendary_gem_rank` (item_guid BIGINT UNSIGNED NOT NULL PRIMARY KEY,'
           ' gem_rank INT UNSIGNED NOT NULL DEFAULT 0) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;']
    sql += ensure_column('dc_item_affix', 'legendary_rank', 'INT UNSIGNED NULL')
    return '\n'.join(sql) + '\n'


def generate(module=MODULE):
    rows = items(module)
    world, characters = world_sql(rows, module), characters_sql()
    (module / 'data/generated/legendary_gems_0002_items.sql').write_text(world, encoding='utf-8', newline='\n')
    (module / 'data/generated/legendary_gems_0001_rank.sql').write_text(characters, encoding='utf-8', newline='\n')
    write_migration(module, module / 'data/sql/db-world/updates/legendary_gems_0002_items.sql', world)
    write_migration(module, module / 'data/sql/db-characters/updates/legendary_gems_0001_rank.sql', characters)


if __name__ == '__main__':
    import argparse
    argparse.ArgumentParser(description=__doc__).parse_args()
    generate()
