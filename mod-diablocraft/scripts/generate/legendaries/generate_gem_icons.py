#!/usr/bin/env python3
"""Gem icons (diablocraft-fpo9l): each gem item wears its own icon from the designer's art.

Reads data/gem_icons.csv (item_entry, display_id, icon; display ids are append-only project identities, like
the item entries) and writes:

  world   legendary_gems_0005_gem_icons.sql   item_template.displayid of the 50 stat gems and the 21 legendary gems
  client  ItemDisplayInfo.dbc           one row per display: InventoryIcon = the icon, no model
          Item.dbc                      the same displayid on the item's own row, which is where the 3.3.5a
                                        client takes the bag icon from (client-patch/dbc/README.md)

The icons are client-patch/art/Interface/Icons/<icon>.blp, made by client-patch/source/gems/draw_gem_icons.py.
The server needs no display row: it checks a template's displayid only against its own Item.dbc, which holds
none of our entries. The base generators still clone a donor gem's look (generate_crafting.py `visuals`,
generate_legendary_gem_items.py DONOR); this migration is what overrides it, so its name sorts after theirs: the
core applies a database's updates in filename order, and a fresh database replays them all.
"""
import csv
from pathlib import Path

import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
import scripts_path  # noqa: E402,F401  (R5: every scripts/ folder on sys.path)
from applied_migrations import write_coupled_outputs, write_migration
from dbc_store import Store, schema

MODULE = Path(__file__).resolve().parents[3]
ROOT = MODULE.parent
CLIENT = ROOT / 'client-patch/dbc'
ICONS = ROOT / 'client-patch/art/Interface/Icons'
MIGRATION = MODULE / 'data/sql/db-world/updates/legendary_gems_0005_gem_icons.sql'
DISPLAY_FIRST = 90100   # after the wings' 90000; stock ItemDisplayInfo ends at 68742


def read(name):
    with (MODULE / 'data' / name).open(encoding='utf-8', newline='') as stream:
        return list(csv.DictReader(stream, strict=True))


def rows(module=MODULE):
    """[(entry, display, icon)], checked against every gem item there is."""
    out = [(int(r['item_entry']), int(r['display_id']), r['icon']) for r in read('gem_icons.csv')]
    gems = {int(r['item_entry']) for name in ('gem_items.csv', 'legendary_gem_items.csv') for r in read(name)}
    if {entry for entry, _, _ in out} != gems or len(out) != len(gems):
        raise ValueError('gem_icons.csv must list every gem item of gem_items.csv and legendary_gem_items.csv once')
    displays, icons = [d for _, d, _ in out], [i for _, _, i in out]
    if len(set(displays)) != len(displays) or min(displays) < DISPLAY_FIRST or len(set(icons)) != len(icons):
        raise ValueError(f'gem_icons.csv: display ids and icons must be unique, display ids from {DISPLAY_FIRST}')
    missing = [icon for icon in icons if not (ICONS / f'{icon}.blp').is_file()]
    if missing:
        raise ValueError(f'no icon in {ICONS.relative_to(ROOT)} for {missing}; run draw_gem_icons.py')
    return sorted(out)


def world_sql(gems):
    return '\n'.join(['-- Generated by generate_gem_icons.py from gem_icons.csv; do not hand-edit.']
                     + [f'UPDATE `item_template` SET `displayid`={display} WHERE `entry`={entry};'
                        for entry, display, _ in gems]) + '\n'


def client_dbcs(gems):
    """(Item.dbc, ItemDisplayInfo.dbc) bytes: ours replaced where they sit, a new one appended."""
    displays = Store((CLIENT / 'ItemDisplayInfo.dbc').read_bytes(), schema(ROOT, 'itemdisplayinfo_dbc'))
    items = Store((CLIENT / 'Item.dbc').read_bytes(), schema(ROOT, 'item_dbc'))
    blank = {name: '' if kind in ('varchar', 'text') else 0 for name, kind, _ in displays.columns}
    for entry, display, icon in gems:
        if display in displays.rows and not displays.decode(display)['InventoryIcon_1'].startswith('DC_Gem_'):
            raise ValueError(f'display {display} already belongs to another record')
        displays.encode({**blank, 'ID': display, 'InventoryIcon_1': icon})
        if entry not in items.rows:
            raise ValueError(f'item {entry} has no Item.dbc row (client-patch/dbc/build_item.py appends it)')
        items.encode({**items.decode(entry), 'DisplayInfoID': display})
    return items.bytes(), displays.bytes()


def generate():
    gems = rows()
    sql = world_sql(gems)
    item_dbc, display_dbc = client_dbcs(gems)
    write_migration(MODULE, MIGRATION, sql)
    write_coupled_outputs(MODULE, MIGRATION, sql, [(CLIENT / 'Item.dbc', item_dbc),
                                                   (CLIENT / 'ItemDisplayInfo.dbc', display_dbc)],
                          label='gem icon client rows')


if __name__ == '__main__':
    import argparse
    argparse.ArgumentParser(description=__doc__).parse_args()
    generate()
