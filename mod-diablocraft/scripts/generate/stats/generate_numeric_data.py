#!/usr/bin/env python3
"""Emit numeric common-stat rules transcribed into the verified source CSVs."""
import csv
import math
from pathlib import Path

import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
import scripts_path  # noqa: E402,F401  (R5: every scripts/ folder on sys.path)
from applied_migrations import write_migration

MODULE = Path(__file__).resolve().parents[3]
# Explicit source cells, never parse gameplay numbers out of prose at runtime.
CELLS = {
    'fury_from_damage_per_life_pct': ('barbarian_fury', 'metric', 'Fury from taking damage', 'fury_per_life_pct'),
    'deaths_breath_min_monster_level': ('difficulty_tiers', 'tier', 'Normal', 'deaths_breath_min_monster_level'),
    'mystic_offer_count': ('mystic', 'rule', 'enchant_result_options', 'numeric_count'),
    'mystic_jewelry_gem_count': ('mystic', 'rule', 'enchant_cost_legendary_set_jewelry', 'numeric_count'),
    'jeweler_unsocket_gold': ('jeweler', 'operation_id', 'unsocket_current', 'gold'),
    'crit_chance_pct': ('stats', 'stat', 'Crit Chance', 'base_pct'),
    'crit_damage_pct': ('stats', 'stat', 'Crit Damage', 'base_pct'),
    'attack_speed_cap': ('stats', 'stat', 'Attack Speed', 'cap_numeric'),
    'movement_cap_pct': ('stats', 'stat', 'Movement Speed', 'cap_numeric'),
    'magic_find_cap_pct': ('stats', 'stat', 'Magic Find', 'cap_numeric'),
    'gold_find_cap_pct': ('stats', 'stat', 'Gold Find', 'cap_numeric'),
    'xp_penalty_level': ('stats', 'stat', 'XP bonus', 'xp_penalty_level'),
    'xp_divisor': ('stats', 'stat', 'XP bonus', 'xp_divisor'),
    'all_res_per_int': ('class_primary_stats', 'class', 'Barbarian', 'all_res_per_int'),
    'class_dr_pct': ('class_primary_stats', 'class', 'Barbarian', 'innate_dr_pct'),
    'armor_level_coefficient': ('mitigation', 'mitigation_type', 'Armor Damage Reduction', 'level_coefficient'),
    'resistance_level_coefficient': ('mitigation', 'mitigation_type', 'Resistance Damage Reduction', 'level_coefficient'),
}


# Historical SQL provenance is a display label, never a lookup key. Retaining
# it avoids rewriting applied numeric history for this selector-only change
# (Architect, 2026-09-20, contract-numbers-out-of-prose).
SOURCE_LABELS = {'jeweler_unsocket_gold': 'Remove gem (non-destroying)'}


def render(module=MODULE):
    values = []
    for name, (file, key, identity, column) in CELLS.items():
        with (module / f'data/d3/{file}.csv').open(newline='', encoding='utf-8') as stream:
            matches = [row for row in csv.DictReader(stream) if row[key] == identity]
        if len(matches) != 1:
            raise ValueError(f'{file}/{identity}: expected one source row')
        text = matches[0][column]
        if not text or not math.isfinite(float(text)) or float(text) < 0:
            raise ValueError(f'{file}/{identity}/{column}: missing or invalid numeric source')
        label = SOURCE_LABELS.get(name, identity)
        values.append(f"('{name}',{text},'{file}.csv/{label}/{column}')")
    return ("-- Generated by generate_numeric_data.py; sourced D3 rules, not tunables.\n"
            "CREATE TABLE IF NOT EXISTS dc_numeric_rule (name VARCHAR(64) PRIMARY KEY, value DOUBLE NOT NULL, source VARCHAR(255) NOT NULL);\n"
            "REPLACE INTO dc_numeric_rule (name,value,source) VALUES\n" + ',\n'.join(values) + ';\n')


def generate(module=MODULE):
    sql = render(module)
    (module / 'data/generated/numeric_rules_0001.sql').write_text(sql, encoding='utf-8')
    write_migration(module, module / 'data/sql/db-world/updates/numeric_rules_0001.sql', sql)


if __name__ == '__main__':
    import argparse
    argparse.ArgumentParser(description=__doc__).parse_args()
    generate()
