#!/usr/bin/env python3
"""Each roster monster's D3 type, for the stats that read a creature's type: CSV -> monster_types_0001_d3_types.sql.

    python3 mod-diablocraft/scripts/generate/stats/generate_monster_types.py

D3's damage-to-type stats (damage_humans; docs/contracts/legendary-powers.md) ask what D3 calls a monster. The answer is
the `monster_type` column of data/d3/gr_monster_progress.csv, reached through the roster's warpath_name, the same road the
rift progress points take (generate_spawn_sheets.py). A roster monster whose warpath_name is `none`, or that is held back
with no creature entry, has no row, and a monster with no row gets no bonus until its row is filled. Only the Human rows are
read by the game today; Beasts, Demons and Undead read the creature template's own type.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
import scripts_path  # noqa: E402,F401  (R5: every scripts/ folder on sys.path)
from applied_migrations import write_coupled_outputs, write_migration  # noqa: E402
import generate_spawn_sheets as sheets  # noqa: E402

MODULE = Path(__file__).resolve().parents[3]
NAME = "monster_types_0001_d3_types.sql"


def check_types(roster, rows):
    """[{monster, entry, d3_type}] for every roster monster with a creature entry and a row in the progress sheet."""
    types = {r["name"]: r["monster_type"].strip() for r in rows}
    out = []
    for m in roster:
        name = m["warpath_name"]
        if name == "none" or m["entry"] is None:
            continue
        if name not in types:
            raise sheets.DataError(f"{m['monster']}: warpath_name {name!r} is not in gr_monster_progress.csv")
        if not types[name]:
            raise sheets.DataError(f"gr_monster_progress.csv {name}: monster_type is empty")
        out.append(dict(monster=m["monster"], entry=m["entry"], d3_type=types[name]))
    return out


def render(data):
    rows = ",\n".join(f"({sheets.literal(r['monster'])}, {r['entry']}, {sheets.literal(r['d3_type'])})" for r in data)
    return "\n".join([
        "-- Generated by generate_monster_types.py from data/d3/gr_monster_progress.csv through the roster's warpath_name; never edit.",
        "-- Each roster monster's D3 type (Human, Beast, Demon, Undead, Reaper...), read by the damage-to-type stats.",
        "SET NAMES utf8mb4;",
        "CREATE TABLE IF NOT EXISTS `dc_monster_d3_type` (`monster` VARCHAR(64) NOT NULL, `entry` INT UNSIGNED NOT NULL, "
        "`d3_type` VARCHAR(32) NOT NULL, PRIMARY KEY (`monster`)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;",
        "DELETE FROM `dc_monster_d3_type`;",
        f"INSERT INTO `dc_monster_d3_type` (`monster`, `entry`, `d3_type`) VALUES\n{rows};",
    ]) + "\n"


def load(roster_path=sheets.ROSTER, progress_path=sheets.PROGRESS):
    return check_types(sheets.read_roster(roster_path), sheets.read_csv(progress_path))


def main():
    sql = render(load())
    target = MODULE / "data/sql/db-world/updates" / NAME
    write_migration(MODULE, target, sql)
    write_coupled_outputs(MODULE, target, sql, [(MODULE / "data/generated" / NAME, sql)], label="monster D3 types")


if __name__ == "__main__":
    import argparse
    argparse.ArgumentParser(description=__doc__).parse_args()
    main()
