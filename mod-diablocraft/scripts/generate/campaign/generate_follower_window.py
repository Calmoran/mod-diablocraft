"""Generate the Follower window's static data: each follower's name, kind, relic slot name and four tiers of two skills.

The window (mod-diablocraft/lua/aio/dc_follower.lua) draws the skills' names, icons and texts without asking the server:
they are fixed by data/d3/followers.csv (the skill rows) and data/d3/followers_roster.csv. Only the picks, the levels the
tiers open at and the follower's sheet travel on the wire (docs/contracts/followers.md, "Messages"). One sheet in, one
Lua table out, a global the window reads when it opens (AIO's file load order is not ours to depend on).

    python3 mod-diablocraft/scripts/generate/campaign/generate_follower_window.py
"""
import csv
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
import scripts_path  # noqa: E402,F401  (R5: every scripts/ folder on sys.path)

MODULE = Path(__file__).resolve().parents[3]
SKILLS = MODULE / "data/d3/followers.csv"
ROSTER = MODULE / "data/d3/followers_roster.csv"
OUTPUT = MODULE / "lua/aio/dc_follower_skills.lua"

# The stock icon (Interface\Icons, a base-client file) each skill wears. Every skill id of the sheet has one.
ICONS = {
    "heal": "spell_nature_rejuvenation", "intervene": "ability_warrior_shieldwall", "loyalty": "spell_holy_devotionaura",
    "intimidate": "ability_warrior_warcry", "charge": "ability_warrior_charge", "onslaught": "ability_warrior_punishingblow",
    "inspire": "spell_holy_divinepurpose", "guardian": "spell_holy_blessingofprotection",
    "crippling-shot": "inv_weapon_bow_07", "powered-shot": "spell_fire_selfdestruct", "hysteria": "ability_ghoulfrenzy",
    "anatomy": "ability_criticalstrike", "piercing-shot": "ability_gouge", "multishot": "ability_rogue_slicedice",
    "vanish": "spell_shadow_antimagicshell", "nights-veil": "spell_shadow_shadowfury",
    "charm": "spell_shadow_soulgem", "temporal-pulse": "spell_arcane_portaldalaran", "amplification": "spell_fire_fireball02",
    "prophetic-harmony": "inv_misc_pocketwatch_01", "powered-shield": "spell_holy_powerwordshield",
    "erosion": "spell_frost_arcticwinds", "focused-mind": "spell_nature_bloodlust", "fates-lapse": "spell_arcane_arcane04",
}
# The stock icon of each follower's portrait square (the window has no model to show).
PORTRAITS = {"templar": "spell_holy_devotionaura", "scoundrel": "inv_weapon_bow_07", "enchantress": "spell_arcane_portaldalaran"}
# The relic slot's name for each follower kind (docs/contracts/followers.md, "Relics").
RELIC_SLOT = {"templar": "Templar Relic", "scoundrel": "Scoundrel Token", "enchantress": "Enchantress Focus"}


class WindowDataError(Exception):
    pass


def lua_string(text):
    out = text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    return '"' + out + '"'


def read():
    """({follower_id: roster row}, {follower_id: {tier: [skill rows in sheet order]}}); the sheet is checked whole."""
    with open(ROSTER, newline="", encoding="utf-8") as handle:
        roster = {int(row["follower_id"]): row for row in csv.DictReader(handle)}
    tiers = {}
    with open(SKILLS, newline="", encoding="utf-8") as handle:
        for row in csv.DictReader(handle):
            if row["kind"] != "skill":
                continue
            follower = int(row["follower_id"])
            if follower not in roster:
                raise WindowDataError(f"skill {row['skill_id']} names follower {follower}, not on the roster")
            if row["skill_id"] not in ICONS:
                raise WindowDataError(f"skill {row['skill_id']} has no icon in ICONS")
            tiers.setdefault(follower, {}).setdefault(int(row["tier"]), []).append(row)
    for follower, by_tier in tiers.items():
        if sorted(by_tier) != [1, 2, 3, 4] or any(len(rows) != 2 for rows in by_tier.values()):
            raise WindowDataError(f"follower {follower} has not four tiers of two skills")
    if set(tiers) != set(roster):
        raise WindowDataError("a follower of the roster has no skills")
    return roster, tiers


def render():
    roster, tiers = read()
    out = ["-- luacheck: globals DCFollowerData",
           "-- Generated by generate_follower_window.py from followers.csv and followers_roster.csv; do not hand-edit.",
           "-- The Follower window's static data: names, kinds, relic slot names, and each tier's two skills with their stock icon and text lines.",
           'local AIO=AIO or require("AIO")', "if AIO.AddAddon() then return end",
           "DCFollowerData={followers={"]
    for follower in sorted(roster):
        row = roster[follower]
        out.append(f"[{follower}]={{key={lua_string(row['key'])},name={lua_string(row['name'])},kind={lua_string(row['subname'])},"
                   f"stat={lua_string(row['main_stat'].capitalize())},relic={lua_string(RELIC_SLOT[row['key']])},"
                   f"portrait={lua_string('Interface' + chr(92) + 'Icons' + chr(92) + PORTRAITS[row['key']])},tiers={{")
        for tier in sorted(tiers[follower]):
            skills = tiers[follower][tier]
            out.append(f"  {{level={int(skills[0]['d3_level'])},skills={{")
            for skill in skills:
                lines = [part.strip() for part in skill["text"].split(" / ")]
                icon = "Interface\\Icons\\" + ICONS[skill["skill_id"]]
                out.append(f"    {{id={lua_string(skill['skill_id'])},name={lua_string(skill['name'])},"
                           f"icon={lua_string(icon)},text={lua_string(chr(10).join(lines))}}},")
            out.append("  }},")
        out.append("}},")
    out.append("}}")
    return "\n".join(out) + "\n"


def main():
    OUTPUT.write_text(render(), encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(MODULE.parent)}")


if __name__ == "__main__":
    main()
