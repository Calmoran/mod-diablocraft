#!/usr/bin/env python3
"""Emit the creature templates of the Shaman's elementals from data/d3/shaman_elemental_summons.csv.

One row a creature a Shaman Primal skill raises for its look: its entry, the stock creature whose row and model it copies and the
ScriptName that gives it its AI. Each is the donor's own row with the module's AI and no loot, gossip or credit, untargetable like the
Wizard's Hydra, the way the other classes' summons are made: the render is generate_spells.py summon_templates, the one function that
builds them, applied to this sheet alone so the older summons' migrations keep their bytes. The elemental deals nothing itself: its
damage is the Shaman's skill damage (src/classes/shaman/dc_shaman_fire_elemental.cpp and dc_shaman_earth_elemental.cpp); the creature
is what the player sees.
"""
import csv
from pathlib import Path

import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
import scripts_path  # noqa: E402,F401  (R5: every scripts/ folder on sys.path)
from applied_migrations import write_migration

MODULE = Path(__file__).resolve().parents[3]
SHEET = 'shaman_elemental_summons.csv'
MIGRATION = 'minions_0007_shaman_elemental_summons.sql'
# The entries already taken by the module's other summons; a new entry never reuses one.
OTHER_SHEETS = ('data/d3/wizard_summons.csv', 'data/d3/monk_summons.csv', 'data/d3/crusader_summons.csv', 'data/legendary_summons.csv',
                'data/d3/necromancer_summons.csv', 'data/d3/demon_hunter_summons.csv', 'data/d3/witch_doctor_summons.csv',
                'data/d3/witch_doctor_hex_summons.csv', 'data/d3/witch_doctor_body_summons.csv')
ANCIENTS = range(900100, 900103)
# The Shaman's totems hold 900180 to 900189 (shaman_summons.csv).
TOTEMS = range(900180, 900190)
NOT_SELECTABLE = 0x02000000  # UNIT_FLAG_NOT_SELECTABLE


def read(module, name):
    with (module / name).open(encoding='utf-8', newline='') as stream:
        return list(csv.DictReader(stream, strict=True))


def rows(module=MODULE):
    taken = set(ANCIENTS) | set(TOTEMS) | {int(r['entry']) for n in OTHER_SHEETS for r in read(module, n)}
    out = []
    for r in read(module, f'data/d3/{SHEET}'):
        where = f"{SHEET} {r['summon']}"
        entry = int(r['entry'])
        if entry in taken:
            raise ValueError(f'{where}: entry {entry} is taken')
        taken.add(entry)
        if r['script'] != 'dc_minion':
            raise ValueError(f'{where}: script is dc_minion')
        if not r['why']:
            raise ValueError(f'{where}: needs its reason')
        out.append(r)
    return out


def render(module=MODULE):
    import generate_spells
    rows(module)  # the checks
    text = generate_spells.summon_templates(SHEET)
    # The look is no target: untargetable, as the Hydra and the totems are.
    return (f"-- Generated by generate_shaman_elemental_summons.py from {SHEET}; do not hand-edit.\n"
            + text.replace(",unit_flags=0,unit_flags2=0,", f",unit_flags={NOT_SELECTABLE},unit_flags2=0,"))


def generate(module=MODULE):
    write_migration(module, module / 'data/sql/db-world/updates' / MIGRATION, render(module))


if __name__ == '__main__':
    import argparse
    argparse.ArgumentParser(description=__doc__).parse_args()
    generate()
