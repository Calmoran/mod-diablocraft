#!/usr/bin/env python3
"""Stock spells Torment switches off, through the core's own disable registry (diablocraft-hcwjv, diablocraft-r0d0h).

    python3 mod-diablocraft/scripts/generate/classes/generate_stock_spells_off.py            # data/d3/stock_spells_off.csv -> world_0086_stock_spells_off.sql
    python3 mod-diablocraft/scripts/generate/classes/generate_stock_spells_off.py --shaman   # first rewrite the sheet's Shaman rows from the client DBCs

One `disables` row per sheet row: sourceType 0 (spell). A row with a `map_id` is off on that map for players and creatures:
flags player + creature + map, params_0 the map. Player covers a self-cast trap aura (GameObject::CastSpell lets the target
cast it), creature the world trigger a trap summons otherwise (DisableMgr::IsDisabledFor checks the caster unit). A row with a
blank `map_id` is off for players on every map and still works for creatures (a Shaman monster casts its stock spells): flags
player only. The sheet is the source; the Shaman's rows (every stock spell of its three class skill lines, Ghost Wolf kept) are
derived from SkillLineAbility.dbc and Spell.dbc by `--shaman`, and a test re-derives them to catch drift.

world_0041_stock_spells_off.sql (the Magtheridon trap row) is applied and stays as it was; the newest migration is the whole sheet.
"""
import csv
import struct
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
import scripts_path  # noqa: E402,F401  (R5: every scripts/ folder on sys.path)
from applied_migrations import write_coupled_outputs, write_migration  # noqa: E402

MODULE = Path(__file__).resolve().parents[3]
SHEET = MODULE / "data/d3/stock_spells_off.csv"
NAME = "world_0086_stock_spells_off.sql"
# DisableMgr.h: DISABLE_TYPE_SPELL; SPELL_DISABLE_PLAYER | SPELL_DISABLE_CREATURE | SPELL_DISABLE_MAP. Identities, not game numbers.
SOURCE_SPELL = 0
FLAGS = 0x1 | 0x2 | 0x10
FLAGS_EVERYWHERE = 0x1
# The Shaman's stock spells (diablocraft-r0d0h, brief shaman-build-2026-10-22 step 1a): the abilities of the three class skill
# lines of SkillLine.dbc (373 Enhancement, 374 Restoration, 375 Elemental Combat, 573 Restoration), which is what the trainers and
# the talent trees teach, ranks and totem spells included. Weapon and armor proficiencies sit in other skill lines and stay. The
# native totem slots are summon properties, not spells, and stay for our totems; Ghost Wolf is the one stock form our skill of that
# name keeps wearing. Identities, not game numbers.
SHAMAN_SKILL_LINES = (373, 374, 375, 573)
SHAMAN_KEPT = {2645: "Ghost Wolf"}
SHAMAN_SOURCE = "diablocraft-r0d0h (brief shaman-build-2026-10-22, 1a): a stock Shaman spell (skill line %d), off for players on every map"
DBC = MODULE.parent / "azerothcore-wotlk/build/server/data/dbc"
SPELL_NAME_FIELD = 136   # Spell.dbc Name_Lang_enUS (generate_spells.py F_NAME_ENUS)


def read_sheet(path=SHEET):
    with Path(path).open(encoding="utf-8-sig", newline="") as stream:
        rows = list(csv.DictReader(stream, strict=True))
    for row in rows:
        int(row["spell"])
        if row["map_id"].strip():
            int(row["map_id"])
        if not row["source"].strip():
            raise ValueError(f"spell {row['spell']} has no source")
    return rows


def flags_of(row):
    return FLAGS if row["map_id"].strip() else FLAGS_EVERYWHERE


def where(row):
    return f"on map {row['map_id']}" if row["map_id"].strip() else "for players"


def render(rows):
    ids = ", ".join(r["spell"] for r in rows)
    values = ",\n".join(f"  ({SOURCE_SPELL}, {r['spell']}, {flags_of(r)}, '{r['map_id']}', '', 'Torment: {r['name'].replace(chr(39), chr(39) * 2)} off "
                        f"{where(r)} (stock_spells_off.csv)')" for r in rows)
    return "\n".join([
        "-- Generated by generate_stock_spells_off.py from data/d3/stock_spells_off.csv (diablocraft-hcwjv, diablocraft-r0d0h); never edit.",
        "-- Stock spells switched off through the core's disable registry: on one map for players and creatures, or for players on every map.",
        f"DELETE FROM `disables` WHERE `sourceType` = {SOURCE_SPELL} AND `entry` IN ({ids});",
        f"INSERT INTO `disables` (`sourceType`, `entry`, `flags`, `params_0`, `params_1`, `comment`) VALUES\n{values};",
        "",
    ])


def read_dbc(name, directory=DBC):
    """(records as tuples of unsigned words, string block, fields) of a stock client DBC."""
    raw = (Path(directory) / name).read_bytes()
    magic, count, fields, size, _strings = struct.unpack_from("<4s4I", raw)
    if magic != b"WDBC" or size != fields * 4:
        raise ValueError(f"{name}: not a WDBC file of 4-byte fields")
    records = [struct.unpack_from(f"<{fields}I", raw, 20 + n * size) for n in range(count)]
    return records, raw[20 + count * size:]


def stock_shaman_spells(directory=DBC):
    """[(spell id, name, skill line)] of every stock Shaman spell (SHAMAN_SKILL_LINES), SHAMAN_KEPT left out, by spell id."""
    abilities, _ = read_dbc("SkillLineAbility.dbc", directory)
    spells, strings = read_dbc("Spell.dbc", directory)
    names = {r[0]: strings[r[SPELL_NAME_FIELD]:strings.index(0, r[SPELL_NAME_FIELD])].decode("utf-8") for r in spells}
    found = {}
    for record in abilities:
        line, spell = record[1], record[2]
        if line in SHAMAN_SKILL_LINES and spell not in SHAMAN_KEPT:
            if spell in names:   # the stock table lists ids Spell.dbc lacks (30810): the core refuses a disable of those
                found.setdefault(spell, line)
    return [(spell, names[spell], line) for spell, line in sorted(found.items())]


def shaman_rows(directory=DBC):
    return [{"spell": str(spell), "name": name, "map_id": "", "source": SHAMAN_SOURCE % line}
            for spell, name, line in stock_shaman_spells(directory)]


def write_shaman_rows(directory=DBC):
    """Replace the sheet's Shaman rows (their source starts as SHAMAN_SOURCE does) by the derived ones, the other rows kept in place."""
    rows = [r for r in read_sheet() if not r["source"].startswith(SHAMAN_SOURCE.split("%")[0])] + shaman_rows(directory)
    with SHEET.open("w", encoding="utf-8", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=["spell", "name", "map_id", "source"], lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)


def generate():
    sql = render(read_sheet())
    target = MODULE / "data/sql/db-world/updates" / NAME
    write_migration(MODULE, target, sql)
    write_coupled_outputs(MODULE, target, sql, [(MODULE / "data/generated/stock_spells_off.sql", sql)], label="stock spells off")
    print(f"Generated {NAME}")


if __name__ == "__main__":
    if "--shaman" in sys.argv[1:]:
        write_shaman_rows()
    generate()
