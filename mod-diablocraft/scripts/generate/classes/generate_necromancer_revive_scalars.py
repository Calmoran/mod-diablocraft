#!/usr/bin/env python3
"""The attack scalar of each roster monster that can be revived: the sheets -> necromancer_revive_0001_scalars.sql.

    python3 mod-diablocraft/scripts/generate/classes/generate_necromancer_revive_scalars.py

Revive lets a revived monster keep its own attack, scaled by D3's Damage Scalar of that attack (decisions.md 2026-10-21,
q-1021-36 option b). data/d3/necromancer_revive_attacks.csv holds the scalar of every `p6_Necro_Revive_*` attack power (decoded
by generate_necromancer_revive_attacks.py); data/d3/necromancer_revive_monsters.csv says which attack is which roster
monster's. A roster monster with no row revives at the base scalar of 1 (Revive's Revived Monster Damage Scalar), as 34 of
D3's 51 attacks are 1.0. The game reads the table by the creature's entry (dc_revive_scalar).
"""
import csv
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
MODULE = HERE.parents[2]
sys.path.insert(0, str(HERE.parents[1]))
import scripts_path  # noqa: E402,F401  (R5: every scripts/ folder on sys.path)
from applied_migrations import write_coupled_outputs, write_migration  # noqa: E402
import generate_spawn_sheets as sheets  # noqa: E402

NAME = "necromancer_revive_0001_scalars.sql"


def read(name):
    with (MODULE / "data/d3" / name).open(encoding="utf-8", newline="") as stream:
        return list(csv.DictReader(stream, strict=True))


def rows(roster=None, attacks=None, monsters=None):
    roster = sheets.read_roster() if roster is None else roster
    scalars = {r["power"]: r["damage_scalar"] for r in (read("necromancer_revive_attacks.csv") if attacks is None else attacks)}
    by_name = {m["monster"]: m for m in roster}
    out, seen = [], set()
    for row in (read("necromancer_revive_monsters.csv") if monsters is None else monsters):
        where = f"necromancer_revive_monsters.csv {row['monster']}"
        monster = by_name.get(row["monster"])
        if monster is None or monster["entry"] is None:
            raise ValueError(f"{where}: not a roster monster with a creature entry")
        if row["monster"] in seen:
            raise ValueError(f"{where}: twice")
        seen.add(row["monster"])
        if not scalars.get(row["power"]):
            raise ValueError(f"{where}: {row['power']} has no Damage Scalar in necromancer_revive_attacks.csv")
        if not row["why"]:
            raise ValueError(f"{where}: needs its reason")
        out.append(dict(entry=monster["entry"], monster=row["monster"], power=row["power"], scalar=float(scalars[row["power"]])))
    return out


def render(data=None):
    data = rows() if data is None else data
    values = ",\n".join(f"({r['entry']}, {sheets.literal(r['monster'])}, {sheets.literal(r['power'])}, {r['scalar']:g})" for r in data)
    return "\n".join([
        "-- Generated by generate_necromancer_revive_scalars.py from necromancer_revive_attacks.csv and necromancer_revive_monsters.csv; never edit.",
        "-- The attack scalar of each roster monster a Necromancer can revive; a monster with no row is revived at a scalar of 1.",
        "SET NAMES utf8mb4;",
        "CREATE TABLE IF NOT EXISTS `dc_revive_scalar` (`entry` INT UNSIGNED NOT NULL, `monster` VARCHAR(64) NOT NULL, "
        "`power` VARCHAR(96) NOT NULL, `scalar` DOUBLE NOT NULL, PRIMARY KEY (`entry`)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;",
        "DELETE FROM `dc_revive_scalar`;",
        f"INSERT INTO `dc_revive_scalar` (`entry`, `monster`, `power`, `scalar`) VALUES\n{values};",
    ]) + "\n"


def main():
    sql = render()
    target = MODULE / "data/sql/db-world/updates" / NAME
    write_migration(MODULE, target, sql)
    write_coupled_outputs(MODULE, target, sql, [(MODULE / "data/generated" / NAME, sql)], label="revive scalars")


if __name__ == "__main__":
    import argparse
    argparse.ArgumentParser(description=__doc__).parse_args()
    main()
