#!/usr/bin/env python3
"""Emit the creature templates of the Witch Doctor's pets from data/d3/witch_doctor_summons.csv (diablocraft-vxrcu.7) and the Fetish
Shaman Hex summons from data/d3/witch_doctor_hex_summons.csv and the Fetish body Spirit Walk leaves behind from
data/d3/witch_doctor_body_summons.csv (one migration each, the first left as it was applied).

One row a creature a Witch Doctor skill or passive raises: its entry, the donor creature whose row and model it copies, and the ScriptName
that gives it its AI. Each is the donor's own row with the module's AI and no loot, gossip or credit, the way the Wizard's and
the Monk's summons are made: the render is generate_spells.py summon_templates, the one function that builds them, applied
to this sheet alone so the older summons' migrations keep their bytes. Life, level, faction, owner and lifetime are set when
the minion is raised, from the Witch Doctor (combat/dc_minions.cpp).
"""
import csv
from pathlib import Path

import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
import scripts_path  # noqa: E402,F401  (R5: every scripts/ folder on sys.path)
from applied_migrations import write_migration

MODULE = Path(__file__).resolve().parents[3]
SHEET = 'witch_doctor_summons.csv'
MIGRATION = 'minions_0003_witch_doctor_summons.sql'
HEX_SHEET = 'witch_doctor_hex_summons.csv'
HEX_MIGRATION = 'minions_0004_witch_doctor_hex_summons.sql'
BODY_SHEET = 'witch_doctor_body_summons.csv'
BODY_MIGRATION = 'minions_0005_witch_doctor_body_summons.sql'
SHEETS = ((SHEET, MIGRATION), (HEX_SHEET, HEX_MIGRATION), (BODY_SHEET, BODY_MIGRATION))
# The entries already taken by the module's other summons; a new entry never reuses one.
OTHER_SHEETS = ('data/d3/wizard_summons.csv', 'data/d3/monk_summons.csv', 'data/d3/crusader_summons.csv', 'data/legendary_summons.csv', 'data/d3/necromancer_summons.csv')
ANCIENTS = range(900100, 900103)


def read(module, name):
    with (module / name).open(encoding='utf-8', newline='') as stream:
        return list(csv.DictReader(stream, strict=True))


def rows(module=MODULE, sheet=SHEET):
    taken = set(ANCIENTS) | {int(r['entry']) for n in OTHER_SHEETS for r in read(module, n)}
    # the Witch Doctor's other sheet holds its own entries
    taken |= {int(r['entry']) for other, _m in SHEETS if other != sheet for r in read(module, f'data/d3/{other}')}
    out = []
    for r in read(module, f'data/d3/{sheet}'):
        where = f"{sheet} {r['summon']}"
        entry = int(r['entry'])
        if entry in taken:
            raise ValueError(f'{where}: entry {entry} is taken')
        taken.add(entry)
        if r['script'] != 'dc_minion':
            raise ValueError(f'{where}: script is dc_minion')
        if not r['why']:
            raise ValueError(f'{where}: needs its reason')
        out.append(r)
    return out


def render(module=MODULE, sheet=SHEET):
    import generate_spells
    rows(module, sheet)  # the checks
    return (f"-- Generated by generate_witch_doctor_summons.py from {sheet}; do not hand-edit.\n"
            + generate_spells.summon_templates(sheet))


def generate(module=MODULE):
    for sheet, migration in SHEETS:
        write_migration(module, module / 'data/sql/db-world/updates' / migration, render(module, sheet))


if __name__ == '__main__':
    import argparse
    argparse.ArgumentParser(description=__doc__).parse_args()
    generate()
