#!/usr/bin/env python3
"""Emit the numbers of the follower skills: followers_skill_numbers.csv -> dc_follower_skill_value.

The skills themselves (tier, D3 level, cooldown) are followers.csv's rows, written by generate_follower_gear.py as dc_follower_skill.
This sheet holds what the skills do: one row per number, `value` the number at no main stat and `value_max` the number at the
main stat cap (blank when the number does not scale), a row with no follower and no skill a rule every skill shares. Each row names
its source (a power file and its SF, the planner's text, the 2.7.0 notes) or says it is a placeholder.

followers_0010_skill_values.sql (world): dc_follower_skill_value. src/classes/follower/dc_follower_skills.cpp reads it at startup.
followers_0003_character_skill.sql (characters) is a schema migration and is hand-written: dc_character_follower_skill.
"""
import csv
import math
from pathlib import Path

import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
import scripts_path  # noqa: E402,F401  (R5: every scripts/ folder on sys.path)
from applied_migrations import write_migration, write_coupled_outputs
import generate_follower_gear as gear

MODULE = Path(__file__).resolve().parents[3]
MIGRATION = 'followers_0010_skill_values.sql'
# The widths of dc_follower_skill_value's text columns. The unit was 32 and the Enchantress' 'percent of weapon damage, Arcane' is 33, so
# followers_0010 widens it to 64 (an ALTER, since the table exists) and a value that does not fit stops the generator.
SKILL_WIDTH, TOKEN_WIDTH, UNIT_WIDTH = 32, 40, 64
COLUMNS = ('follower_id', 'key', 'skill_id', 'token', 'value', 'value_max', 'unit', 'source')


def number(text, where, what):
    value = float(text)
    if not math.isfinite(value):
        raise ValueError(f'{where}: {what} is a finite number')
    return value


def fits(row, where):
    """Refuses a row whose text does not fit the table's column: the unit that did not (33 in 32) stopped the world server."""
    for column, width in (('skill_id', SKILL_WIDTH), ('token', TOKEN_WIDTH), ('unit', UNIT_WIDTH)):
        if len(row[column]) > width:
            raise ValueError(f'{where}: {column} is {len(row[column])} characters and the column holds {width}')


def values(module=MODULE):
    """followers_skill_numbers.csv, checked against followers.csv: [(follower id, skill id, token, value, value max or None, unit)]."""
    followers = gear.roster(module)
    skills, _relics = gear.sheet(module)
    known = {(s['key'], s['skill']) for s in skills}
    out, seen = [], set()
    with (module / 'data/d3/followers_skill_numbers.csv').open(encoding='utf-8-sig', newline='') as stream:
        reader = csv.DictReader(stream, strict=True)
        if tuple(reader.fieldnames) != COLUMNS:
            raise ValueError('followers_skill_numbers.csv: the columns are ' + ', '.join(COLUMNS))
        rows = list(reader)
    for row in rows:
        where = f"followers_skill_numbers.csv {row['key']} {row['skill_id']} {row['token']}"
        if not row['source'].strip() or not row['unit'].strip() or not row['token'].strip():
            raise ValueError(f'{where}: token, unit and source are required')
        if row['key'] == '' and row['skill_id'] == '' and row['follower_id'] == '0':
            follower_id, skill = 0, ''
        else:
            follower = followers.get(row['key'])
            if not follower or row['follower_id'] != str(follower['id']):
                raise ValueError(f'{where}: follower_id does not match followers_roster.csv')
            if (row['key'], row['skill_id']) not in known:
                raise ValueError(f'{where}: no such skill in followers.csv')
            follower_id, skill = follower['id'], row['skill_id']
        if (follower_id, skill, row['token']) in seen:
            raise ValueError(f'{where}: repeated')
        seen.add((follower_id, skill, row['token']))
        fits(row, where)
        low = number(row['value'], where, 'value')
        high = number(row['value_max'], where, 'value_max') if row['value_max'] != '' else None
        if high is not None and high < low:
            raise ValueError(f'{where}: value_max is not below value')
        out.append((follower_id, skill, row['token'], low, high, row['unit']))
    return out


def render(module=MODULE):
    rows = values(module)
    text = ['-- Generated by generate_follower_skills.py from followers_skill_numbers.csv; do not hand-edit.',
            'SET NAMES utf8mb4;',
            f'CREATE TABLE IF NOT EXISTS dc_follower_skill_value (follower_id TINYINT UNSIGNED NOT NULL, skill_id VARCHAR({SKILL_WIDTH}) NOT NULL, '
            f'token VARCHAR({TOKEN_WIDTH}) NOT NULL, value DOUBLE NOT NULL, value_max DOUBLE NULL, unit VARCHAR({UNIT_WIDTH}) NOT NULL, '
            'PRIMARY KEY (follower_id, skill_id, token)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;',
            # The table exists from followers_0008 and 0009 with a 32 character unit, and CREATE IF NOT EXISTS leaves it so.
            f'ALTER TABLE dc_follower_skill_value MODIFY unit VARCHAR({UNIT_WIDTH}) NOT NULL;',
            'DELETE FROM dc_follower_skill_value;',
            'INSERT INTO dc_follower_skill_value (follower_id, skill_id, token, value, value_max, unit) VALUES\n'
            + ',\n'.join(f"({f},{gear.quote(s)},{gear.quote(t)},{format(v, '.15g')},"
                         f"{'NULL' if m is None else format(m, '.15g')},{gear.quote(u)})" for f, s, t, v, m, u in rows) + ';']
    return '\n'.join(text) + '\n'


def generate(module=MODULE):
    text = render(module)
    target = module / 'data/sql/db-world/updates' / MIGRATION
    write_migration(module, target, text)
    write_coupled_outputs(module, target, text, [(module / 'data/generated' / MIGRATION, text)], label='Follower skill values')
    print('Generated follower skill values')


if __name__ == '__main__':
    import argparse
    argparse.ArgumentParser(description=__doc__).parse_args()
    generate()
