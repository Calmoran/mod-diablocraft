#!/usr/bin/env python3
"""Emit src/combat/dc_healing_table.h from data/d3/healing_table.csv (diablocraft-im7mr.24).

D3's power files scale their heals with the level: `0.0014 * Table(Healing, Effective_Level)` (Leech's Osmosis, P6_Necro_Leech SF_1). The
table is the power formulas' "Healing" table (GameBalance/PowerFormulaTables.gam), one value for each level 0 to 70; the sheet holds it
(read with scripts/decode_pow.py table Healing) and this writes it as a constant the server reads. A level past the last row reads the last
row. Run from anywhere:

    python mod-diablocraft/scripts/generate/classes/generate_healing_table.py
"""
import csv
from pathlib import Path

MODULE = Path(__file__).resolve().parents[3]
SHEET = MODULE / 'data/d3/healing_table.csv'
HEADER = MODULE / 'src/combat/dc_healing_table.h'


def read(module=MODULE):
    with (module / 'data/d3/healing_table.csv').open(encoding='utf-8-sig', newline='') as stream:
        rows = list(csv.DictReader(stream, strict=True))
    if [int(r['level']) for r in rows] != list(range(len(rows))):
        raise ValueError('healing_table.csv: the levels run 0, 1, 2 ... with none missing')
    values = [float(r['value']) for r in rows]
    if len(values) < 2 or values[0] <= 0 or any(b < a for a, b in zip(values[1:], values[2:])):
        raise ValueError('healing_table.csv: the values are positive and never fall from level 1 on')
    return values


def render(module=MODULE):
    values = read(module)
    body = ',\n'.join('    ' + ', '.join(f'{v:g}' for v in values[i:i + 10]) for i in range(0, len(values), 10))
    return ('// Generated by generate_healing_table.py from healing_table.csv; do not hand-edit.\n'
            '#pragma once\n\n'
            '#include <algorithm>\n#include <cstddef>\n\n'
            '// D3\'s Healing table of the power formulas: what a heal scaled by level is worth at each level, 0 to the last row.\n'
            'namespace DC::Combat::Healing\n{\n'
            f'inline constexpr double Table[{len(values)}] = {{\n{body}}};\n\n'
            '// The table at `level`; a level past the last row reads the last.\n'
            'inline double At(unsigned level)\n{\n'
            '    return Table[std::min<std::size_t>(level, sizeof(Table) / sizeof(Table[0]) - 1)];\n}\n'
            '} // namespace DC::Combat::Healing\n')


def generate(module=MODULE):
    (module / 'src/combat/dc_healing_table.h').write_text(render(module), encoding='utf-8', newline='\n')


if __name__ == '__main__':
    import argparse
    argparse.ArgumentParser(description=__doc__).parse_args()
    generate()
