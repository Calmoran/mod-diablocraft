#!/usr/bin/env python3
"""Emit the creature templates of the Shaman's totems from data/d3/shaman_summons.csv.

One row a totem slot (fire, earth, water, air): its entry, the stock totem creature whose row and model it copies, and the ScriptName
that gives it its pulse. Each is the donor's own row with the module's AI and no loot, gossip or credit, untargetable like the
Wizard's Hydra, the way the other classes' summons are made: the render is generate_spells.py summon_templates, the one function that
builds them, applied to this sheet alone so the older summons' migrations keep their bytes. The core summons them into the native
totem slots and gives each the caster's race's model for its slot; the module sets what they do (src/classes/shaman/dc_shaman_totems.cpp).
"""
import csv
from pathlib import Path

import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
import scripts_path  # noqa: E402,F401  (R5: every scripts/ folder on sys.path)
from applied_migrations import write_migration

MODULE = Path(__file__).resolve().parents[3]
SHEET = 'shaman_summons.csv'
MIGRATION = 'minions_0006_shaman_summons.sql'
# The entries already taken by the module's other summons; a new entry never reuses one.
OTHER_SHEETS = ('data/d3/wizard_summons.csv', 'data/d3/monk_summons.csv', 'data/d3/crusader_summons.csv', 'data/legendary_summons.csv',
                'data/d3/necromancer_summons.csv', 'data/d3/demon_hunter_summons.csv', 'data/d3/witch_doctor_summons.csv',
                'data/d3/witch_doctor_hex_summons.csv', 'data/d3/witch_doctor_body_summons.csv')
ANCIENTS = range(900100, 900103)


def read(module, name):
    with (module / name).open(encoding='utf-8', newline='') as stream:
        return list(csv.DictReader(stream, strict=True))


def rows(module=MODULE):
    taken = set(ANCIENTS) | {int(r['entry']) for n in OTHER_SHEETS for r in read(module, n)}
    out = []
    for r in read(module, f'data/d3/{SHEET}'):
        where = f"{SHEET} {r['summon']}"
        entry = int(r['entry'])
        if entry in taken:
            raise ValueError(f'{where}: entry {entry} is taken')
        taken.add(entry)
        if r['script'] != 'dc_shaman_totem':
            raise ValueError(f'{where}: script is dc_shaman_totem')
        if not r['why']:
            raise ValueError(f'{where}: needs its reason')
        out.append(r)
    return out


def render(module=MODULE):
    import generate_spells
    rows(module)  # the checks
    return ("-- Generated by generate_shaman_summons.py from shaman_summons.csv; do not hand-edit.\n"
            + generate_spells.summon_templates(SHEET))


def generate(module=MODULE):
    write_migration(module, module / 'data/sql/db-world/updates' / MIGRATION, render(module))


if __name__ == '__main__':
    import argparse
    argparse.ArgumentParser(description=__doc__).parse_args()
    generate()
