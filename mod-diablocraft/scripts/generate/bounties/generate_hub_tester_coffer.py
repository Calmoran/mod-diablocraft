#!/usr/bin/env python3
"""Generate the additive Tester's Coffer hub migration from the designer's .gps data."""
import csv
import json
import math
from pathlib import Path
import struct

import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
import scripts_path  # noqa: E402,F401  (R5: every scripts/ folder on sys.path)
from applied_migrations import write_coupled_outputs, write_migration
from generate_hub_placements import DATA as PLACEMENTS, hub_ids, launch_tier_count, upsert
from scryer_hub import LEGACY

ROOT = Path(__file__).resolve().parents[3]
# FROZEN since the hub moved to the Sanctum of Torment (diablocraft-976b): this generator wrote the applied
# world_0020 for Scryer's Tier from the old hub's data (tests/scryer_hub); the Sanctum's coffer is
# generate_hub_sanctum_move.py's, from the live world_tester_coffer.csv.
SOURCE = LEGACY / "world_tester_coffer.csv"
NAME = "world_0020_tester_coffer.sql"  # next world migration after world_0019_class_display_power.sql
ENTRY = 910018  # next creature template after the managed hub 910017 tome stack entry
# Stock creature 30548, The Guardian's Charge, uses display 27106. Pinned
# CreatureDisplayInfo.dbc -> CreatureModelData.dbc maps it to
# World\Goober\G_ChestTitan.mdx. Keep creature gossip; copy the stock chest look.
CHEST_DONOR = 30548
CHEST_DISPLAY = 27106
TUNABLES = ("tester_coffer_gold", "tester_coffer_materials", "tester_coffer_gems", "tester_coffer_paragon")


def q(value):
    return "'" + str(value).replace("'", "''") + "'"


def f32(value):
    return struct.unpack("<f", struct.pack("<f", float(value)))[0]


def input_row(path=SOURCE):
    with path.open(newline="", encoding="utf-8") as stream:
        rows = list(csv.DictReader(stream))
    expected = {"map_id", "area_id", "x", "y", "z", "o", "placement_source", "source_guid", "guid_source"}
    if len(rows) != 1 or set(rows[0]) != expected:
        raise ValueError("Expected one the designer-sourced tester coffer placement row")
    row = rows[0]
    if not row["placement_source"] or not row["guid_source"]:
        raise ValueError("Tester coffer placement and GUID block require sources")
    map_id, area_id = hub_ids()
    if (int(row["map_id"]), int(row["area_id"])) != (map_id, area_id):
        raise ValueError("Tester coffer must be in the approved hub area")
    for key in ("x", "y", "z", "o"):
        value = f32(row[key])
        if not math.isfinite(value):
            raise ValueError("Non-finite tester coffer coordinate")
        row[key] = value
    if not 0 <= row["o"] < 2 * math.pi:
        raise ValueError("Tester coffer orientation must be in [0, 2*pi)")
    row["source_guid"] = int(row["source_guid"])
    if row["source_guid"] <= 0:
        raise ValueError("Tester coffer creature GUID must be positive")
    return row


def tunable_rows():
    with (ROOT / "data/tunables/economy.csv").open(newline="", encoding="utf-8-sig") as stream:
        rows = {row["name"]: row for row in csv.DictReader(stream) if row["name"] in TUNABLES}
    if set(rows) != set(TUNABLES):
        raise ValueError("Tester coffer tunables are incomplete")
    result = []
    for name in TUNABLES:
        row = rows[name]
        if row["d3_value"] or not row["value"] or not row["notes"]:
            raise ValueError("Tester coffer targets need the designer-approved values and citations")
        value = int(row["value"])
        if value <= 0 or value > 2**53:
            raise ValueError("Tester coffer target is outside exact double integer range")
        result.append("('economy',{},NULL,{}, {}, {})".format(
            q(name), value, q(row["unit"]), q(row["notes"])))
    return result


def hub_respawn_seconds():
    # Carry the sourced hub-NPC respawn period from the managed Blacksmith,
    # rather than introducing a new unsourced gameplay number.
    with PLACEMENTS.open(newline="", encoding="utf-8") as stream:
        rows = [json.loads(row["placement"]) for row in csv.DictReader(stream)
                if row["kind"] == "c" and json.loads(row["placement"])["id"] == 910000]
    if len(rows) != 1 or int(rows[0]["spawntimesecs"]) <= 0:
        raise ValueError("Managed hub Blacksmith respawn source is missing")
    return int(rows[0]["spawntimesecs"])


def generate(path=SOURCE):
    row = input_row(path)
    count = launch_tier_count()
    source_guid = row["source_guid"]
    if count < 1 or source_guid + count - 1 >= 2**32:
        raise ValueError("Invalid launch tier count for tester coffer GUID reservation")
    map_id, area_id = hub_ids()
    x, y, z, o = (row[key] for key in ("x", "y", "z", "o"))
    donor = CHEST_DONOR
    coffer_name = q("Tester's Coffer")
    lines = [
        "-- Generated by generate_hub_tester_coffer.py from world_tester_coffer.csv and economy.csv; never edit.",
        "-- Placement: " + row["placement_source"] + ".",
        "-- Appearance: stock creature 30548 The Guardian's Charge, display 27106, "
        "CreatureModelData model World/Goober/G_ChestTitan.mdx (pinned 3.3.5a DBC).",
        "-- Creature entry 910018 follows managed hub service entry 910017; creature GUIDs "
        f"{source_guid}-{source_guid + count - 1} from {row['guid_source']}.",
        "-- Creature/gameobject GUID spaces are separate.",
        "-- Apply to the world database with worldserver stopped.",
        "SET NAMES utf8mb4;",
        "CREATE TEMPORARY TABLE dc_tester_coffer_guard (ok INT NOT NULL CHECK(ok=1));",
        "START TRANSACTION;",
        f"INSERT INTO dc_tester_coffer_guard VALUES (EXISTS(SELECT 1 FROM dc_world_areas WHERE map_id={map_id} AND area_id={area_id} AND status='open' AND phase_scope='all'));",
        f"INSERT INTO dc_tester_coffer_guard VALUES (EXISTS(SELECT 1 FROM creature_template WHERE entry={donor}));",
        f"INSERT INTO dc_tester_coffer_guard VALUES (EXISTS(SELECT 1 FROM creature_template_model WHERE CreatureID={donor} AND CreatureDisplayID={CHEST_DISPLAY}));",
        f"INSERT INTO dc_tester_coffer_guard VALUES (NOT EXISTS(SELECT 1 FROM creature_template WHERE entry={ENTRY}) OR EXISTS(SELECT 1 FROM creature_template WHERE entry={ENTRY} AND ScriptName='dc_tester_coffer'));",
        f"INSERT INTO dc_tester_coffer_guard VALUES ((SELECT COUNT(*) FROM dc_tier_phase WHERE tier_id BETWEEN 1 AND {count} AND phase=tier_id)={count});",
        f"INSERT INTO dc_tester_coffer_guard VALUES (NOT EXISTS(SELECT 1 FROM dc_area_source WHERE kind='c' AND source_guid={source_guid}) OR EXISTS(SELECT 1 FROM dc_area_source WHERE kind='c' AND source_guid={source_guid} AND map_id={map_id} AND area_id={area_id} AND entry={ENTRY}));",
    ]
    for tier in range(1, count + 1):
        guid = source_guid + tier - 1
        lines.append(
            f"INSERT INTO dc_tester_coffer_guard VALUES (NOT EXISTS(SELECT 1 FROM creature WHERE guid={guid}) "
            f"OR EXISTS(SELECT 1 FROM creature WHERE guid={guid} AND id={ENTRY} AND map={map_id} "
            f"AND phaseMask={tier}));")
        if tier > 1:
            lines.append(
                f"INSERT INTO dc_tester_coffer_guard VALUES (NOT EXISTS(SELECT 1 FROM dc_area_spawn WHERE kind='c' AND spawn_guid={guid}) "
                f"OR EXISTS(SELECT 1 FROM dc_area_spawn WHERE kind='c' AND spawn_guid={guid} "
                f"AND map_id={map_id} AND area_id={area_id} AND source_guid={source_guid} AND tier={tier}));")
    lines += [
        "CREATE TEMPORARY TABLE dc_tester_coffer_template LIKE creature_template;",
        f"INSERT INTO dc_tester_coffer_template SELECT * FROM creature_template WHERE entry={donor};",
        f"UPDATE dc_tester_coffer_template SET entry={ENTRY},name={coffer_name},subname='',",
        "npcflag=1,ScriptName='dc_tester_coffer';",
        f"REPLACE INTO creature_template SELECT * FROM dc_tester_coffer_template;",
        "DROP TEMPORARY TABLE dc_tester_coffer_template;",
        f"DELETE FROM creature_template_model WHERE CreatureID={ENTRY};",
        f"INSERT INTO creature_template_model SELECT {ENTRY},Idx,CreatureDisplayID,DisplayScale,Probability,VerifiedBuild FROM creature_template_model WHERE CreatureID={donor} AND CreatureDisplayID={CHEST_DISPLAY};",
        "INSERT INTO dc_tunables (category,name,d3_value,tuned_value,unit,notes) VALUES",
        "  " + ",\n  ".join(tunable_rows()) + "\nON DUPLICATE KEY UPDATE tuned_value=VALUES(tuned_value),unit=VALUES(unit),notes=VALUES(notes);",
    ]
    for tier in range(1, count + 1):
        guid = source_guid + tier - 1
        creature = dict(guid=guid, id=ENTRY, map=map_id, zoneId=area_id, areaId=area_id,
                        spawnMask=1, phaseMask=tier, position_x=x, position_y=y, position_z=z,
                        orientation=o, spawntimesecs=hub_respawn_seconds())
        lines.append(upsert("creature", creature))
        if tier == 1:
            source = dict(map_id=map_id, area_id=area_id, kind="c", source_guid=guid,
                          entry=ENTRY, source_phase=1, position_x=x, position_y=y,
                          position_z=z, orientation=o)
            lines.append(upsert("dc_area_source", source))
        else:
            copy = dict(map_id=map_id, area_id=area_id, kind="c", source_guid=source_guid,
                        tier=tier, spawn_guid=guid)
            lines.append(upsert("dc_area_spawn", copy))
    lines += ["COMMIT;", "DROP TEMPORARY TABLE dc_tester_coffer_guard;", ""]
    return "\n".join(lines)


def main():
    sql = generate()
    migration = ROOT / "data/sql/db-world/updates" / NAME
    if migration.exists() and not migration.read_text(encoding="utf-8").startswith(
            "-- Generated by generate_hub_tester_coffer.py"):
        raise ValueError(NAME + " is already owned by another migration; choose the next free world number")
    write_migration(ROOT, migration, sql)
    write_coupled_outputs(ROOT, migration, sql, [(ROOT / "data/generated" / NAME, sql)],
                          label="Tester Coffer generated SQL mirror")
    print(NAME + ": sourced Tester's Coffer template and " + str(launch_tier_count()) + " tier spawns")


if __name__ == "__main__":
    main()
