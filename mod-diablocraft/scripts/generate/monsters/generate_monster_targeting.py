#!/usr/bin/env python3
"""the designer's targeting tunables: CSV -> world schema and seed updates.

Gameplay values are proposed placeholders, never published D3 measurements.
Regeneration preserves database tuning; reset a profile explicitly to reseed it.
"""
import csv
import math
from pathlib import Path

import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
import scripts_path  # noqa: E402,F401  (R5: every scripts/ folder on sys.path)
from applied_migrations import write_migration

MODULE = Path(__file__).resolve().parents[3]
DATA = MODULE / 'data/d3'
# Phase 2 (Architect, 2026-09-19): this sheet is the designer's numbers, not D3's
# published reference data, so it moved to data/tunables/ and out of
# data/d3/. Its runtime home is unchanged - it is still this generator's
# table, not dc_tunables. data/tunables/README.md says so under "Files with
# their own table".
TUNABLES = MODULE / 'data/tunables'
GENERATED = MODULE / 'data/generated'
UPDATES = MODULE / 'data/sql/db-world/updates'
COLUMNS = ('lock_seconds', 'jitter_percent', 'recency_weight', 'proximity_weight',
           'reachability_weight', 'recency_window_seconds', 'recency_max_yards',
           'candidate_max_yards', 'unreachable_penalty', 'switch_margin')
PROFILES = ('normal', 'elite', 'guardian')


def read():
    with (TUNABLES / 'monster_targeting.csv').open(encoding='utf-8-sig', newline='') as stream:
        return list(csv.DictReader(stream))


def validate(rows):
    if len(rows) != len(PROFILES) or {r['profile'] for r in rows} != set(PROFILES):
        raise ValueError('exactly normal, elite and guardian profiles are required')
    for row in rows:
        values = {key: float(row[key]) for key in COLUMNS}
        if any(not math.isfinite(v) or v < 0 for v in values.values()):
            raise ValueError('tunables must be finite and nonnegative')
        if not math.isfinite(sum(values[k] for k in ('recency_weight', 'proximity_weight',
                             'reachability_weight', 'unreachable_penalty', 'switch_margin'))) or not math.isfinite(
                values['lock_seconds'] * (1 + values['jitter_percent'] / 100)):
            raise ValueError('tunables overflow score or lock arithmetic')
        if any(values[k] <= 0 for k in ('lock_seconds', 'recency_window_seconds', 'candidate_max_yards')):
            raise ValueError('lock, recency window and candidate range must be positive')
        if values['jitter_percent'] >= 100 or values['recency_max_yards'] > values['candidate_max_yards']:
            raise ValueError('jitter must be below 100%; recency range must fit candidate range')
        if "the designer's tunables" not in row['source'] or 'placeholder' not in row['notes'].lower():
            raise ValueError('every profile must identify tunables and placeholder provenance')
    profiles = {r['profile']: r for r in rows}
    if any(float(profiles['guardian'][key]) <= float(profiles['normal'][key]) for key in ('lock_seconds', 'switch_margin')):
        raise ValueError('guardian lock and switch margin must exceed normal')
    return rows


def quote(value):
    return "'" + value.replace('\\', '\\\\').replace("'", "''") + "'"


def render():
    rows = validate(read())
    schema = '\n'.join([
        '-- Generated by generate_monster_targeting.py; do not hand-edit.',
        '-- WORLD database: shared monster AI configuration, no character state.',
        'CREATE TABLE IF NOT EXISTS dc_monster_targeting (',
        '  profile VARCHAR(16) NOT NULL PRIMARY KEY,',
        *('  ' + key + ' DOUBLE NOT NULL,' for key in COLUMNS),
        '  source VARCHAR(128) NOT NULL,',
        '  notes TEXT NOT NULL',
        ');', ''])
    seed = '\n'.join([
        '-- Generated by generate_monster_targeting.py; do not hand-edit.',
        "-- All numbers are proposed placeholders: the designer's tunables 2026-09-18.",
        'SET NAMES utf8mb4;',
        'INSERT INTO dc_monster_targeting (profile,' + ','.join(COLUMNS) + ',source,notes) VALUES',
        ',\n'.join('(' + ','.join([quote(row['profile']), *(format(float(row[k]), '.15g') for k in COLUMNS),
                                 quote(row['source']), quote(row['notes'])]) + ')' for row in rows),
        # The CSV wins on every apply (ruling 2026-09-19): monster_targeting.csv
        # is in data/tunables/, so every profile number is refreshed from it and
        # not only its prose. Refreshing source and notes alone meant an edited
        # number never reached a world that already had the row.
        'ON DUPLICATE KEY UPDATE '
        + ','.join(f'{column}=VALUES({column})' for column in COLUMNS)
        + ',source=VALUES(source),notes=VALUES(notes);', ''])
    return schema, seed


def main():
    schema, seed = render()  # Validate everything before writing anything.
    GENERATED.mkdir(parents=True, exist_ok=True)
    for name, text in (('rifts_0012_monster_targeting_schema.sql', schema),
                       ('rifts_0013_monster_targeting_profiles.sql', seed)):
        (GENERATED / name).write_text(text, encoding='utf-8')
        write_migration(MODULE, UPDATES / name, text)
        print('Generated ' + name)


if __name__ == '__main__':
    import argparse
    argparse.ArgumentParser(description=__doc__).parse_args()
    main()
