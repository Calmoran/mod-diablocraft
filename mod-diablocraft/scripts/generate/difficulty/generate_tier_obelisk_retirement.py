#!/usr/bin/env python3
"""Retire the hub's difficulty obelisk, gameobject 910010 (diablocraft-fjqx, ruling 2026-10-07).

Difficulty is now chosen from the Difficulty button in the hub (diablocraft-7p05), and the server
refuses a pick outside the hub (DC::World::IsInHub), so the obelisk and its click path go. Its rows
were placed by world_0002, world_0007, world_0024, world_0032 and difficulty_area_1_876, which stay
as they were applied; this removes everything they left under the entry, on any map, from every
table that held it: the tier copies' registry (dc_area_spawn, dc_area_source), any spawn addon, the
spawns, and the template with its addon and locale rows. The entry is named here, the one place that
still names it. A rerun finds nothing left to remove.

    python3 mod-diablocraft/scripts/generate/difficulty/generate_tier_obelisk_retirement.py
"""
from pathlib import Path

import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
import scripts_path  # noqa: E402,F401  (R5: every scripts/ folder on sys.path)
from applied_migrations import write_coupled_outputs, write_migration

ROOT = Path(__file__).resolve().parents[3]
NAME = "world_0034_tier_obelisk_retired.sql"
# Constant: our custom gameobject entry (world_0002), an identity, not a game magnitude.
OBELISK = 910010


def render():
    spawns = f"SELECT guid FROM gameobject WHERE id={OBELISK}"
    return "\n".join([
        "-- Generated by generate_tier_obelisk_retirement.py; never edit.",
        f"-- The hub's difficulty obelisk ({OBELISK}) is retired (diablocraft-fjqx): difficulty is chosen from the hub's Difficulty button.",
        "START TRANSACTION;",
        f"DELETE FROM dc_area_spawn WHERE kind='g' AND (spawn_guid IN ({spawns}) OR source_guid IN "
        f"(SELECT source_guid FROM dc_area_source WHERE kind='g' AND entry={OBELISK}));",
        f"DELETE FROM dc_area_source WHERE kind='g' AND entry={OBELISK};",
        f"DELETE FROM gameobject_addon WHERE guid IN ({spawns});",
        f"DELETE FROM gameobject WHERE id={OBELISK};",
        f"DELETE FROM gameobject_template_addon WHERE entry={OBELISK};",
        f"DELETE FROM gameobject_template_locale WHERE entry={OBELISK};",
        f"DELETE FROM gameobject_template WHERE entry={OBELISK};",
        "COMMIT;",
        ""])


if __name__ == "__main__":
    sql = render()
    updates = ROOT / "data/sql/db-world/updates" / NAME
    write_migration(ROOT, updates, sql)
    write_coupled_outputs(ROOT, updates, sql, [(ROOT / "data/generated" / NAME, sql)])
    print(f"Generated {NAME}")
