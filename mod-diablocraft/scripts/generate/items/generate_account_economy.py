def render_stash_prices(module: Path) -> str:
    """Each purchasable tab has its own economy row; blank stays SQL NULL."""
    with (module / "data/tunables/economy.csv").open(encoding="utf-8", newline="") as stream:
        rows = {}
        for row in csv.DictReader(stream):
            name = row["name"]
            if name in rows:
                raise ValueError(f"Duplicate economy tunable: {name}")
            rows[name] = row

    def number(name: str, unit: str, maximum: int, nullable: bool = False) -> str:
        if name not in rows:
            raise ValueError(f"Missing economy tunable: {name}")
        row = rows[name]
        if row["unit"] != unit or not row["notes"].strip():
            raise ValueError(f"{name}: expected {unit} and source notes")
        cell = row["value"].strip() or row["d3_value"].strip()
        if not cell and nullable:
            return "NULL"
        try:
            value = Decimal(cell)
        except InvalidOperation as error:
            raise ValueError(f"{name}: invalid number") from error
        if not value.is_finite() or not 0 <= value <= maximum or value != value.to_integral_value():
            raise ValueError(f"{name}: expected an unsigned integer up to {maximum}")
        return str(int(value))

    launch = int(number("stash_launch_tabs", "count", 255))
    maximum = int(number("stash_max_tabs", "count", 255))
    if not 1 <= launch <= maximum:
        raise ValueError("Expected 1 <= stash_launch_tabs <= stash_max_tabs")
    values = []
    for tab in range(launch + 1, maximum + 1):
        price = number(f"stash_tab_{tab}_price_gold", "gold", 2**64 - 1, nullable=True)
        values.append(f"({tab},{price})")
    sql = "-- Generated by generate_account_economy.py from data/tunables/economy.csv; do not edit.\n"
    sql += "-- Whole Torment gold (1:1); blank prices remain NULL and refuse purchase.\n"
    if values:
        sql += "INSERT INTO `dc_stash_tuning` (`next_tab`,`price_gold`) VALUES\n"
        sql += ",\n".join(values) + "\nON DUPLICATE KEY UPDATE `price_gold`=VALUES(`price_gold`);\n"
    return sql


def render(module: Path = MODULE) -> tuple[str, str]:
    with (module / "data/d3/account_economy.csv").open(encoding="utf-8", newline="") as stream:
        rows = list(csv.DictReader(stream))
    seen: set[int] = set()
    values = []
    for row in rows:
        entry, copper = int(row["item_entry"]), int(row["copper_per_item"])
        if entry <= 0 or entry > 2**32-1 or entry in seen or not row["source"]:
            raise ValueError("Invalid or duplicate legacy entry")
        seen.add(entry)
        if row["kind"] not in {"material", "retired_gold"} or not 0 <= copper <= 2**64-1:
            raise ValueError("Invalid legacy conversion")
        if (row["kind"] == "material") != (copper == 0):
            raise ValueError("Materials are counts; retired gold requires a conversion")
        name = row["name"].replace("'", "''")
        source = row["source"].replace("'", "''")
        values.append(f"({entry},'{name}','{row['kind']}',{copper},'{source}')")
    if not any(r["kind"] == "material" for r in rows) or not any(r["kind"] == "retired_gold" for r in rows):
        raise ValueError("The source manifest requires materials and a retired denomination")
    world = """-- Generated by generate_account_economy.py; do not edit.
CREATE TABLE IF NOT EXISTS dc_account_economy_kind (
 item_entry INT UNSIGNED PRIMARY KEY, name VARCHAR(80) NOT NULL,
 kind ENUM('material','retired_gold') NOT NULL,
 copper_per_item BIGINT UNSIGNED NOT NULL, source VARCHAR(255) NOT NULL
) ENGINE=InnoDB;
REPLACE INTO dc_account_economy_kind VALUES
""" + ",\n".join(values) + ";\n"
    for entry in CURRENCY_ITEMS:
        if entry not in seen or next(r for r in rows if int(r["item_entry"]) == entry)["kind"] != "material":
            raise ValueError(f"Currency item {entry} is not a ledger material")
    def quoted(text: str) -> str:
        return "'" + text.replace("'", "''") + "'"
    items = ",\n".join(
        f"  ({entry}, 10, 0, {quoted(next(r['name'] for r in rows if int(r['item_entry']) == entry))}, {display}, 1, 2048, 1, 0, 0, 0, 0, "
        f"2147483647, 8192, 4, 1, 70, {quoted(text)})" for entry, (display, text) in CURRENCY_ITEMS.items())
    world += f"""DELETE FROM `item_template` WHERE `entry` IN ({",".join(map(str, CURRENCY_ITEMS))});
INSERT INTO `item_template`
  (`entry`, `class`, `subclass`, `name`, `displayid`, `Quality`, `Flags`, `BuyCount`, `BuyPrice`, `SellPrice`,
   `InventoryType`, `maxcount`, `stackable`, `BagFamily`, `Material`, `bonding`, `ItemLevel`, `description`)
VALUES
{items};
"""
    retired = ",".join(r["item_entry"] for r in rows if r["kind"] == "retired_gold")
    world += f"UPDATE item_template SET BuyPrice=0,SellPrice=0,description='Retired denomination; migration only.' WHERE entry IN ({retired});\n"
    characters = """-- Generated by generate_account_economy.py; do not edit.
CREATE TABLE IF NOT EXISTS dc_account_gold (
 account_id INT UNSIGNED NOT NULL, mode ENUM('normal','hardcore') NOT NULL,
 balance_copper BIGINT UNSIGNED NOT NULL DEFAULT 0, revision BIGINT UNSIGNED NOT NULL DEFAULT 0,
 PRIMARY KEY(account_id,mode)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS dc_account_currency (
 account_id INT UNSIGNED NOT NULL, mode ENUM('normal','hardcore') NOT NULL,
 item_entry INT UNSIGNED NOT NULL, amount BIGINT UNSIGNED NOT NULL DEFAULT 0,
 revision BIGINT UNSIGNED NOT NULL DEFAULT 0, PRIMARY KEY(account_id,mode,item_entry)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS dc_account_economy_operation (
 operation_id VARCHAR(96) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 description TEXT NOT NULL, committed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS dc_account_economy_check (
 operation_id VARCHAR(96) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 sequence_id INT UNSIGNED NOT NULL, valid TINYINT NOT NULL,
 PRIMARY KEY(operation_id,sequence_id), CONSTRAINT dc_economy_revision_valid CHECK(valid=1)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS dc_account_economy_migration (
 source_kind ENUM('character','item') NOT NULL, source_guid BIGINT UNSIGNED NOT NULL,
 character_guid INT UNSIGNED NOT NULL, account_id INT UNSIGNED NOT NULL,
 mode ENUM('pending','normal','hardcore') NOT NULL, item_entry INT UNSIGNED NOT NULL,
 original_amount BIGINT UNSIGNED NOT NULL, pool_amount BIGINT UNSIGNED NOT NULL,
 location VARCHAR(80) NOT NULL, migrated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(source_kind,source_guid), KEY pending_character(character_guid,mode)
) ENGINE=InnoDB;
"""
    return world, characters


def generate(module: Path = MODULE) -> None:
    stash_prices = render_stash_prices(module)
    world, characters = render(module)
    for database, sql in (("world", world), ("characters", characters)):
        mirror = module / f"data/generated/account_economy_{database}.sql"
        updates = module / f"data/sql/db-{database}/updates"
        ledger = updates / "account_economy_0001_ledger.sql"
        mirror.parent.mkdir(parents=True, exist_ok=True)
        mirror.write_text(sql, encoding="utf-8", newline="\n")
        if not ledger.exists():
            write_migration(module, ledger, sql)
            continue
        if ledger.read_text(encoding="utf-8") == sql:
            continue
        # 0001 has been applied: its hash is recorded in the updates table, so
        # write_migration refuses it. The schema is CREATE TABLE IF NOT EXISTS
        # and the metadata is a REPLACE, so re-running the whole render as the
        # next migration is idempotent and carries changed values (the
        # 2026-09-12 gold unit) to an already-migrated database. When that next
        # migration is itself applied, write_migration warns instead of
        # rewriting it and the change needs the one after it.
        write_migration(module, updates / (WORLD_LEDGER_MIGRATION if database == "world" else CHARACTERS_LEDGER_MIGRATION), sql)
    migration = module / "data/sql/db-world/updates" / STASH_MIGRATION
    mirror = module / "data/generated" / STASH_MIGRATION
    write_migration(module, migration, stash_prices)
    write_coupled_outputs(module, migration, stash_prices, [(mirror, stash_prices)], label="stash prices")
    print("PASS account economy schema, conversion metadata and stash prices generated")


if __name__ == "__main__":
    import argparse
    argparse.ArgumentParser(description=__doc__).parse_args()
    generate(MODULE)
