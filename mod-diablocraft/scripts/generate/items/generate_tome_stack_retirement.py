#!/usr/bin/env python3
"""Retire the Tome's old book stack, gameobject spawn 910017 (diablocraft-jn9l, ruling 2026-10-10).

Nothing stands on the stack since diablocraft-bb67 moved the Tome. Its spawn is removed from every map and its registry rows
from dc_area_source and dc_area_spawn (the old hub's tier copies included), with any spawn addon. The gameobject_template row
STAYS (the designer: no stock template change), so it is not touched here. world_0023 and world_0032 stay as they were applied;
world_hub_placements.csv no longer names the stack, so world_0032 no longer moves it. A rerun finds nothing left to remove.

    python3 mod-diablocraft/scripts/generate/items/generate_tome_stack_retirement.py
"""
from pathlib import Path

import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
import scripts_path  # noqa: E402,F401  (R5: every scripts/ folder on sys.path)
from applied_migrations import write_coupled_outputs, write_migration

ROOT = Path(__file__).resolve().parents[3]
NAME = "world_0038_tome_stack_retired.sql"
# Constant: our custom gameobject entry (world_0011), an identity, not a game magnitude.
STACK = 910017


def render():
    spawns = f"SELECT guid FROM gameobject WHERE id={STACK}"
    return "\n".join([
        "-- Generated by generate_tome_stack_retirement.py; never edit.",
        f"-- The Tome's old book stack ({STACK}) has no spawn left (diablocraft-jn9l); its template stays.",
        "START TRANSACTION;",
        f"DELETE FROM dc_area_spawn WHERE kind='g' AND (spawn_guid IN ({spawns}) OR source_guid IN "
        f"(SELECT source_guid FROM dc_area_source WHERE kind='g' AND entry={STACK}));",
        f"DELETE FROM dc_area_source WHERE kind='g' AND entry={STACK};",
        f"DELETE FROM gameobject_addon WHERE guid IN ({spawns});",
        f"DELETE FROM gameobject WHERE id={STACK};",
        "COMMIT;",
        ""])


if __name__ == "__main__":
    sql = render()
    updates = ROOT / "data/sql/db-world/updates" / NAME
    write_migration(ROOT, updates, sql)
    write_coupled_outputs(ROOT, updates, sql, [(ROOT / "data/generated" / NAME, sql)])
    print(f"Generated {NAME}")
