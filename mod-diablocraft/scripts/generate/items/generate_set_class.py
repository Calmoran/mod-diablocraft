#!/usr/bin/env python3
"""The class each D3 set belongs to, for the loot roll (diablocraft-set-class-drop).

Ruling 2026-10-03: "all class set items are dropping instead of the 85/15 rule". A class set
(Armor of Akkhan, Bones of Rathma...) drops for its class only, with the same 85/15 split every
other class-only item has (decisions.md 2026-09-23, loot roll class). base_items.csv cannot say it:
a set's generic pieces (Helm, Boots) have no usable_by and no designated_class, and those two
columns also decide who may WEAR a piece, so filling them would change the wear rule.

data/d3/set_classes.csv keys the class by SET, which is the natural key: one row per set in
base_items.csv, the class D3Planner gives it (reference/d3planner/data_itemsets.js, `class:` or
`tclass:`) and the line that says so. A classless set (Cain's Destiny, Born's Command...) has an
empty class_key and stays for everyone. The loot loader joins this table through
dc_base_item.set_name. Wear follows the same sheet since diablocraft-9rhz (ruling 2026-10-03, q-1003-28):
generate_sql.py render_set_wear_class locks each set piece's AllowableClass to its set's class, in the
delta migration items_0020; this generator and its frozen migration are unchanged.

    python3 mod-diablocraft/scripts/generate/items/generate_set_class.py

Outputs: the world migration items_0018_set_class.sql and, coupled to it, a data/generated mirror.
"""
import csv
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

import scripts_path  # noqa: E402,F401  (R5: every scripts/ folder on sys.path)
from applied_migrations import write_coupled_outputs, write_migration  # noqa: E402

MODULE = Path(__file__).resolve().parents[3]
SHEET = MODULE / "data" / "d3" / "set_classes.csv"
BASE_ITEMS = MODULE / "data" / "d3" / "base_items.csv"
MIGRATION = "items_0018_set_class.sql"
HEADER = ["set_name", "class_key", "source"]
# The seven D3 classes a set can belong to. Which of them is playable is class_map.csv's business:
# a set of a class that is not playable yet simply drops for nobody, like its designated pieces.
CLASS_KEYS = {"barbarian", "crusader", "demonhunter", "monk", "necromancer", "witchdoctor", "wizard"}
SOURCE = re.compile(r"^reference/d3planner/data_itemsets\.js:[1-9][0-9]*$")


class DataError(Exception):
    pass


def read_csv(path):
    with path.open(encoding="utf-8-sig", newline="") as stream:
        reader = csv.DictReader(stream, strict=True)
        return reader.fieldnames, list(reader)


def read_sheet(sheet=SHEET, base_items=BASE_ITEMS):
    """[(set_name, class_key)] in sheet order, validated against base_items.csv in both directions."""
    fields, rows = read_csv(sheet)
    if fields != HEADER:
        raise DataError(f"{sheet.name}: header is {fields}, expected {HEADER}")
    seen, out = set(), []
    for number, row in enumerate(rows, 2):
        name, key, source = row["set_name"], row["class_key"], row["source"]
        if not name or name != name.strip():
            raise DataError(f"{sheet.name}:{number}: set_name {name!r} is empty or padded")
        if name in seen:
            raise DataError(f"{sheet.name}:{number}: set {name!r} appears twice")
        seen.add(name)
        if key and key not in CLASS_KEYS:
            raise DataError(f"{sheet.name}:{number}: class_key {key!r} is not one of {sorted(CLASS_KEYS)}")
        if not SOURCE.match(source):
            raise DataError(f"{sheet.name}:{number}: source {source!r} must cite reference/d3planner/data_itemsets.js:LINE")
        out.append((name, key))
    _, items = read_csv(base_items)
    sets = {row["set_name"] for row in items if row["rarity"] == "set"}
    if sets - seen:
        raise DataError(f"{sheet.name}: sets in base_items.csv with no row: {sorted(sets - seen)}")
    if seen - sets:
        raise DataError(f"{sheet.name}: rows for sets base_items.csv does not have: {sorted(seen - sets)}")
    return out


def quote(text):
    return "'" + text.replace("\\", "\\\\").replace("'", "''") + "'"


def render(rows):
    lines = [
        "-- Generated by generate_set_class.py from data/d3/set_classes.csv; edit the sheet and rerun it.",
        "-- Apply to the world database. The class a set belongs to, for the loot roll's drop pick only",
        "-- (diablocraft-set-class-drop). An empty class_key is a classless set: it drops for everyone.",
        "-- AllowableClass never reads this table.",
        "SET NAMES utf8mb4;",
        "CREATE TABLE IF NOT EXISTS `dc_set_class` (",
        "  `set_name` VARCHAR(100) NOT NULL,",
        "  `class_key` VARCHAR(40) NOT NULL DEFAULT '',",
        "  PRIMARY KEY (`set_name`)",
        ") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;",
        "DELETE FROM `dc_set_class`;",
        "INSERT INTO `dc_set_class` (`set_name`, `class_key`) VALUES",
    ]
    body = [f"({quote(name)}, {quote(key)})" for name, key in rows]
    lines.append(",\n".join(body) + ";")
    return "\n".join(lines) + "\n"


def main():
    rows = read_sheet()
    sql = render(rows)
    migration = Path("data/sql/db-world/updates") / MIGRATION
    wrote = write_migration(MODULE, migration, sql)
    write_coupled_outputs(MODULE, migration, sql, [(Path("data/generated/set_class.sql"), sql)],
                          label="set class mirror")
    classed = sum(1 for _, key in rows if key)
    print(f"{len(rows)} sets, {classed} with a class, {len(rows) - classed} classless; "
          f"{MIGRATION} {'written' if wrote else 'left as it is'}")


if __name__ == "__main__":
    try:
        main()
    except DataError as error:
        sys.exit(f"generate_set_class: {error}")
