#!/usr/bin/env python3
"""Emit the affix lines that belong to one item type: a class item's own pool lines (the Shaman's Ritual Mace and Totem).

Sheet (data/d3): class_item_pools.csv, the same columns as affix_pools.csv with `slot` written "<slot>:<type>" ("onehand:Ritual
Mace"). The roller and the Mystic read a base's slot pool and, beside it, the pool of "<slot>:<type>" for its own type
(src/items/dc_items_data.cpp PoolFor), so a line the sheet lists here is rolled by that type alone and by no other type of the slot.

items_0061_class_item_pools.sql (world): the rows inserted into dc_affix_pool, the table items_0040 built; the slot pools
themselves are left as they are. It is merged, so it stays as it shipped: without the two Maelstrom lines (LATER_LINES), which
the stats Shaman 2b appended made possible (diablocraft-xnrvn.9). Those ride in items_0063_class_item_pools_maelstrom.sql, which
deletes and inserts only their own affix ids.
"""
import csv
from pathlib import Path

import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
import scripts_path  # noqa: E402,F401  (R5: every scripts/ folder on sys.path)
from applied_migrations import write_coupled_outputs, write_migration

MODULE = Path(__file__).resolve().parents[3]
MIGRATION = 'items_0061_class_item_pools.sql'
MAELSTROM_MIGRATION = 'items_0063_class_item_pools_maelstrom.sql'
LATER_LINES = ('maelstromgen', 'primarymaelstrom')   # the sheet's lines that MAELSTROM_MIGRATION carries, not MIGRATION
COLUMNS = ('slot', 'affix_id', 'affix_name', 'kind', 'value_min', 'value_max', 'value_step', 'item_level_bracket', 'is_percent',
           'source_file', 'display_order', 'value_min2', 'value_max2', 'weapon_class')
BRACKETS = ('rare', 'legendary', 'ancient', 'primal')
KINDS = ('primary', 'secondary')


def quote(text):
    return "'" + text.replace("'", "''") + "'"


def number(text, where):
    if text == '':
        return 'NULL'
    try:
        value = float(text)
    except ValueError:
        raise ValueError(f'{where}: {text!r} is not a number') from None
    return format(value, '.15g')


def read(module=MODULE):
    """class_item_pools.csv, checked: the rows in file order. Every type holds the same lines in all four brackets."""
    with (module / 'data/d3/class_item_pools.csv').open(encoding='utf-8-sig', newline='') as stream:
        reader = csv.DictReader(stream, strict=True)
        if tuple(reader.fieldnames or ()) != COLUMNS:
            raise ValueError(f"class_item_pools.csv: the columns are {', '.join(COLUMNS)}")
        rows = list(reader)
    seen = set()
    for row in rows:
        where = f"class_item_pools.csv {row['slot']} {row['affix_id']} {row['item_level_bracket']}"
        if row['slot'].count(':') != 1 or not all(row['slot'].split(':')):
            raise ValueError(f"{where}: the slot is written <slot>:<type>")
        if row['kind'] not in KINDS or row['item_level_bracket'] not in BRACKETS or row['is_percent'] not in ('0', '1'):
            raise ValueError(f"{where}: a kind (primary or secondary), a bracket ({', '.join(BRACKETS)}), is_percent 0 or 1")
        low, high = row['value_min'], row['value_max']
        if low == '' or high == '' or float(high) < float(low):
            raise ValueError(f'{where}: value_min and value_max, the second not below the first')
        if not row['affix_name'] or not row['source_file']:
            raise ValueError(f'{where}: affix_name and source_file are required')
        key = (row['slot'], row['affix_id'], row['item_level_bracket'])
        if key in seen:
            raise ValueError(f'{where}: repeated')
        seen.add(key)
    for slot in {row['slot'] for row in rows}:
        mine = {(r['affix_id'], r['kind']) for r in rows if r['slot'] == slot}
        for bracket in BRACKETS:
            here = {(r['affix_id'], r['kind']) for r in rows if r['slot'] == slot and r['item_level_bracket'] == bracket}
            if here != mine:
                raise ValueError(f'class_item_pools.csv {slot}: the {bracket} bracket holds other affixes than the rest')
    return rows


def statements(rows, comment, delete_only=None):
    slots = sorted({row['slot'] for row in rows})
    where = f'slot IN ({", ".join(quote(slot) for slot in slots)})'
    if delete_only:
        where += f' AND affix_id IN ({",".join(quote(a) for a in delete_only)})'
    lines = ['-- Generated by generate_class_item_pools.py from class_item_pools.csv; do not hand-edit.', comment,
             'SET NAMES utf8mb4;',
             f'DELETE FROM dc_affix_pool WHERE {where};',
             'INSERT INTO dc_affix_pool (slot, affix_id, affix_name, kind, value_min, value_max, value_step, '
             'item_level_bracket, is_percent, source_file, display_order, value_min2, value_max2, weapon_class) VALUES\n'
             + ',\n'.join(f"({quote(r['slot'])},{quote(r['affix_id'])},{quote(r['affix_name'])},{quote(r['kind'])},"
                          f"{number(r['value_min'], 'min')},{number(r['value_max'], 'max')},{number(r['value_step'], 'step')},"
                          f"{quote(r['item_level_bracket'])},{r['is_percent']},{quote(r['source_file'])},"
                          f"{int(r['display_order'])},{number(r['value_min2'], 'min2')},{number(r['value_max2'], 'max2')},"
                          f"{quote(r['weapon_class'])})" for r in rows) + ';']
    return '\n'.join(lines) + '\n'


def render(module=MODULE):
    rows = [row for row in read(module) if row['affix_id'] not in LATER_LINES]
    return statements(rows, "-- The affix lines one item type rolls beside its slot's pool (slot written <slot>:<type>).")


def render_maelstrom(module=MODULE):
    rows = [row for row in read(module) if row['affix_id'] in LATER_LINES]
    return statements(rows, "-- The Shaman's two Maelstrom lines (Totem: Primary skills generate Maelstrom; Ritual Mace: Maelstrom generation), "
                      "on the stats Shaman 2b added.", delete_only=sorted(LATER_LINES))


def generate(module=MODULE):
    text = render(module)
    target = module / 'data/sql/db-world/updates' / MIGRATION
    write_migration(module, target, text)
    write_coupled_outputs(module, target, text, [(module / 'data/generated' / MIGRATION, text)], label='Class item pools')
    later = render_maelstrom(module)
    target = module / 'data/sql/db-world/updates' / MAELSTROM_MIGRATION
    write_migration(module, target, later)
    write_coupled_outputs(module, target, later, [(module / 'data/generated' / MAELSTROM_MIGRATION, later)],
                          label='Class item pools (Maelstrom lines)')
    print('Generated class item pools')


if __name__ == '__main__':
    import argparse
    argparse.ArgumentParser(description=__doc__).parse_args()
    generate()
