"""Generate custom container templates from data/tunables/bags.csv; stdlib only.

Bags are the designer's tunables, not D3 figures, so the CSV carries that in its source
column. Each row clones a stock container and overrides only what makes it ours,
the same way generate_crafting.py builds gems and the retired Gold Bar: every
column the clone brings across is already a valid container, so a bag can never
be half-defined by a missing field.

The engine and this client both cap a container at 36 slots -- the installed
world data ships entry 23162 at 36 -- so the generator refuses anything larger
rather than writing a row the client would clip.
"""
import csv
from pathlib import Path

import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
import scripts_path  # noqa: E402,F401  (R5: every scripts/ folder on sys.path)
from applied_migrations import write_migration

# Literal audit (docs/research/literal-audit-claude.md): the numbers below are
# constants, not tunables - recorded here, nothing else changes.
# Constant (audit 121, 36): MAX_SLOTS, the largest container the client will draw; Verified fact, enforced as a refusal.
# Constant (audit 122, 100000, 7): entry floor for our bags and the item-quality bound; Validation.

MODULE = Path(__file__).resolve().parents[3]
DATA = MODULE / "data/d3"
# Phase 2 (Architect, 2026-09-19): this sheet is the designer's numbers, not D3's
# published reference data, so it moved to data/tunables/ and out of
# data/d3/. Its runtime home is unchanged - it is still this generator's
# table, not dc_tunables. data/tunables/README.md says so under "Files with
# their own table".
TUNABLES = MODULE / "data/tunables"
MAX_SLOTS = 36


def quote(value: str) -> str:
    return "'" + str(value).replace("\\", "\\\\").replace("'", "''") + "'"


def render(module: Path = MODULE) -> str:
    with (module / "data/tunables/bags.csv").open(encoding="utf-8-sig", newline="") as stream:
        rows = list(csv.DictReader(stream, strict=True))
    if not rows:
        raise ValueError("bags.csv is empty")
    sql = [# The line below still names data/d3/bags.csv on purpose: bags_0002 has
    # already been applied, and changing one byte of an applied delta is what
    # the guard below refuses. The sheet is at data/tunables/bags.csv now; the
    # next numbered delta is where that comment gets corrected.
    "-- Generated by generate_bags.py; edit data/d3/bags.csv and rerun.",
           "-- Apply to the world database."]
    seen: set[int] = set()
    for row in rows:
        entry, clone = int(row["entry"]), int(row["clone_from"])
        slots, quality, display = int(row["slots"]), int(row["quality"]), int(row["displayid"])
        if entry < 100000 or entry in seen:
            raise ValueError(f"Bag entry must be ours and unique: {row!r}")
        if not 1 <= slots <= MAX_SLOTS:
            raise ValueError(f"A container holds 1 to {MAX_SLOTS} slots: {row!r}")
        if not 0 <= quality <= 7 or display <= 0 or not row["name"] or not row["source"]:
            raise ValueError(f"Invalid bag row: {row!r}")
        seen.add(entry)
        sql += [
            "CREATE TEMPORARY TABLE dc_bag LIKE item_template;",
            f"INSERT INTO dc_bag SELECT * FROM item_template WHERE entry={clone};",
            # BagFamily 0 keeps it a general bag: a family bit would make the
            # client refuse everything but that family, including our items.
            f"UPDATE dc_bag SET entry={entry},name={quote(row['name'])},ContainerSlots={slots},"
            f"displayid={display},Quality={quality},class=1,subclass=0,InventoryType=18,BagFamily=0,"
            # Unbound on purpose: a container is a utility, and leaving it free
            # lets one move between characters through the account stash.
            "bonding=0,stackable=1,maxcount=0,ItemLevel=1,RequiredLevel=0,RequiredSkill=0,"
            "RequiredSkillRank=0,RequiredSpell=0,RequiredHonorRank=0,RequiredCityRank=0,"
            "RequiredReputationFaction=0,RequiredReputationRank=0,MaxDurability=0,BuyPrice=0,"
            "SellPrice=0,Flags=0,FlagsExtra=0,AllowableClass=-1,AllowableRace=-1,"
            f"description={quote('')};",
            "REPLACE INTO item_template SELECT * FROM dc_bag;",
            "DROP TEMPORARY TABLE dc_bag;",
        ]
    return "\n".join(sql) + "\n"


def generate(module: Path = MODULE) -> None:
    sql = render(module)
    mirror = module / "data/generated/bags.sql"
    updates = module / "data/sql/db-world/updates"
    containers = updates / "bags_0001_containers.sql"
    mirror.parent.mkdir(parents=True, exist_ok=True)
    mirror.write_text(sql, encoding="utf-8", newline="\n")
    if not containers.exists():
        write_migration(module, containers, sql)
    elif containers.read_text(encoding="utf-8") != sql:
        # 0001 has been applied and an applied migration is immutable, so the
        # changed value lands as the next numbered migration written by this
        # same generator (2026-09-12, as account_economy and crafting do). The
        # whole render is a REPLACE INTO over a fresh clone, so re-running it
        # is idempotent and carries the new slot count to a migrated database.
        # write_migration refuses an applied 0002 and asks for 0003 instead.
        write_migration(module, updates / "bags_0002_satchel_slots.sql", sql)
    print(f"PASS {sql.count('REPLACE INTO item_template')} container template(s) generated")


if __name__ == "__main__":
    import argparse
    argparse.ArgumentParser(description=__doc__).parse_args()
    generate()
