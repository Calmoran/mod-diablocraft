"""Generate the mapped Blacksmith catalogue. D3 SNOs are stable recipe IDs.

Costs and output IDs come from the supplied D3 archives and current base mapping;
an unmapped ingredient disables a recipe rather than silently dropping its cost.
Legacy slot recipes remain unchanged.
"""
import csv
from pathlib import Path
import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
import scripts_path  # noqa: E402,F401  (R5: every scripts/ folder on sys.path)
from applied_migrations import write_migration, write_coupled_outputs
from generate_crafting import quote

MODULE=Path(__file__).resolve().parents[3]
MIGRATION='crafting_0006_blacksmith_catalog.sql'

def read(name):
    with (MODULE/'data/d3'/name).open(encoding='utf-8-sig',newline='') as f:
        return list(csv.DictReader(f))

def render():
    recipes=read('blacksmith_catalog.csv'); costs=read('blacksmith_catalog_materials.csv')
    bases={r['d3_id']:r for r in read('base_items.csv')}
    ids={r['d3_id']:int(r['item_entry']) for r in read('base_item_ids.csv')}
    material_ids={int(r['item_entry']) for r in read('account_economy.csv') if r['kind']=='material'}
    by_id={}; costkeys=set()
    for r in recipes:
        for key in ('recipe_sno','output_entry','item_level','required_level','gold','enabled'):
            r[key]=int(r[key])
        rid=r['recipe_sno']
        if not 0<rid<=0xffffffff or rid in by_id or not r['source']:
            raise ValueError('Invalid/duplicate recipe identity')
        if (ids.get(r['output_d3_id'])!=r['output_entry'] or r['slot']!=bases[r['output_d3_id']]['slot']
            or r['rarity'] not in ('magic','rare','legendary','set') or r['enabled'] not in (0,1)
            or not 0<r['item_level']<=70 or not 0<r['required_level']<=70 or r['gold']<0
            or r['page'] not in ('weapons','armor')):
            raise ValueError('Unmapped/unsupported recipe output')
        by_id[rid]=r
    for c in costs:
        for k in ('recipe_sno','item_entry','amount'): c[k]=int(c[k])
        key=c['recipe_sno'],c['d3_id']
        if key in costkeys or c['recipe_sno'] not in by_id or not c['source'] or c['amount']<=0:
            raise ValueError('Invalid/duplicate ingredient')
        if c['item_entry'] and c['item_entry'] not in material_ids: raise ValueError('Unknown account material')
        costkeys.add(key)
    for rid,r in by_id.items():
        ingredients=[c for c in costs if c['recipe_sno']==rid]
        if not ingredients or bool(r['enabled'])!=(all(c['item_entry'] for c in ingredients) and r['rarity']!='magic'):
            raise ValueError('Recipe availability disagrees with ingredient coverage')
        if bool(r['unavailable_reason'])==bool(r['enabled']): raise ValueError('Unavailable recipe needs a reason')
    lines=['-- Generated by generate_blacksmith_catalog.py from sourced mapped recipe CSVs.', 'SET NAMES utf8mb4;',
           'CREATE TABLE IF NOT EXISTS dc_blacksmith_catalog (id INT UNSIGNED PRIMARY KEY,output_entry INT UNSIGNED NOT NULL,name VARCHAR(160) NOT NULL,slot VARCHAR(20) NOT NULL,category VARCHAR(40) NOT NULL,page VARCHAR(12) NOT NULL,rarity VARCHAR(20) NOT NULL,item_level INT UNSIGNED NOT NULL,required_level INT UNSIGNED NOT NULL,gold_d3 BIGINT UNSIGNED NOT NULL,enabled TINYINT UNSIGNED NOT NULL,unavailable_reason VARCHAR(160) NOT NULL);',
           'CREATE TABLE IF NOT EXISTS dc_blacksmith_catalog_material (recipe_id INT UNSIGNED NOT NULL,d3_id VARCHAR(80) NOT NULL,item_entry INT UNSIGNED NOT NULL,amount INT UNSIGNED NOT NULL,PRIMARY KEY(recipe_id,d3_id));',
           'DELETE FROM dc_blacksmith_catalog_material;', 'DELETE FROM dc_blacksmith_catalog;']
    for r in sorted(recipes,key=lambda x:x['recipe_sno']):
        fields=('recipe_sno','output_entry','name','slot','category','page','rarity','item_level','required_level','gold','enabled','unavailable_reason')
        lines.append('INSERT INTO dc_blacksmith_catalog VALUES ('+','.join(quote(r[k]) for k in fields)+');')
    for c in sorted(costs,key=lambda x:(x['recipe_sno'],x['d3_id'])):
        lines.append('INSERT INTO dc_blacksmith_catalog_material VALUES ('+','.join(quote(c[k]) for k in ('recipe_sno','d3_id','item_entry','amount'))+');')
    # The two-second bar (blacksmith_cast_seconds) is a data/tunables/crafting.csv row; the tunables generator
    # ships it (tunables_0006), so this migration never writes dc_tunables. Refuse a sheet without it.
    with (MODULE/'data/tunables/crafting.csv').open(encoding='utf-8-sig',newline='') as f:
        timing=[r for r in csv.DictReader(f) if r['name']=='blacksmith_cast_seconds']
    if len(timing)!=1 or float(timing[0]['value'])<=0: raise ValueError('Missing approved craft duration')
    return '\n'.join(lines)+'\n'

def generate():
    text=render(); target=MODULE/'data/sql/db-world/updates'/MIGRATION
    write_migration(MODULE,target,text)
    write_coupled_outputs(MODULE,target,text,[(MODULE/'data/generated/blacksmith_catalog.sql',text)],label='mapped Blacksmith catalogue')
    print('Generated mapped Blacksmith catalogue')

if __name__=='__main__': generate()
