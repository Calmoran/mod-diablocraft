"""Retire the trade skill pilot's rows (decisions.md 2026-10-03 R4).

The pilot (a ruby combine and a shoulders craft through the stock trade skill
window) is gone from the code. The rows it left are listed here by id, the one
place that still names them, and removed from every store that held them:

  * the world database: its four spells, two skill lines, four skill-line
    abilities, two race/class rules and the script bindings of its two recipes
    (world_0013 stays as it was applied; this migration removes what it added),
    plus the Jeweler's unused `economy.jeweler_remove_gold` tunable;
  * the characters database: the spells and skills a character learned from
    them (an unlearned skill is dropped at login by the core anyway, with an
    error line; a spell the server no longer has is skipped with one);
  * the client's Spell, SkillLine, SkillLineAbility and SkillRaceClassInfo DBCs;
  * the generated mirror of world_0013.

A rerun finds nothing left to remove and writes the same bytes.
"""
import argparse
from pathlib import Path

import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
import scripts_path  # noqa: E402,F401  (R5: every scripts/ folder on sys.path)
from applied_migrations import require_companion_migration, write_coupled_outputs, write_migration
from dbc_store import Store, schema

MODULE = Path(__file__).resolve().parents[3]
SPELLS = (85000, 85001, 85002, 85003)           # openers, then recipes
SKILL_LINES = (1000, 1001)
ABILITIES = (30000, 30001, 30002, 30003)
RACE_CLASS_RULES = (1000, 1001)
RECIPE_SPELLS = (85002, 85003)                  # the ones with a script binding
STORES = {'Spell': ('spell_dbc', SPELLS), 'SkillLine': ('skillline_dbc', SKILL_LINES),
          'SkillLineAbility': ('skilllineability_dbc', ABILITIES),
          'SkillRaceClassInfo': ('skillraceclassinfo_dbc', RACE_CLASS_RULES)}
WORLD_MIGRATION = 'world_0029_trade_skill_retired.sql'
CHARACTER_MIGRATION = 'trade_skill_0001_retired.sql'


def ids(values):
    return ','.join(str(v) for v in values)


def world_sql():
    lines = ['-- Generated by generate_trade_skill_retirement.py; never edit.',
             '-- The trade skill pilot is retired (decisions.md 2026-10-03 R4).']
    for table, values in STORES.values():
        lines.append(f'DELETE FROM `{table}` WHERE ID IN ({ids(values)});')
    lines.append(f"DELETE FROM spell_script_names WHERE spell_id IN ({ids(RECIPE_SPELLS)}) "
                 f"AND ScriptName='dc_tradeskill_pilot';")
    lines.append("DELETE FROM dc_tunables WHERE category='economy' AND name='jeweler_remove_gold';")
    return '\n'.join(lines) + '\n'


def character_sql():
    return '\n'.join(['-- Generated by generate_trade_skill_retirement.py; never edit.',
                      '-- A character that learned the pilot\'s openers or recipes forgets them.',
                      f'DELETE FROM character_spell WHERE spell IN ({ids(SPELLS)});',
                      f'DELETE FROM character_skills WHERE skill IN ({ids(SKILL_LINES)});']) + '\n'


def generate(module=MODULE):
    module = Path(module)
    root = module.parent
    client = root / 'client-patch/dbc'
    updates = module / 'data/sql/db-world/updates'
    migration = require_companion_migration(module, updates / WORLD_MIGRATION, updates)
    text = world_sql()
    outputs = {}
    for name, (table, values) in STORES.items():
        path = client / f'{name}.dbc'
        store = Store(path.read_bytes(), schema(root, table))
        before = len(store.rows)
        for key in values:
            store.rows.pop(key, None)
        if len(store.rows) != before:
            outputs[path] = store.bytes()
    mirror = module / 'data/generated/tradeskill_pilot.sql'
    write_migration(module, migration, text)
    write_migration(module, module / 'data/sql/db-characters/updates' / CHARACTER_MIGRATION, character_sql())
    write_coupled_outputs(module, migration, text, list(outputs.items()),
                          label='Trade skill retirement: client DBCs')
    if mirror.exists():
        mirror.unlink()
    print(f'Trade skill pilot retired: {len(outputs)} client DBC(s) changed.')
    return outputs


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--module-root', type=Path, default=MODULE)
    generate(parser.parse_args().module_root)
