from generate_numeric_data import CELLS


def recipe_rows():
    gems = read('gems.csv')
    mapping = gem_items(MODULE, gems)
    entries = {(r['colour'], r['tier']): mapping[r['gem_id'], r['tier']]
               for r in gems if r['is_legendary'] == '0'}
    rows = []
    operations = {}
    for r in read('jeweler.csv'):
        if r['row_type'] not in ('gem_combine', 'unsocket'):
            continue
        identity = r.get('operation_id', '')
        if not identity or identity in operations:
            raise ValueError(f'Missing or duplicate Jeweler operation ID: {identity!r}')
        operations[identity] = r
    for r in operations.values():
        if r['row_type'] != 'gem_combine':
            continue
        tier, input_tier = r.get('output_tier', ''), r.get('input_tier', '')
        count = number(r, 'input_count')
        if (tier not in TIERS or input_tier not in TIERS
                or TIERS.index(tier) != TIERS.index(input_tier)+1 or count <= 0):
            raise ValueError(f'Invalid combine row: {r}')
        for colour in sorted({colour for colour, _ in entries}):
            rows.append((entries[colour, tier], entries[colour, input_tier], count,
                         number(r, 'gold'), number(r, 'deaths_breath')))
    if len(rows) != 45 or len({r[0] for r in rows}) != 45:
        raise ValueError('Expected nine combines for each of five normal colours')
    unsocket = operations.get(CELLS['jeweler_unsocket_gold'][2])
    if unsocket is None or unsocket['row_type'] != 'unsocket':
        raise ValueError('Expected one keyed current unsocket price')
    number(unsocket, 'gold')  # Runtime price is generated as dc_numeric_rule.jeweler_unsocket_gold.
    return rows


def drop_rows():
    result = []
    tiers = read('difficulty_tiers.csv')
    # Stable project IDs join the named D3 tier; CSV/header order has no role.
    tier_ids = difficulty_tiers(MODULE, tiers)
    for r in read('gem_drops.csv'):
        if r['source'] not in ('normal_monster', 'normal_monster (Master+)') or r['chance_pct'] == 'does not drop':
            continue
        tier = 'Normal' if r['gem_tier'] == 'Regular' else r['gem_tier']
        if tier not in TIERS:
            raise ValueError(f'Unknown gem drop tier: {r}')
        result.append((number(r, 'min_level'), number(r, 'max_level'),
                       tier_ids['Master'] if '(Master+)' in r['source'] else tier_ids['Normal'], tier))
    if len(result) != 6:
        raise ValueError('Expected five baseline level brackets and the Master+ Imperial row')
    return result


def write(name, sql, database='world'):
    content = '\n'.join(sql)+'\n'
    (MODULE / 'data/generated' / name).write_text(content, encoding='utf-8', newline='\n')
    write_migration(MODULE, MODULE / f'data/sql/db-{database}/updates' / name, content)


def generate():
    sql = ['-- Generated by generate_sql.py --jeweler from jeweler.csv, gems.csv and gem_drops.csv.',
           '-- All combine tiers unlocked; no jewelry, training or legendary gems.']
    sql += table('dc_jeweler_recipe', 'output_entry INT PRIMARY KEY,input_entry INT NOT NULL,input_count INT NOT NULL,gold_d3 INT NOT NULL,deaths_breath INT NOT NULL', recipe_rows())
    sql += table('dc_gem_drop', 'min_level INT NOT NULL,max_level INT NOT NULL,min_tier INT NOT NULL,gem_tier VARCHAR(40) NOT NULL,PRIMARY KEY(min_level,min_tier)', drop_rows())
    outputs = [('crafting_0002_jeweler.sql', sql, 'world'), ('loot_0003_buffer_kind.sql',
                ['-- Generated by generate_sql.py --jeweler; existing buffers remain rolled items.'] +
                ensure_column('dc_loot_buffer', 'kind', "VARCHAR(16) NOT NULL DEFAULT 'rolled'"), 'characters')]
    tuning = [r for r in read('loot_tuning.csv', TUNABLES) if r['source'] == 'gem']
    if len(tuning) != 1 or "the designer's tunables" not in tuning[0]['notes']:
        raise ValueError('Expected one explicitly marked the designer gem-tuning row')
    r = tuning[0]
    sql = ['-- Generated by generate_sql.py --jeweler from loot_tuning.csv; tunables, not published rates.']
    for key in ('gem_chance_pct', 'gem_imperial_share_pct'):
        value = Decimal(r[key])
        if not value.is_finite() or not 0 <= value <= 100:
            raise ValueError(f'Invalid {key}')
        sql += ensure_column('dc_loot_tuning', key, 'DOUBLE NULL')
    sql += ["DELETE FROM dc_loot_tuning WHERE source='gem';",
            'INSERT INTO dc_loot_tuning(source,notes,gem_chance_pct,gem_imperial_share_pct) VALUES ('+
            ','.join((quote('gem'),quote(r['notes']),r['gem_chance_pct'],r['gem_imperial_share_pct']))+');']
    outputs.append(('loot_0004_gem_tuning.sql', sql, 'world'))
    from generate_sql import TABLES, render_table
    full_tuning, _ = render_table(MODULE/'data/tunables/loot_tuning.csv', TABLES['loot_tuning'])
    for name, sql, database in outputs:
        write(name, sql, database)
    (MODULE/'data/generated/loot_tuning.sql').write_text(full_tuning, encoding='utf-8', newline='\n')
    print('Jeweler: 45 combines, six drop eligibility rows, typed loot buffer')


if __name__ == '__main__':
    import argparse
    argparse.ArgumentParser(description=__doc__).parse_args()
    generate()
