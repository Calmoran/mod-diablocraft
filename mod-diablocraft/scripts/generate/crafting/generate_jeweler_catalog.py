"""Generate the Jeweler's Craft Jewelry catalogue: Sovereign Amulet and Ring, Hellfire Ring and Amulet, and the four
Infernal Machine organs the Hellfire recipes spend.

Costs and output ids come from D3's RecipesJeweler.gam (data/d3/jeweler_catalog.csv); the tables mirror the
Blacksmith's mapped catalogue so Craft() reads either one. A recipe is enabled only when every ingredient is an item
Torment has; a missing one disables it with a reason. The organs are plain bag items with no drop source yet
(data/d3/hellfire_organs.csv).
"""
import csv
from pathlib import Path
import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
import scripts_path  # noqa: E402,F401  (R5: every scripts/ folder on sys.path)
from applied_migrations import write_migration, write_coupled_outputs
from generate_crafting import quote
from persistent_ids import gem_items

MODULE=Path(__file__).resolve().parents[3]
MIGRATION='crafting_0010_jeweler_catalog.sql'
PAGES={'neck':'amulets','finger':'rings'}
REASON_COLUMN=160
MAIN_STATS=('','str','dex','int')

def read(name):
    with (MODULE/'data/d3'/name).open(encoding='utf-8-sig',newline='') as f:
        return list(csv.DictReader(f))

def render():
    recipes=read('jeweler_catalog.csv'); costs=read('jeweler_catalog_materials.csv')
    bases={r['d3_id']:r for r in read('base_items.csv')}
    ids={r['d3_id']:int(r['item_entry']) for r in read('base_item_ids.csv')}
    held={int(r['item_entry']) for r in read('account_economy.csv') if r['kind']=='material'}
    held|=set(gem_items(MODULE,read('gems.csv')).values())
    organs=read('hellfire_organs.csv')
    for o in organs:
        for key in ('item_entry','displayid','item_level','max_stack'): o[key]=int(o[key])
        if not o['name'] or not o['source'] or not 0<o['max_stack']<=0x7fffffff or o['item_entry'] in held:
            raise ValueError('Invalid organ item: '+o['d3_id'])
        held.add(o['item_entry'])
    by_id={}; costkeys=set()
    for r in recipes:
        for key in ('recipe_sno','output_entry','item_level','required_level','gold','enabled'):
            r[key]=int(r[key])
        rid=r['recipe_sno']
        if not 0<rid<=0xffffffff or rid in by_id or not r['source']:
            raise ValueError('Invalid/duplicate recipe identity')
        base=bases.get(r['output_d3_id'])
        if (not base or ids.get(r['output_d3_id'])!=r['output_entry'] or r['slot']!=base['slot'] or base['pool_version']!='yes'
            or PAGES.get(r['slot'])!=r['page'] or r['rarity'] not in ('rare','legendary') or r['enabled'] not in (0,1)
            or not 0<r['item_level']<=70 or not 0<r['required_level']<=70 or r['gold']<0):
            raise ValueError('Unmapped/unsupported recipe output: '+r['recipe'])
        if r['main_stat'] not in MAIN_STATS or (r['main_stat'] and r['slot']!='neck'):
            raise ValueError('Invalid main stat: '+r['recipe'])
        if len(r['unavailable_reason'])>REASON_COLUMN:
            raise ValueError('Unavailable reason is longer than its column: '+r['recipe'])
        by_id[rid]=r
    for c in costs:
        for k in ('recipe_sno','item_entry','amount'): c[k]=int(c[k])
        key=c['recipe_sno'],c['d3_id']
        if key in costkeys or c['recipe_sno'] not in by_id or not c['source'] or c['amount']<=0:
            raise ValueError('Invalid/duplicate ingredient')
        if c['item_entry'] and c['item_entry'] not in held: raise ValueError('Unknown material or gem item')
        costkeys.add(key)
    for rid,r in by_id.items():
        ingredients=[c for c in costs if c['recipe_sno']==rid]
        if not ingredients or bool(r['enabled'])!=all(c['item_entry'] for c in ingredients):
            raise ValueError('Recipe availability disagrees with ingredient coverage: '+r['recipe'])
        if bool(r['unavailable_reason'])==bool(r['enabled']): raise ValueError('Unavailable recipe needs a reason')
    lines=['-- Generated by generate_jeweler_catalog.py from sourced Jeweler recipe CSVs.', 'SET NAMES utf8mb4;',
           'CREATE TABLE IF NOT EXISTS dc_jeweler_catalog (id INT UNSIGNED PRIMARY KEY,output_entry INT UNSIGNED NOT NULL,name VARCHAR(160) NOT NULL,slot VARCHAR(20) NOT NULL,category VARCHAR(40) NOT NULL,page VARCHAR(12) NOT NULL,rarity VARCHAR(20) NOT NULL,item_level INT UNSIGNED NOT NULL,required_level INT UNSIGNED NOT NULL,gold_d3 BIGINT UNSIGNED NOT NULL,main_stat VARCHAR(3) NOT NULL,enabled TINYINT UNSIGNED NOT NULL,unavailable_reason VARCHAR(%d) NOT NULL);'%REASON_COLUMN,
           'CREATE TABLE IF NOT EXISTS dc_jeweler_catalog_material (recipe_id INT UNSIGNED NOT NULL,d3_id VARCHAR(80) NOT NULL,item_entry INT UNSIGNED NOT NULL,amount INT UNSIGNED NOT NULL,PRIMARY KEY(recipe_id,d3_id));',
           'DELETE FROM dc_jeweler_catalog_material;', 'DELETE FROM dc_jeweler_catalog;']
    for r in sorted(recipes,key=lambda x:x['recipe_sno']):
        fields=('recipe_sno','output_entry','name','slot','category','page','rarity','item_level','required_level','gold','main_stat','enabled','unavailable_reason')
        lines.append('INSERT INTO dc_jeweler_catalog VALUES ('+','.join(quote(r[k]) for k in fields)+');')
    for c in sorted(costs,key=lambda x:(x['recipe_sno'],x['d3_id'])):
        lines.append('INSERT INTO dc_jeweler_catalog_material VALUES ('+','.join(quote(c[k]) for k in ('recipe_sno','d3_id','item_entry','amount'))+');')
    # Plain bag items (class Misc), stacked as D3's item table has them; entries are project ids.
    lines+=['DELETE FROM item_template WHERE entry IN (%s);'%','.join(str(o['item_entry']) for o in organs),
            'INSERT INTO item_template (entry,class,subclass,name,displayid,Quality,Flags,BuyCount,BuyPrice,SellPrice,InventoryType,maxcount,stackable,BagFamily,bonding,ItemLevel,description) VALUES']
    values=["(%d,15,0,%s,%d,1,0,1,0,0,0,0,%d,0,0,%d,%s)"%(o['item_entry'],quote(o['name']),o['displayid'],o['max_stack'],o['item_level'],quote('Spent at the Jeweler on the Hellfire Ring and Amulet.')) for o in organs]
    lines+=[',\n'.join(values)+';']
    return '\n'.join(lines)+'\n'

def generate():
    text=render(); target=MODULE/'data/sql/db-world/updates'/MIGRATION
    write_migration(MODULE,target,text)
    write_coupled_outputs(MODULE,target,text,[(MODULE/'data/generated/jeweler_catalog.sql',text)],label='Jeweler catalogue')
    print('Generated Jeweler catalogue')

if __name__=='__main__': generate()
