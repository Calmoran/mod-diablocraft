ROOT = Path(__file__).resolve().parents[3]
# FROZEN since the hub moved to the Sanctum of Torment (diablocraft-976b): this generator wrote the applied
# world_0005 for Scryer's Tier. Its hub inputs are the old hub's data (tests/scryer_hub); the live files of the
# same names now describe the Sanctum, and generate_hub_sanctum_move.py reads those.
FROZEN = {'world_hub_points.csv', 'world_areas.csv', 'world_hub_native_spawns.csv'}


def read(name):
    with ((LEGACY if name in FROZEN else ROOT / 'data/d3') / name).open(encoding='utf-8-sig', newline='') as stream:
        return list(csv.DictReader(stream))


def point_rows():
    rows = read('world_hub_points.csv')
    if len(rows) != 3 or {r['name'] for r in rows} != {'spawn', 'town_portal', 'rift_exit'}:
        raise ValueError('Exactly spawn, town_portal and rift_exit are required')
    for row in rows:
        for key in ('x', 'y', 'z'):
            row[key] = str(tunable_value('ui', f"hub_{row['name']}_{key}_yards", module=ROOT))
        for key in ('map_id', 'area_id'):
            if not row[key].isdigit() or not 0 <= int(row[key]) < 2**32:
                raise ValueError(f'Invalid {key}: {row}')
        for key in ('x', 'y', 'z', 'o'):
            if not Decimal(row[key]).is_finite():
                raise ValueError(f'Non-finite {key}: {row}')
        if not row['source']:
            raise ValueError('GPS source is required')
    if len({(r['map_id'], r['area_id']) for r in rows}) != 1:
        raise ValueError('Hub points must share a map and area')
    return rows


def generate(db):
    points = point_rows()
    spawn = next(r for r in points if r['name'] == 'spawn')
    map_id, area_id = int(spawn['map_id']), int(spawn['area_id'])
    rules = read('world_areas.csv')
    if not any(r['map_id'] == str(map_id) and r['area_id'] == str(area_id)
               and r['status'] == 'open' and r['phase_scope'] == 'all' for r in rules):
        raise ValueError('The supplied hub area must be open in all phases')
    former = [r for r in rules if r['note'] == 'Former GM Island hub']
    if len(former) != 1 or former[0]['status'] != 'closed':
        raise ValueError('GM Island must be closed')
    native = read('world_hub_native_spawns.csv')
    seen = set()
    for r in native:
        key = r['kind'], int(r['guid'])
        if r['kind'] not in ('c', 'g') or key in seen or key[1] <= 0:
            raise ValueError(f'Invalid or duplicate surveyed spawn: {r}')
        if (int(r['map_id']), int(r['area_id'])) != (map_id, area_id) or not r['source']:
            raise ValueError(f'Survey outside the approved hub area: {r}')
        if 910000 <= int(r['entry']) <= 910013:
            raise ValueError('Survey must not remove Diablocraft services or portals')
        seen.add(key)
    if not native:
        raise ValueError('Missing core-resolved native spawn survey')

    sql = ['-- Generated by generate_hub_relocation.py; apply with worldserver stopped.',
           '-- Sources: world_hub_points.csv, world_hub_native_spawns.csv, world_areas.csv, world_hub_services.csv.',
           '-- Removes only surveyed native placements, never terrain/WMO scenery or templates.',
           'SET NAMES utf8mb4;',
           'CREATE TABLE IF NOT EXISTS dc_world_hub_point (name VARCHAR(32) PRIMARY KEY,map_id INT UNSIGNED NOT NULL,area_id INT UNSIGNED NOT NULL,x DOUBLE NOT NULL,y DOUBLE NOT NULL,z DOUBLE NOT NULL,o DOUBLE NOT NULL);',
           'CREATE TEMPORARY TABLE dc_hub_native (kind CHAR(1),guid INT UNSIGNED,entry INT UNSIGNED,PRIMARY KEY(kind,guid));',
           'INSERT INTO dc_hub_native VALUES\n' + ',\n'.join(
               f"('{r['kind']}',{int(r['guid'])},{int(r['entry'])})" for r in native) + ';']
    for kind, table in (('c', 'creature'), ('g', 'gameobject')):
        victims = f'dc_hub_remove_{kind}'
        sql.append(f"CREATE TEMPORARY TABLE {victims} AS SELECT s.guid FROM {table} s JOIN dc_hub_native n ON n.kind='{kind}' AND n.guid=s.guid AND n.entry=s.id WHERE s.map={map_id};")
        relations = dict(SIMPLE[kind])
        relations.update({f'pool_{table}': 'guid', f'game_event_{table}': 'guid'})
        if kind == 'c':
            relations.update({t: 'guid' for t in ('game_event_model_equip', 'game_event_npc_vendor', 'game_event_npcflag')})
        for related, column in relations.items():
            sql.append(f'DELETE s FROM `{related}` s JOIN {victims} v ON v.guid=s.`{column}`;')
        sql += [f'DELETE s FROM spawn_group s JOIN {victims} v ON v.guid=s.spawnId WHERE s.spawnType={0 if kind == "c" else 1};',
                f'DELETE s FROM smart_scripts s JOIN {victims} v ON s.entryorguid=-CAST(v.guid AS SIGNED) WHERE s.source_type={0 if kind == "c" else 1};',
                f'DELETE s FROM conditions s JOIN {victims} v ON s.SourceEntry=-CAST(v.guid AS SIGNED) WHERE s.SourceTypeOrReferenceId=22 AND s.SourceId={0 if kind == "c" else 1};',
                f'DELETE s FROM conditions s JOIN {victims} v ON s.ConditionValue3=v.guid WHERE s.ConditionTypeOrReference=31 AND s.ConditionValue1={3 if kind == "c" else 5};']
    for column in ('leaderGUID', 'memberGUID'):
        sql.append(f'DELETE s FROM creature_formations s JOIN dc_hub_remove_c v ON v.guid=s.{column};')
    for kind in ('c', 'g'):
        for column, types in (('guid', '0,1' if kind == 'c' else '2,3'), ('linkedGuid', '0,3' if kind == 'c' else '1,2')):
            sql.append(f'DELETE s FROM linked_respawn s JOIN dc_hub_remove_{kind} v ON v.guid=s.{column} WHERE s.linkType IN ({types});')
    for kind, table in (('c', 'creature'), ('g', 'gameobject')):
        sql += [f"DELETE s FROM dc_area_source s JOIN dc_hub_remove_{kind} v ON v.guid=s.source_guid WHERE s.kind='{kind}';",
                f"DELETE s FROM dc_area_spawn s JOIN dc_hub_remove_{kind} v ON v.guid=s.spawn_guid WHERE s.kind='{kind}';",
                f'DELETE s FROM {table} s JOIN dc_hub_remove_{kind} v ON v.guid=s.guid;']
    sql.append(render_world_areas(LEGACY / 'world_areas.csv')[0])
    for r in points:
        values = ','.join(r[k] for k in ('map_id', 'area_id', 'x', 'y', 'z', 'o'))
        sql.append(f"REPLACE INTO dc_world_hub_point VALUES('{r['name']}',{values});")
    sql += ["REPLACE INTO dc_world_hub SELECT 1,map_id,area_id,x,y,z,o FROM dc_world_hub_point WHERE name='spawn';",
            "UPDATE playercreateinfo c JOIN dc_world_hub_point p ON p.name='spawn' SET c.map=p.map_id,c.zone=p.area_id,c.position_x=p.x,c.position_y=p.y,c.position_z=p.z,c.orientation=p.o WHERE c.class=1;"]
    for service in read('world_hub_services.csv'):
        entry, source = int(service['entry']), int(service['clone_entry'])
        row = db.rows('creature_template', f'entry={source}')[0]
        row.update(entry=entry, name=service['name'], npcflag=int(service['npcflag']),
                   ScriptName=service['script'], AIName='', subname=service['subname'],
                   minlevel=int(service['level']), maxlevel=int(service['level']))
        sql += [f'DELETE FROM creature_template WHERE entry={entry};', insert('creature_template', row),
                f'DELETE FROM creature_template_model WHERE CreatureID={entry};']
        for model in db.rows('creature_template_model', f'CreatureID={source}'):
            sql.append(insert('creature_template_model', dict(model, CreatureID=entry)))
    sql += ['DROP TEMPORARY TABLE dc_hub_remove_c,dc_hub_remove_g,dc_hub_native;', '']
    return '\n'.join(sql)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--mysql', required=True)
    parser.add_argument('--defaults-file', required=True)
    args = parser.parse_args()
    sql = generate(Database(args.mysql, args.defaults_file, 'acore_world'))
    (ROOT / 'data/generated/world_0005_shattrath_hub.sql').write_text(sql, encoding='utf-8', newline='\n')
    write_migration(ROOT, ROOT / 'data/sql/db-world/updates/world_0005_shattrath_hub.sql', sql)
    print('Generated world_0005_shattrath_hub.sql')
