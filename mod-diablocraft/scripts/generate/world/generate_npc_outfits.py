#!/usr/bin/env python3
"""NPC outfits (diablocraft-0prr): data/outfits/npc_outfits.csv -> the world table and its rows.

One row per creature entry: race, gender, skin, face, hair, hair colour, facial hair and one item
entry per visible slot (0 = nothing), as the server's mirror-image answer sends them
(src/common/dc_world_outfits.h). `addon_auras` (space-separated spell ids) goes to the stock
creature_template_addon.auras of the same entry, because an NPC's shirt carries no spell.
The CSV wins on every apply. A removed row stays in the database until someone deletes it.

Run from the repo root:  python mod-diablocraft/scripts/generate/world/generate_npc_outfits.py
"""
import csv
from pathlib import Path

import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
import scripts_path  # noqa: E402,F401  (R5: every scripts/ folder on sys.path)
from applied_migrations import write_migration

MODULE = Path(__file__).resolve().parents[3]
SOURCE = MODULE / 'data/outfits/npc_outfits.csv'
GENERATED = MODULE / 'data/generated'
UPDATES = MODULE / 'data/sql/db-world/updates'
# The visible slots, in the order the client's mirror-image data lists them.
SLOTS = ('head', 'shoulders', 'shirt', 'chest', 'waist', 'legs', 'feet', 'wrists', 'hands', 'back', 'tabard')
LOOKS = ('race', 'gender', 'skin', 'face', 'hair', 'hair_color', 'facial_hair')
COLUMNS = ('entry',) + LOOKS + SLOTS
# Constant (identifiers, not game magnitudes): player race ids and the two genders of the 3.3.5 client.
RACES = range(1, 12)
GENDERS = (0, 1)
BYTE = 255
SCHEMA_NAME = 'outfits_0001_npc_outfit_schema.sql'
ROWS_NAME = 'outfits_0003_npc_outfits.sql'  # 0002 is applied and frozen; each rows migration carries the whole sheet as an upsert


def read():
    with SOURCE.open(encoding='utf-8-sig', newline='') as stream:
        return list(csv.DictReader(stream))


def number(row, key, high):
    try:
        value = int(row[key])
    except (TypeError, ValueError):
        raise ValueError(f"entry {row.get('entry')}: {key} must be a whole number, got {row.get(key)!r}")
    if not 0 <= value <= high:
        raise ValueError(f"entry {row['entry']}: {key} {value} is outside 0..{high}")
    return value


def validate(rows):
    seen = set()
    for row in rows:
        entry = number(row, 'entry', 2 ** 32 - 1)
        if entry in seen:
            raise ValueError(f'entry {entry} appears twice')
        seen.add(entry)
        if number(row, 'race', BYTE) not in RACES:
            raise ValueError(f'entry {entry}: race {row["race"]} is not a player race')
        if number(row, 'gender', BYTE) not in GENDERS:
            raise ValueError(f'entry {entry}: gender must be 0 (male) or 1 (female)')
        for key in LOOKS[2:]:
            number(row, key, BYTE)
        for key in SLOTS:
            number(row, key, 2 ** 32 - 1)
        for aura in row['addon_auras'].split():
            if not aura.isdigit() or int(aura) == 0:
                raise ValueError(f'entry {entry}: addon_auras holds spell ids, got {aura!r}')
    return rows


def quote(value):
    return "'" + value.replace('\\', '\\\\').replace("'", "''") + "'"


def render():
    rows = validate(read())
    schema = '\n'.join([
        '-- Generated by generate_npc_outfits.py; do not hand-edit.',
        '-- WORLD database: what an NPC wears, sent through the client mirror-image data.',
        'CREATE TABLE IF NOT EXISTS dc_npc_outfit (',
        "  entry INT UNSIGNED NOT NULL PRIMARY KEY COMMENT 'creature_template.entry',",
        *(f'  {key} TINYINT UNSIGNED NOT NULL DEFAULT 0,' for key in LOOKS),
        *(f"  {key} INT UNSIGNED NOT NULL DEFAULT 0 COMMENT 'item_template.entry, 0 = nothing'," for key in SLOTS),
        '  notes TEXT NOT NULL',
        ');', ''])
    lines = ['-- Generated by generate_npc_outfits.py; do not hand-edit.', 'SET NAMES utf8mb4;']
    values = ',\n'.join('(' + ','.join([*(row[key] for key in COLUMNS), quote(row['notes'])]) + ')' for row in rows)
    lines += ['INSERT INTO dc_npc_outfit (' + ','.join(COLUMNS) + ',notes) VALUES', values,
              'ON DUPLICATE KEY UPDATE ' + ','.join(f'{key}=VALUES({key})' for key in COLUMNS[1:] + ('notes',)) + ';']
    auras = [row for row in rows if row['addon_auras'].split()]
    if auras:
        lines += ['INSERT INTO creature_template_addon (entry,auras) VALUES',
                  ',\n'.join(f"({row['entry']},{quote(' '.join(row['addon_auras'].split()))})" for row in auras),
                  'ON DUPLICATE KEY UPDATE auras=VALUES(auras);']
    return schema, '\n'.join(lines) + '\n'


def main():
    schema, seed = render()  # Validate everything before writing anything.
    GENERATED.mkdir(parents=True, exist_ok=True)
    for name, text in ((SCHEMA_NAME, schema), (ROWS_NAME, seed)):
        (GENERATED / name).write_text(text, encoding='utf-8')
        write_migration(MODULE, UPDATES / name, text)
        print('Generated ' + name)


if __name__ == '__main__':
    import argparse
    argparse.ArgumentParser(description=__doc__).parse_args()
    main()
