#!/usr/bin/env python3
"""Generate the Rift Keeper's tooltip fix (diablocraft-smzk): no subname, level 70.

creature_template 910003 was cloned from the stock Blacksmith, so its tooltip read the donor's subname
'Macecrafter' at the donor's level 42 (world_0005). The subname and level cells of world_hub_services.csv are the
source; this writes the one UPDATE that puts them on the live row. world_0005 stays as it shipped (applied-migration guard).

    python3 mod-diablocraft/scripts/generate/world/generate_hub_keeper_tooltip.py
"""
import csv
from pathlib import Path

import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
import scripts_path  # noqa: E402,F401  (R5: every scripts/ folder on sys.path)
from applied_migrations import write_coupled_outputs, write_migration
from generate_rifts import quote

ROOT = Path(__file__).resolve().parents[3]
CSV = ROOT / "data/d3/world_hub_services.csv"
NAME = "world_0033_rift_keeper_tooltip.sql"


def render(path=CSV):
    rows = [r for r in csv.DictReader(path.open(encoding="utf-8-sig", newline="")) if r["entry"] == "910003"]
    if len(rows) != 1 or not rows[0]["level"].isdigit():
        raise ValueError("world_hub_services.csv needs one Rift Keeper row (910003) with a whole-number level")
    row = rows[0]
    return "\n".join([
        "-- Generated by generate_hub_keeper_tooltip.py from world_hub_services.csv; never edit.",
        "-- the designer on dev 2026-10-05 (diablocraft-smzk): the Rift Keeper's tooltip read the Blacksmith donor's subname; it has none, and is level 70.",
        f"UPDATE `creature_template` SET `subname` = {quote(row['subname'])}, `minlevel` = {row['level']}, `maxlevel` = {row['level']} WHERE `entry` = 910003;",
        ""])


if __name__ == "__main__":
    sql = render()
    updates = ROOT / "data/sql/db-world/updates" / NAME
    write_migration(ROOT, updates, sql)
    write_coupled_outputs(ROOT, updates, sql, [(ROOT / "data/generated" / NAME, sql)])
    print(f"Generated {NAME}")
