"""diablocraft-xw2m return, review point 6: the Mystic's server functions run, not read.

test_mystic_enchant.py checks the rules header and, for the rest of src/crafting, the wiring as text. This
suite runs the module's own Pick, MysticState and StoredOffers (with Need, AffixRow, Affix, AsPick and Shown),
cut out of src/crafting/dc_crafting_shared.cpp and dc_mystic.cpp exactly as they are, against doubles for the core
(tests/mystic_crafting/). The rules header, the Items::Instance / Affix types and the window records are the
real ones. Proved by execution:

  * Pick with choice 1, 2 and 3 on a stored offer: 1 leaves the item's rows alone, 2 and 3 write the stored
    roll (value, ranges, value2 and its bracket), the offer is deleted, nothing is charged;
  * choice 0 and 4, and an empty offer, are refused with nothing saved;
  * a damage line only becomes a damage line: an offer stored before the rebuild (one part each) cannot replace it;
  * MysticState's bind flag on boundAccount 0 and set, and a pending state that leads with the line as it is on
    the item (an old two-row offer included);
  * the stored choices come back from the characters table alone (a relog).

Each rule has a mutant that must turn a named scenario red. Not covered: Roll (its draws and charge are the
GM script in docs/test-diablocraft-xw2m.md; the rules it calls are in test_mystic_enchant.py), the real
database and the core's transaction.
"""
import shutil
import subprocess
import unittest
from pathlib import Path

import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
import scripts_path  # noqa: E402,F401  (R5: every scripts/ folder on sys.path)
import crafting_source
import harness_env

REPO_ROOT = Path(__file__).resolve().parents[4]
MODULE = REPO_ROOT / "mod-diablocraft"
HARNESS = MODULE / "tests" / "mystic_crafting"
# The functions it cuts out live in two files: the shared helpers and the Mystic.
MYSTIC_FILES = ("dc_crafting_shared.cpp", "dc_mystic.cpp")
# Scratch belongs in the build tree (AGENTS.md), not the system temp.
SCRATCH = REPO_ROOT / "azerothcore-wotlk" / "build" / "_agent-scratch" / "mystic_crafting"

# In the order the module has them; each is the whole function, braces balanced.
FUNCTIONS = (
    "void Need(bool ok, char const* message)",
    "void AffixRow(CharacterDatabaseTransaction const& tx, uint64 guid, Items::Affix const& a)",
    "Items::Affix const& Affix(Items::Instance const& item, uint32 seq)",
    "std::vector<StoredOffer> StoredOffers(uint64 guid)",
    "void NeedMysticItem(Items::Instance const& instance)",
    "Enchant::Pick AsPick(Items::Affix const& a)",
    "Window::EnchantAffix Shown(Enchant::Pick const& p, int state = 0)",
    "Window::EnchantState MysticState(Player* player, uint32 guid)",
    "void Pick(Player* player, uint32 guid, uint32 choice)",
)
STRUCT = "struct StoredOffer"
BEFORE_STORED_OFFERS = "std::vector<StoredOffer> StoredOffers(uint64 guid)"


def definition(marker, source):
    assert source.count(marker) == 1, "%r is not unique in dc_crafting_shared.cpp and dc_mystic.cpp (%d)" % (marker, source.count(marker))
    start = source.index(marker)
    end = source.index("{", start) + 1
    depth = 1
    while depth:
        depth += (source[end] == "{") - (source[end] == "}")
        end += 1
    return source[start:end]


def extract(source):
    pieces = []
    for marker in FUNCTIONS:
        if marker == BEFORE_STORED_OFFERS:
            pieces.append(definition(STRUCT, source) + ";")
        pieces.append(definition(marker, source))
    return ("// Generated by scripts/tests/crafting/test_mystic_crafting.py from the module's own source. Do not edit.\n"
            "#pragma once\nnamespace DC::Crafting\n{\nnamespace\n{\n" + "\n\n".join(pieces)
            + "\n} // namespace\n} // namespace DC::Crafting\n")


def mutate(text, old, new):
    assert text.count(old) == 1, "mutation target %r occurs %d times" % (old, text.count(old))
    return text.replace(old, new)


def mutate_in(source, marker, old, new):
    """The mutation applied inside one function only: the same words occur in the module's other functions."""
    return mutate(source, definition(marker, source), mutate(definition(marker, source), old, new))


STORED_OFFERS = "std::vector<StoredOffer> StoredOffers(uint64 guid)"
MYSTIC_STATE = "Window::EnchantState MysticState(Player* player, uint32 guid)"


class MysticCrafting(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.compiler = shutil.which("c++") or shutil.which("g++")
        if not cls.compiler:
            raise unittest.SkipTest("no C++ compiler")
        cls.source = "\n".join(crafting_source.read(name) for name in MYSTIC_FILES)
        cls.pick = definition("void Pick(Player* player, uint32 guid, uint32 choice)", cls.source)
        assert str(SCRATCH).startswith(str(REPO_ROOT / "azerothcore-wotlk" / "build" / "_agent-scratch"))

    def build_and_run(self, variant, source):
        folder = SCRATCH / variant
        folder.mkdir(parents=True, exist_ok=True)
        (folder / "dc_mystic_extract.h").write_text(extract(source), encoding="utf-8")
        binary = folder / "mystic_crafting"
        if binary.exists():
            binary.unlink()
        built = subprocess.run(
            [self.compiler, "-std=c++17", "-O0", "-UNDEBUG", "-I", str(folder), "-I", str(HARNESS / "shim"),
             "-I", str(HARNESS), "-I", str(MODULE / "src" / "crafting"), "-I", str(MODULE / "src" / "common"),
             "-I", str(MODULE / "src" / "items"), str(HARNESS / "mystic_crafting_harness.cpp"), "-o", str(binary)],
            capture_output=True, text=True)
        if built.returncode:
            raise AssertionError("the harness did not compile for %s:\n%s" % (variant, built.stderr[-5000:]))
        ran = harness_env.run([str(binary)], capture_output=True, text=True)
        results = {}
        for line in ran.stdout.splitlines():
            if line.startswith("PASS "):
                results[line[5:]] = True
            elif line.startswith("FAILED "):
                results[line[7:]] = False
        return ran.returncode, results, ran.stdout + ran.stderr

    def assertRed(self, variant, source, scenarios):
        code, results, output = self.build_and_run(variant, source)
        self.assertNotEqual(code, 0, "%s: the harness still passed" % variant)
        for scenario in scenarios:
            # A mutant that crashes the harness (an offer index out of range) never prints the scenario: also red.
            self.assertIsNot(results.get(scenario), True, "%s: %r stayed green:\n%s" % (variant, scenario, output[-3000:]))

    def test_the_production_functions_pass(self):
        code, results, output = self.build_and_run("production", self.source)
        self.assertEqual(code, 0, output[-3000:])
        self.assertGreaterEqual(len(results), 24, output)
        self.assertTrue(all(results.values()), output)

    # ---- one mutant per rule -------------------------------------------------------------

    def test_pick_must_charge_nothing(self):
        text = mutate(self.source, self.pick, mutate(self.pick, "auto tx = PlayerEconomy::BeginTransaction();",
                                                     "auto tx = PlayerEconomy::BeginTransaction();\n"
                                                     "            Need(Economy::Charge(player, 1), \"x\");"))
        self.assertRed("charges", text, ["pick 1: nothing charged, no price read, no contributions touched",
                                         "pick 2: the offer is deleted and nothing is charged"])

    def test_choice_one_must_keep_the_line(self):
        text = mutate(self.source, self.pick, mutate(self.pick, "if (choice > 1)\n            {",
                                                     "if (choice > 0)\n            {"))
        self.assertRed("keep-replaces", text, ["pick 1: only the offer is deleted, the item's rows are left"])

    def test_choices_two_and_three_are_the_stored_rolls_in_order(self):
        text = mutate(self.source, self.pick, mutate(self.pick, "Items::Affix a = offers[choice - 2].affix;", "Items::Affix a = offers[3 - choice].affix;"))
        self.assertRed("choice-map", text, ["pick 2: the first stored roll is written whole (id, value, ranges, second part)",
                                            "pick 3: the second stored roll is written"])

    def test_the_offer_is_deleted_when_one_is_picked(self):
        text = mutate(self.source, self.pick, mutate(self.pick, 'tx->Append("DELETE FROM dc_enchant_offer WHERE item_guid={}", guid);', ""))
        self.assertRed("offer-kept", text, ["pick 1: only the offer is deleted, the item's rows are left",
                                            "pick 2: the offer is deleted and nothing is charged"])

    def test_the_line_is_replaced_not_added(self):
        text = mutate(self.source, self.pick, mutate(self.pick, 'tx->Append("DELETE FROM dc_item_affix WHERE item_guid={} AND {}", guid,\n'
                                                     '                           target.kind == "socket" ? "kind=\'socket\'" : "seq=" + std::to_string(seq));', ""))
        self.assertRed("line-kept", text, ["pick 2: the line's row is deleted by seq"])

    def test_a_damage_line_must_not_become_a_stat(self):
        guard = "Need(choice < 2 || target.value2 <= 0 || item->GetTemplate()->Class != ITEM_CLASS_WEAPON ||"
        start = self.pick.index(guard)
        end = self.pick.index(");", start) + 2
        text = mutate(self.source, self.pick, self.pick[:start] + self.pick[end:])
        self.assertRed("damage-to-stat", text, ["old one-part offer on a damage line: pick 2 refused",
                                                "old one-part offer on a damage line: pick 3 refused"])

    def test_the_guard_holds_only_a_weapons_damage_line(self):
        # A ring's +X-Y Physical Damage is two parts too, and the Mystic may turn it into any stat.
        text = mutate(self.source, self.pick, mutate(self.pick, " || item->GetTemplate()->Class != ITEM_CLASS_WEAPON ||\n", " ||\n"))
        self.assertRed("guard-on-jewelry", text, ["one-part offer on a ring's two-part damage line: pick 2 goes through"])

    def test_the_guard_must_not_stop_keeping_or_ordinary_lines(self):
        text = mutate(self.source, self.pick, mutate(self.pick, "Need(choice < 2 || target.value2 <= 0 ||",
                                                     "Need(choice < 1 || target.value2 <= 0 ||"))
        self.assertRed("guard-blocks-keep", text, ["old one-part offer on a damage line: keeping the line still works"])

    def test_a_choice_outside_one_to_three_is_refused(self):
        text = mutate(self.source, self.pick, mutate(self.pick, "choice >= 1 && choice <=", "choice >= 0 && choice <="))
        self.assertRed("choice-zero", text, ["pick 0 is refused"])

    def test_the_bind_warning_is_the_first_enchant_only(self):
        text = mutate_in(self.source, MYSTIC_STATE, "state.bind = instance.boundAccount == 0;", "state.bind = instance.boundAccount != 0;")
        self.assertRed("bind", text, ["bind warning on while the item is not bound to an account",
                                      "bind warning off once it is bound"])

    def test_the_stored_choices_keep_their_order(self):
        text = mutate_in(self.source, STORED_OFFERS, "ORDER BY choice_id", "ORDER BY choice_id DESC")
        self.assertRed("offer-order", text, ["pending: then the stored rolls in order",
                                             "pick 2: the first stored roll is written whole (id, value, ranges, second part)"])

    def test_the_second_part_of_a_stored_roll_is_read_back(self):
        text = mutate_in(self.source, STORED_OFFERS, "a.rangeMin2 = f[7].Get<double>();", "a.rangeMin2 = 0;")
        self.assertRed("range2", text, ["pick 3 on a damage line writes value2 and the second bracket"])

    def test_the_pending_screen_leads_with_the_line_as_it_is(self):
        text = mutate_in(self.source, MYSTIC_STATE, "auto three = Enchant::Waiting(lines, offers.front().target, socket, stored);",
                         "auto three = Enchant::Waiting(stored, offers.front().target, socket, stored);")
        self.assertRed("pending-lead", text, ["pending: the first is the line as it is on the item"])

    def test_the_pending_choices_come_from_the_table(self):
        text = mutate_in(self.source, STORED_OFFERS, "if (rows)", "if (false)")
        self.assertRed("no-relog", text, ["a new session reads the same three choices from the table alone"])


if __name__ == "__main__":
    unittest.main()
