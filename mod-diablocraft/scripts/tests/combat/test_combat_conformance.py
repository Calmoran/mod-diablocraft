"""diablocraft-pre-beta-bugs-b items 1-3 on the production path.

The combat conformance review (docs/research/systems/combat-conformance.md,
Wrong rows 1-3) found the auto-attack guards and the melee outcome hook gated
on `Barbarian`, and primary recovery reading the main hand's speed whichever
hand swung. This suite compiles the module's OWN functions, cut out of
dc_combat.cpp, dc_combat.h and dc_barbarian_primaries.cpp, against the doubles in
tests/combat_conformance/conformance_shim.h, and drives them with the playable
classes read out of the generated dc_class_map rows.

Each fix is also checked the other way: the suite puts the old code back
(one mutation at a time) and requires the harness to fail. A test that still
passes with the bug restored proves nothing.

What no test here covers: Unit::RollMeleeOutcomeAgainst itself, the client's
attack toggle, the swing timer and the cooldown the client draws. Those are
docs/test-pre-beta-bugs-b.md's job, live.
"""
