class CombatConformanceTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.compiler = shutil.which("c++") or shutil.which("g++")
        if not cls.compiler:
            raise unittest.SkipTest("no C++ compiler")
        cls.playable = playable_classes()
        cls.stock = next(c for c in WOW_CLASSES if c not in cls.playable)

    def build(self, name, extract_text):
        binary = harness_env.build([HARNESS / "conformance_harness.cpp"], flags=["-std=c++17", "-O0", "-UNDEBUG", "-Wall"], files={"dc_combat_conformance_extract.h": extract_text}, includes=[HARNESS])
        return harness_env.run([str(binary)] + [str(c) for c in self.playable] + [str(self.stock)],
                              capture_output=True, text=True)

    def test_production_functions(self):
        """Items 1-3 as shipped: every playable class, stock untouched, each hand's speed."""
        run = self.build("production", extract())
        self.assertEqual(run.returncode, 0, "a case failed:\n" + run.stderr[-4000:])
        self.assertEqual(run.stdout.strip(), "ok")

    def test_each_old_bug_fails_the_harness(self):
        for name, (where, old, new) in MUTATIONS.items():
            with self.subTest(mutation=name):
                if where == "combat":
                    text = extract(combat=mutate(COMBAT, old, new))
                else:
                    text = extract(primaries=mutate(PRIMARIES, old, new))
                run = self.build("mutation_" + re.sub(r"\W+", "_", name), text)
                self.assertNotEqual(run.returncode, 0, "the harness passed with %r restored" % name)
                self.assertIn("FAIL:", run.stderr)

    def test_class_map_has_a_class_beyond_the_barbarian(self):
        """The fixture is only meaningful if the map names a non-Warrior class."""
        self.assertTrue(any(c != 1 for c in self.playable), self.playable)


if __name__ == "__main__":
    unittest.main()
