"""VictimAdjustedTotal re-adds every victim term ComputeHit snapshotted (diablocraft-mhqha).

ComputeHit stores the victim's bonuses in hit.targetBonus (five readers: Primaries, Abilities, Wizard, Monk, GemPowers) and
folds them into hit.additive. VictimAdjustedTotal swaps the snapshotted bonus for the current one on every hit that is not
fixed: it subtracts hit.targetBonus and adds the readers back. A reader missing from the add-back is subtracted and never
added, so the hit loses it (Toxin's rank-25 +10% damage taken, GemPowers::TargetBonus).

  * tests/victim_adjusted_total/harness.cpp compiles the module's OWN Hit and VictimAdjustedTotal, cut out of
    dc_combat.h and dc_combat.cpp as they are, and drives each of the five terms through an unchanged victim, a debuff
    that landed afterwards and one that ended. Each rule is also checked the other way: the suite drops one reader at
    a time and requires the harness to fail;
  * a cross-source check: the readers named in ComputeHit's `hit.targetBonus =` are exactly the readers named in
    VictimAdjustedTotal, so a sixth reader added to one place and not the other fails here.

What no test here covers: the readers' own math (their tests), and the in-game hit (docs/test-diablocraft-mhqha.md).
"""
import re
import shutil
import subprocess
import unittest
from pathlib import Path

import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
import scripts_path  # noqa: E402,F401  (R5: every scripts/ folder on sys.path)
import harness_env

REPO_ROOT = Path(__file__).resolve().parents[4]
MODULE = REPO_ROOT / "mod-diablocraft"
HARNESS = MODULE / "tests" / "victim_adjusted_total"
# Scratch belongs in the build tree (AGENTS.md), not the system temp.
SCRATCH = REPO_ROOT / "azerothcore-wotlk" / "build" / "_agent-scratch" / "victim_adjusted_total"

COMBAT = (MODULE / "src" / "combat" / "dc_combat.cpp").read_text(encoding="utf-8")
COMBAT_H = (MODULE / "src" / "combat" / "dc_combat.h").read_text(encoding="utf-8")
RE_READ = "double VictimAdjustedTotal(Player* player, Unit* target, Hit const& hit)"
READER = re.compile(r"\b(\w+)::TargetBonus\(")


def definition(marker, source):
    """One function or type, braces balanced, exactly as the module has it."""
    assert source.count(marker) == 1, "%r is not unique" % marker
    start = source.index(marker)
    end = source.index("{", start) + 1
    depth = 1
    while depth:
        depth += (source[end] == "{") - (source[end] == "}")
        end += 1
    return source[start:end]


def extract(combat=COMBAT):
    head = ("// Generated by scripts/tests/combat/test_victim_adjusted_total.py from the module's own\n"
            "// source. Do not edit; edit the module and run the suite.\n#pragma once\n\n")
    return (head + "namespace DC::Combat\n{\n"
            + definition("    struct Hit\n    {", COMBAT_H) + ";\n"
            + definition(RE_READ, combat) + "\n"
            + "} // namespace DC::Combat\n")


def mutate(source, old, new):
    assert source.count(old) == 1, "mutation target %r is not unique" % old
    return source.replace(old, new)


# One rule at a time: the re-read forgets one reader. Each must make the harness fail.
MUTATIONS = {
    "the re-read forgets Primaries": (
        "(Primaries::TargetBonus(target) + Abilities::TargetBonus(target) +\n"
        "                                            Wizard::TargetBonus",
        "(0 + Abilities::TargetBonus(target) +\n"
        "                                            Wizard::TargetBonus"),
    "the re-read forgets Abilities": (
        "Primaries::TargetBonus(target) + Abilities::TargetBonus(target) +\n"
        "                                            Wizard::TargetBonus",
        "Primaries::TargetBonus(target) + 0 +\n"
        "                                            Wizard::TargetBonus"),
    "the re-read forgets Wizard": (
        "Wizard::TargetBonus(player, target, hit.school) + Monk::TargetBonus(player, target) +\n"
        "                                            GemPowers",
        "Monk::TargetBonus(player, target) +\n"
        "                                            GemPowers"),
    "the re-read forgets Monk": (
        "Monk::TargetBonus(player, target) +\n"
        "                                            GemPowers",
        "GemPowers"),
    "the re-read forgets GemPowers": (
        "Monk::TargetBonus(player, target) +\n"
        "                                            GemPowers::TargetBonus(target) -",
        "Monk::TargetBonus(player, target) -"),
    "the re-read keeps the snapshot": (
        "-\n                                            hit.targetBonus) / 100)", "-\n                                            0) / 100)"),
}


def readers(text):
    return sorted(set(READER.findall(text)))


class VictimAdjustedTotalTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.compiler = shutil.which("c++") or shutil.which("g++")
        if not cls.compiler:
            raise unittest.SkipTest("no C++ compiler")

    def build(self, name, extract_text):
        folder = SCRATCH / name
        folder.mkdir(parents=True, exist_ok=True)
        (folder / "dc_victim_adjusted_total_extract.h").write_text(extract_text, encoding="utf-8")
        binary = folder / "victim_adjusted_total_harness"
        built = subprocess.run(
            [self.compiler, "-std=c++17", "-O0", "-UNDEBUG", "-Wall", "-I", str(folder), "-I", str(HARNESS),
             str(HARNESS / "harness.cpp"), "-o", str(binary)],
            capture_output=True, text=True)
        self.assertEqual(built.returncode, 0, "%s did not compile:\n%s" % (name, built.stderr[-6000:]))
        return harness_env.run([str(binary)], capture_output=True, text=True)

    def test_every_victim_term_survives_the_re_read(self):
        """Red on nightly 8bfdc427: the GemPowers term is subtracted and never added back."""
        run = self.build("production", extract())
        self.assertEqual(run.returncode, 0, "a case failed:\n" + run.stderr[-4000:])
        self.assertEqual(run.stdout.strip(), "ok")

    def test_each_reader_failing_the_harness_when_dropped(self):
        for name, (old, new) in MUTATIONS.items():
            with self.subTest(mutation=name):
                run = self.build("mutation_" + re.sub(r"\W+", "_", name), extract(mutate(COMBAT, old, new)))
                self.assertNotEqual(run.returncode, 0, "the harness passed with %r" % name)
                self.assertIn("FAIL:", run.stderr)

    def test_compute_hit_and_the_re_read_name_the_same_readers(self):
        """Cross-source: the five readers ComputeHit snapshots are the readers the re-read adds back."""
        match = re.search(r"hit\.targetBonus = (.*?);", COMBAT, re.S)
        assert match and COMBAT.count("hit.targetBonus = ") == 1, "ComputeHit's snapshot is not one assignment"
        snapshot = readers(match.group(1))
        re_read = definition(RE_READ, COMBAT)
        self.assertGreaterEqual(len(snapshot), 5, "the snapshot lost a reader: %s" % snapshot)
        self.assertEqual(readers(re_read), snapshot, "ComputeHit and VictimAdjustedTotal read different victim terms")

    def test_the_other_victim_multiplier_is_still_divided_out(self):
        """targetFactor (Elemental Exposure) is a multiplier, not part of targetBonus: the re-read swaps it, not the pool."""
        self.assertIn("Wizard::TargetFactor(player, target) / hit.targetFactor", definition(RE_READ, COMBAT))


if __name__ == "__main__":
    unittest.main(verbosity=2)
