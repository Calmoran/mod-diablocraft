"""Hardcore is the realm's, not the character's (11 H4, ruling 2026-09-21).

Normal and Hardcore are separate realms. The login prompt is gone and a new
character is written into `dc_character_mode` from
`Diablocraft.Hardcore.Enable` on its first login, in the same call that hands
out the 08 §5 kit.

Two harnesses are executions rather than readings, and both compile module code
rather than a copy of it. `realm_harness.cpp` runs `RealmMode` and `EnsureMode`,
cut out of `src/hardcore/dc_hardcore.cpp` beside the `Name`/`Parse`/`Load`/
`Forget` helpers they call. `login_order_harness.cpp` runs the same writer and
`StartOwed` from `src/common/dc_world.cpp` through the core's own login order,
because two failures only show up there: a start that never inserted its row has
no retry once `AT_LOGIN_FIRST` is consumed, and the account economy resolves at
`OnPlayerLogin` while the character is still modeless.

What those harnesses model rather than run is named in their own headers: the
account economy is a model of the four behaviours the owner review cited, the
ledger is not modelled, and the kit is not modelled.

What stays a source assertion, and why: that the prompt is gone, that `choose`
is a GM tool, and that the two authorised inserts are the only writes of `mode`
are all facts about which code exists, so reading the source is the only way to
state them; and `DC::World::Start` cannot be compiled out of its file without
the whole starter kit, so the order of its two gates is checked as text.
"""
import re
import shutil
import subprocess
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
import scripts_path  # noqa: E402,F401  (R5: every scripts/ folder on sys.path)
import harness_env
import unittest
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[4]
MODULE = REPO_ROOT / "mod-diablocraft"
HARNESS = MODULE / "tests" / "hardcore_realm"
CORE = REPO_ROOT / "azerothcore-wotlk"
# Scratch belongs in the build tree (AGENTS.md), not the system temp.
SCRATCH = CORE / "build" / "_agent-scratch" / "hardcore_realm"

HARDCORE = (MODULE / "src" / "hardcore" / "dc_hardcore.cpp").read_text(encoding="utf-8")
HEADER = (MODULE / "src" / "hardcore" / "dc_hardcore.h").read_text(encoding="utf-8")
WORLD = (MODULE / "src" / "common" / "dc_world.cpp").read_text(encoding="utf-8")
CONF = (MODULE / "conf" / "mod_diablocraft.conf.dist").read_text(encoding="utf-8")

# In the order they have to compile in.
EXTRACTED = (
    "char const* Name(Mode mode)",
    "Mode Parse(",
    "Mode Load(",
    "void Forget(",
    "Mode RealmMode(",
    "bool EnsureMode(",
)


def definition(marker, source=None):
    """The whole function, braces balanced, exactly as the module has it."""
    source = HARDCORE if source is None else source
    start = source.index(marker)
    assert source.count(marker) == 1, "%s is not unique" % marker
    end = source.index("{", start) + 1
    depth = 1
    while depth:
        depth += (source[end] == "{") - (source[end] == "}")
        end += 1
    return source[start:end]


AUTHORIZED_INSERT = "INSERT IGNORE INTO dc_character_mode (guid,mode) VALUES ({},'{}')"


def sql_statements(source):
    """Every statement against `dc_character_mode` in `source`.

    Comments are dropped and adjacent string literals are glued back together,
    then each SQL verb is read up to the end of its own literal. This is not a
    C++ lexer and does not pretend to be one, but it does not depend on pairing
    quotes across the whole file either - which is exactly how the first version
    of this test went wrong. It matched `"..."` pairs from the top of the file,
    an earlier literal shifted the pairing, and the second `INSERT IGNORE` (the
    GM repair) was never seen at all, so a test that claimed there was one
    writer passed while there were two.
    """
    code = "\n".join(line for line in source.splitlines() if not line.lstrip().startswith("//"))
    glued = re.sub(r'"\s*"', "", code)
    return re.findall(r'(?:INSERT|REPLACE|UPDATE|DELETE)\s[^"]*?dc_character_mode[^"]*', glued)


class HardcoreRealmTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.compiler = shutil.which("c++") or shutil.which("g++")
        if not cls.compiler:
            raise unittest.SkipTest("no C++ compiler")
        SCRATCH.mkdir(parents=True, exist_ok=True)
        header = ("// Generated by scripts/tests/hardcore/test_hardcore_realm.py from the module's own\n"
                  "// source. Do not edit; edit the module and run the suite.\n"
                  "#pragma once\n#include \"realm_shim.h\"\n\n")
        (SCRATCH / "dc_hardcore_extract.h").write_text(
            header + "\n\n".join(definition(marker) for marker in EXTRACTED) + "\n",
            encoding="utf-8")
        (SCRATCH / "dc_world_extract.h").write_text(
            header + definition("bool StartOwed(", WORLD) + "\n", encoding="utf-8")
        cls.binaries = {}
        for source in ("realm_harness.cpp", "login_order_harness.cpp"):
            binary = SCRATCH / Path(source).stem
            built = subprocess.run(
                [cls.compiler, "-std=c++17", "-O0", "-UNDEBUG",
                 "-I", str(SCRATCH), "-I", str(HARNESS),
                 str(HARNESS / source), "-o", str(binary)],
                capture_output=True, text=True)
            if built.returncode:
                raise AssertionError("%s did not compile:\n%s" % (source, built.stderr[-4000:]))
            cls.binaries[source] = binary

    def run_harness(self, source):
        run = harness_env.run([str(self.binaries[source])], capture_output=True, text=True)
        self.assertEqual(run.returncode, 0, "a case failed:\n" + run.stderr[-4000:])
        self.assertEqual(run.stdout.strip(), "ok")

    def test_the_realm_setting_is_what_a_new_character_is_written_as(self):
        """Setting 0 writes normal, 1 writes hardcore, an existing row stands."""
        self.run_harness("realm_harness.cpp")

    def test_the_login_resolves_the_account_after_the_mode_and_retries(self):
        """Eight scenarios over the core's own login order, both hook orders.

        A new character on either realm, an account that already has a balance,
        a pending contribution credited exactly once across three logins, a
        failed resolution and a failed mode write each recovering on the next
        login, an existing mode that neither the realm setting nor the credit
        can move, and a completed start that is left alone.
        """
        self.run_harness("login_order_harness.cpp")

    def test_the_mode_column_has_exactly_two_writers_and_both_only_insert(self):
        """H4 permanence, over both sites.

        There are two: the realm writer in `EnsureMode`, and the GM repair in
        `.dc mode choose`. They send the same `INSERT IGNORE`, so neither can
        overwrite a row that exists. The death and GM-revive statements write
        `dead`, `died_at` and `killed_by` on the same table and are allowed;
        what no statement may do is assign the `mode` column again.
        """
        statements = sql_statements(HARDCORE)
        self.assertTrue(statements, "the statements moved; this test is reading nothing")
        inserts = [statement for statement in statements if statement.startswith("INSERT")]
        self.assertEqual(inserts, [AUTHORIZED_INSERT, AUTHORIZED_INSERT],
                         "the two authorized inserts are not what is in the file: %r" % (inserts,))
        # Named, so neither site can quietly become something else or move.
        for marker in ("    static bool HandleChoose(", "bool EnsureMode("):
            body = definition(marker)
            self.assertIn(AUTHORIZED_INSERT, body, "%s no longer inserts the row" % marker.strip())
            self.assertEqual(body.count("dc_character_mode"), 1,
                             "%s touches the table more than once" % marker.strip())
        for statement in statements:
            self.assertFalse(statement.upper().startswith("REPLACE"),
                             "REPLACE would overwrite a permanent row: " + statement)
            if statement == AUTHORIZED_INSERT:
                continue
            self.assertIsNone(re.search(r"(?<![_A-Za-z])mode\s*=", statement),
                              "a statement assigns the mode column: " + statement)

    def test_the_prompt_is_gone_from_the_server(self):
        """No fallback text, no player-facing question, nothing left to answer."""
        self.assertNotIn("PromptFallback", HARDCORE)
        self.assertNotIn("PromptFallback", HEADER)
        self.assertNotIn("PromptFallback", WORLD)
        self.assertNotIn("ModeChosen", HARDCORE + HEADER + WORLD)
        for phrase in ("Choose a mode", "before your gear is handed out"):
            self.assertNotIn(phrase, HARDCORE)
        # The Lua half (lua/aio/dc_mode.lua) is DeepSeek's and is left in place
        # for the paired task; nothing on the server may still point at it.
        self.assertNotIn("dc_mode.lua", HARDCORE + WORLD)

    def test_choose_survives_only_as_a_gm_repair(self):
        self.assertIn('{"choose", HandleChoose, SEC_ADMINISTRATOR, Console::No}', HARDCORE)
        self.assertNotIn("SEC_PLAYER", HARDCORE)

    def test_the_kit_is_gated_on_the_mode_then_on_the_account(self):
        """Start hands out nothing until the row is written and the account is
        resolved against it, in that order, and both failures defer rather than
        grant."""
        # diablocraft-class-parity: both gates moved into Setup, which Start
        # calls for every class before its profile lookup (#69).
        setup = definition("bool Setup(Player* player, bool creation = false)", WORLD)
        start = definition("void Start(Player* player, bool creation = false)", WORLD)
        # The creation path writes the mode and resolves the account in one go.
        self.assertIn("return Hardcore::EnsureMode(player) && AccountEconomy::ResolveCreation(player);", setup)
        self.assertIn("if (!Hardcore::EnsureMode(player))\n        return false;", setup)
        self.assertIn("if (!AccountEconomy::ResolvePending(player))", setup)
        self.assertLess(setup.index("Hardcore::EnsureMode"), setup.index("AccountEconomy::ResolvePending"),
                        "the account is resolved before the mode exists, which is the bug this fixed")
        # The resolution's failure path returns; it does not fall through.
        self.assertIn("return false;", setup[setup.index("AccountEconomy::ResolvePending"):])
        # Both gates are before the profile lookup and before the first thing
        # the start does to the character, and a failure defers.
        self.assertIn("if (!Setup(player, creation))\n        return;", start)
        self.assertLess(start.index("Setup(player, creation)"), start.index("ProfileFor(player)"))
        self.assertLess(start.index("Setup(player, creation)"), start.index("GiveLevel"))

    def test_a_start_that_never_inserted_its_row_is_retried_next_login(self):
        """The core clears AT_LOGIN_FIRST before the first-login hook, so a
        first attempt that failed before inserting `dc_character_start` has no
        other retry."""
        owed = definition("bool StartOwed(", WORLD)
        self.assertIn("return !player->HasAtLoginFlag(AT_LOGIN_FIRST);", owed)
        login = definition("    void OnPlayerLogin(Player* player) override", WORLD)
        self.assertIn("if(StartOwed(player,row)) Start(player);", login)
        self.assertIn("else if(row) SweepBags(player);", login)

    def test_the_realm_setting_ships_in_the_conf_default_off(self):
        self.assertIn("Diablocraft.Hardcore.Enable = 0", CONF)
        self.assertIn('sConfigMgr->GetOption<bool>("Diablocraft.Hardcore.Enable", false)', HARDCORE)


if __name__ == "__main__":
    unittest.main(verbosity=2)
