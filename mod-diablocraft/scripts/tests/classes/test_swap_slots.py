"""A swap of two wells is one server step (diablocraft-7oozd, from yo9rx's review).

A drag from one well to another used to be two DCSLOT messages: the first took the target well's old skill off the bar (SetSlot's K6
delete) and the second, refused (combat, the gap, the cooldown rule), left it off. Restoring the first well fails the same way. Only a
swap the server does in one transaction cannot lose a skill.

`swap_slots_harness.cpp` runs the module's own DC::Classes::SwapSlots, cut out of src/classes/dc_classes.cpp exactly as it is, against
the core doubles of tests/swap_on_cooldown/swap_shim.h and a fake dc_character_skillbar table whose commit applies every statement or,
when the database refuses, none. The mutants below each break one rule in the production text and require the named scenarios to go
red; they work on text in memory and a scratch folder, never on the tree. The wiring (the DCSWAP message, its gap, the header, the
docs) is checked on the text.

    python mod-diablocraft/scripts/tests/classes/test_swap_slots.py
"""
import re
import shutil
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
import scripts_path  # noqa: E402,F401  (R5: every scripts/ folder on sys.path)
import harness_env

REPO = Path(__file__).resolve().parents[4]
MODULE = REPO / "mod-diablocraft"
HARNESS = MODULE / "tests" / "swap_slots"
SHIM = MODULE / "tests" / "swap_on_cooldown"
CLASSES_CPP = MODULE / "src" / "classes" / "dc_classes.cpp"
CLASSES_H = MODULE / "src" / "classes" / "dc_classes.h"
CONTRACT = REPO / "docs" / "contracts" / "skillbar-messages.md"
SCRATCH = REPO / "azerothcore-wotlk" / "build" / "_agent-scratch" / "swap_slots"
MARKER = "bool SwapSlots(Player* player, unsigned from, unsigned to, std::string& error)"
SCENARIOS = 13


def definition(marker, source):
    assert source.count(marker) == 1, "%r is not unique in dc_classes.cpp (%d)" % (marker, source.count(marker))
    start = source.index(marker)
    end = source.index("{", start) + 1
    depth = 1
    while depth:
        depth += (source[end] == "{") - (source[end] == "}")
        end += 1
    return source[start:end]


def mutate(text, old, new):
    assert text.count(old) == 1, "mutation target %r occurs %d times" % (old, text.count(old))
    return text.replace(old, new)


class SwapSlots(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.compiler = shutil.which("c++") or shutil.which("g++")
        if not cls.compiler:
            raise unittest.SkipTest("no C++ compiler")
        SCRATCH.mkdir(parents=True, exist_ok=True)
        cls.source = CLASSES_CPP.read_text(encoding="utf-8")

    def build_and_run(self, variant, source):
        folder = SCRATCH / variant
        folder.mkdir(parents=True, exist_ok=True)
        (folder / "dc_swap_slots_extract.h").write_text(
            "// Generated by scripts/tests/classes/test_swap_slots.py from the module's own source. Do not edit.\n"
            "#pragma once\n#include \"swap_shim.h\"\n\nnamespace DC::Classes\n{\n" + definition(MARKER, source) + "\n}\n",
            encoding="utf-8")
        binary = harness_env.build([HARNESS / "swap_slots_harness.cpp"], flags=["-std=c++17", "-O0", "-UNDEBUG", "-pthread"],
                                   includes=[folder, SHIM, MODULE / "src"])
        ran = harness_env.run([str(binary)], capture_output=True, text=True)
        results = {}
        for line in ran.stdout.splitlines():
            if line.startswith("PASS "):
                results[line[5:]] = True
            elif line.startswith("FAILED "):
                results[line[7:]] = False
        return ran.returncode, results, ran.stdout + ran.stderr

    def assertRed(self, variant, source, scenarios):
        code, results, output = self.build_and_run(variant, source)
        self.assertNotEqual(code, 0, "%s: the harness still passed:\n%s" % (variant, output[-2000:]))
        for scenario in scenarios:
            self.assertIs(results.get(scenario), False, "%s: %s did not go red:\n%s" % (variant, scenario, output[-3000:]))

    def test_production_passes_every_scenario(self):
        code, results, output = self.build_and_run("production", self.source)
        self.assertEqual(code, 0, "scenarios failed:\n" + output[-6000:])
        self.assertEqual(len(results), SCENARIOS, output[-2000:])
        self.assertTrue(all(results.values()), output[-2000:])

    # ---- one mutant for each rule -----------------------------------------------------

    def test_mutant_a_skill_is_dropped_when_the_target_is_empty(self):
        mutated = mutate(self.source, "        if (!held[side])\n            continue;\n        std::string skill = held[side]->skill",
                         "        if (!held[side] || !held[1 - side])\n            continue;\n        std::string skill = held[side]->skill")
        self.assertRed("mutant_drops_on_empty", mutated, ("a_skill_moves_to_an_empty_well",
                                                          "an_empty_well_moves_nothing_to_a_full_one_the_other_way",
                                                          "no_swap_of_any_two_wells_ever_loses_a_skill"))

    def test_mutant_both_skills_go_to_one_well(self):
        mutated = mutate(self.source, "guid, side == 0 ? to : from, held[side]->skillId", "guid, to, held[side]->skillId")
        self.assertRed("mutant_one_well", mutated, ("two_skills_trade_wells_in_one_step", "no_swap_of_any_two_wells_ever_loses_a_skill"))

    def test_mutant_a_skill_stays_in_its_well(self):
        mutated = mutate(self.source, "guid, side == 0 ? to : from, held[side]->skillId", "guid, side == 0 ? from : to, held[side]->skillId")
        self.assertRed("mutant_stays", mutated, ("two_skills_trade_wells_in_one_step", "a_skill_moves_to_an_empty_well"))

    def test_mutant_the_old_rows_stay(self):
        mutated = mutate(self.source, "guid, from, to);", "guid, from, from);")
        self.assertRed("mutant_old_rows_stay", mutated, ("two_skills_trade_wells_in_one_step", "no_swap_of_any_two_wells_ever_loses_a_skill"))

    def test_mutant_the_shell_is_lost(self):
        mutated = mutate(self.source, "held[side]->skillId, held[side]->spellId, skill, rune)", "held[side]->skillId, held[side]->skillId, skill, rune)")
        self.assertRed("mutant_shell_lost", mutated, ("a_skill_keeps_its_shell_and_names",))

    def test_mutant_the_rune_is_lost(self):
        mutated = mutate(self.source, "std::string skill = held[side]->skill, rune = held[side]->rune;", "std::string skill = held[side]->skill, rune;")
        self.assertRed("mutant_rune_lost", mutated, ("a_skill_keeps_its_shell_and_names",))

    def test_mutant_two_empty_wells_write(self):
        mutated = mutate(self.source, "    if (!held[0] && !held[1])\n    {", "    if (false)\n    {")
        self.assertRed("mutant_empty_writes", mutated, ("two_empty_wells_are_refused_and_write_nothing",))

    def test_mutant_the_same_well_is_swapped(self):
        mutated = mutate(self.source, "    if (from == to)\n    {", "    if (false)\n    {")
        self.assertRed("mutant_same_well", mutated, ("the_same_well_is_refused",))

    def test_mutant_a_well_past_the_bar_is_swapped(self):
        mutated = mutate(self.source, "    if (from >= ActiveSlots() || to >= ActiveSlots())\n    {", "    if (from >= ActiveSlots())\n    {")
        self.assertRed("mutant_past_the_bar", mutated, ("a_well_past_the_bar_is_refused",))

    def test_mutant_combat_is_ignored(self):
        mutated = mutate(self.source, "    // SetSlot's rules for a bar edit: not in combat, not inside an instance except a Greater Rift whose Guardian is dead.\n    if (player->IsInCombat())",
                         "    // SetSlot's rules for a bar edit: not in combat, not inside an instance except a Greater Rift whose Guardian is dead.\n    if (false)")
        self.assertRed("mutant_combat", mutated, ("combat_refuses_and_changes_nothing",))

    def test_mutant_an_instance_is_ignored(self):
        mutated = mutate(self.source, "    if (player->GetMap() && player->GetMap()->Instanceable() && !DC::Rifts::GreaterRiftGuardianDead(player))\n    {\n        error = \"Not inside an instance or rift.\";\n        return false;\n    }\n    std::vector<Slot> const bar",
                         "    std::vector<Slot> const bar")
        self.assertRed("mutant_instance", mutated, ("an_instance_refuses_and_changes_nothing",))

    def test_mutant_a_class_with_no_skills_is_swapped(self):
        mutated = mutate(self.source, "    if (!Playable(player))\n    {\n        error = \"This class has no Diablocraft skills.\";\n        return false;\n    }\n    if (from >= ActiveSlots()",
                         "    if (from >= ActiveSlots()")
        self.assertRed("mutant_unplayable", mutated, ("a_class_with_no_skills_is_refused",))

    def test_mutant_a_refused_save_is_ignored(self):
        mutated = mutate(self.source, "    if (!CharacterDatabase.AsyncCommitTransaction(transaction).m_future.get())\n    {\n        error = \"The skill bar could not be saved.\";\n        return false;\n    }\n    WriteActionBar(player);\n    return true;\n}\n\nbool InitializeStarterBar",
                         "    CharacterDatabase.AsyncCommitTransaction(transaction).m_future.get();\n    WriteActionBar(player);\n    return true;\n}\n\nbool InitializeStarterBar")
        self.assertRed("mutant_save_ignored", mutated, ("a_refused_save_leaves_both_skills_on_the_bar",))

    def test_mutant_a_cooldown_blocks_the_swap(self):
        mutated = mutate(self.source, "    std::uint64_t const guid = player->GetGUID().GetRawValue();\n    CharacterDatabaseTransaction transaction = CharacterDatabase.BeginTransaction();\n    transaction->Append(\"DELETE FROM dc_character_skillbar WHERE guid={} AND slot IN",
                         "    for (Slot const* row : held)\n        if (row && player->GetSpellCooldownDelay(row->spellId))\n            return false;\n    std::uint64_t const guid = player->GetGUID().GetRawValue();\n    CharacterDatabaseTransaction transaction = CharacterDatabase.BeginTransaction();\n    transaction->Append(\"DELETE FROM dc_character_skillbar WHERE guid={} AND slot IN")
        self.assertRed("mutant_cooldown", mutated, ("a_skill_on_cooldown_swaps_like_any_other",))

    def test_mutant_the_bar_is_not_rewritten(self):
        mutated = mutate(self.source, "    WriteActionBar(player);\n    return true;\n}\n\nbool InitializeStarterBar", "    return true;\n}\n\nbool InitializeStarterBar")
        self.assertRed("mutant_no_bar_write", mutated, ("two_skills_trade_wells_in_one_step",))

    # ---- the wiring, on the text ---------------------------------------------------------

    def test_the_message_is_one_request_under_the_slot_gap(self):
        source = re.sub(r"\s+", " ", self.source)
        handler = source[source.index('parts[0] == "DCSWAP"'):source.index('parts[0] == "DCPASSIVE"')]
        self.assertIn("parts.size() >= 3", handler)
        self.assertIn('if (!Admit(slotGap_, player, "skill_slot_gap_ms")) return;', handler)
        self.assertIn("from = static_cast<unsigned>(std::stoul(parts[1])); to = static_cast<unsigned>(std::stoul(parts[2]));", handler)
        self.assertIn("if (!SwapSlots(player, from, to, error)) ChatHandler(player->GetSession()).SendSysMessage(error);", handler)
        # A message that is not a number is dropped, as DCPASSIVE's.
        self.assertIn("catch (std::exception const&) { return; }", handler)

    def test_the_header_declares_it(self):
        header = re.sub(r"\s+", " ", CLASSES_H.read_text(encoding="utf-8"))
        self.assertIn("bool SwapSlots(Player* player, unsigned from, unsigned to, std::string& error);", header)

    def test_swap_is_one_transaction_with_one_commit(self):
        body = definition(MARKER, self.source)
        self.assertEqual(body.count("BeginTransaction()"), 1)
        self.assertEqual(body.count("AsyncCommitTransaction("), 1)
        self.assertEqual(body.count("WriteActionBar("), 1)
        self.assertLess(body.index("AsyncCommitTransaction("), body.index("WriteActionBar("))
        self.assertNotIn("SetSlot(", body)

    def test_the_contract_names_the_message(self):
        text = re.sub(r"\s+", " ", CONTRACT.read_text(encoding="utf-8"))
        for needle in ("`DCSWAP`", "one server step", "While a swap is pending no other drag starts"):
            self.assertIn(needle, text, needle)
        # The window's two-halves pacing is retired (diablocraft-toe6s): the contract no longer describes it.
        for gone in ("SWAP_MARGIN", "SWAP_TRIES", "held while the player is in combat"):
            self.assertNotIn(gone, text, gone)


if __name__ == "__main__":
    unittest.main()
