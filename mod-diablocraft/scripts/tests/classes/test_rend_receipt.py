"""A fully absorbed Rend tick keeps no hit receipt (GitHub #74).

`FinalTick` records the tick's pre-crit receipt before the core absorbs and
delivers it. A tick the absorb eats whole reaches Unit::DealDamage as zero, and
the one consumer (the rift-elite OnDamage) returns on zero before it takes the
receipt, so the receipt waited for the next hit on that elite. The core has no
hook after a tick's delivery, so RendPeriodicProvider also listens to OnDamage
and drops the attacker's receipt on a zero-damage event.

rend_receipt_harness.cpp compiles the module's OWN receipt store, FinalTick,
RendPeriodicProvider and the rift-elite OnDamage, cut out of dc_combat.cpp,
dc_combat.h and dc_affix_unit_script.cpp exactly as they are, and runs a tick through
a model of the core's absorb and OnDamage step, with the two scripts in both
orders. Each rule is also checked the other way: the suite puts one bug back at
a time and requires the harness to fail.

What no test here covers: the native absorb, patch 0016's call into the
provider, and the live Reflects Damage cast (docs/test-diablocraft-rend-receipt.md).
"""
import re
import shutil
import unittest
from pathlib import Path

import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
import scripts_path  # noqa: E402,F401  (R5: every scripts/ folder on sys.path)
import harness_env

REPO_ROOT = Path(__file__).resolve().parents[4]
MODULE = REPO_ROOT / "mod-diablocraft"
HARNESS = MODULE / "tests" / "rend_receipt"
# Scratch belongs in the build tree (AGENTS.md), not the system temp.

COMBAT = "".join(p.read_text(encoding="utf-8") for p in [MODULE / "src" / "combat" / "dc_combat_internal.h", *sorted((MODULE / "src" / "combat").glob("dc_combat*.cpp")),
                                                       MODULE / "src" / "classes" / "barbarian" / "dc_barbarian_rend.cpp"])
COMBAT_H = (MODULE / "src" / "combat" / "dc_combat.h").read_text(encoding="utf-8")
ELITES = (MODULE / "src" / "monsters" / "affixes" / "dc_affix_unit_script.cpp").read_text(encoding="utf-8")


def definition(marker, source):
    """One function or type, braces balanced, exactly as the module has it."""
    assert source.count(marker) == 1, "%r is not unique" % marker
    start = source.index(marker)
    end = source.index("{", start) + 1
    depth = 1
    while depth:
        depth += (source[end] == "{") - (source[end] == "}")
        end += 1
    return source[start:end]


def line_of(pattern, source):
    found = re.search(pattern, source, re.M)
    assert found, "no line matches %r" % pattern
    return found.group(0).strip()


def receipt_store(source):
    """The anonymous namespace holding the map, then the three functions."""
    start = source.rindex("namespace", 0, source.index("struct HitReceipt"))
    last = definition("std::optional<PreCritHit> ConsumePreCritHit(", source)
    text = source[start:source.index(last) + len(last)]
    for name in ("RecordPreCritHit(", "ClearPreCritHit(", "ConsumePreCritHit(", "thread_local"):
        assert name in text, "the receipt store slice lost %s" % name
    return text


def extract(combat=COMBAT):
    head = ("// Generated by scripts/tests/classes/test_rend_receipt.py from the module's own\n"
            "// source. Do not edit; edit the module and run the suite.\n#pragma once\n\n")
    return (head + "namespace DC::Combat\n{\n"
            + definition("    struct Hit\n    {", COMBAT_H) + ";\n"
            + definition("    struct PreCritHit\n    {", COMBAT_H) + ";\n"
            + receipt_store(combat) + "\n"
            + definition("double VictimAdjustedTotal(Player* player, Unit* target, Hit const& hit)", combat) + "\n"
            + line_of(r"^\s*constexpr uint32 REND_BLEED_FIRST = \d+, REND_BLEED_LAST = \d+;", combat) + "\n"
            + "struct dc_rend_bleed\n{\n    Hit snapshot;\n    uint32 baseTicks = 0;\n    bool valid = false;\n    std::vector<ItemPower::BleedStack> stacks;\n"
            + definition("bool FinalTick(AuraEffect const* effect, Unit* caster, Unit* target, uint64& damage, "
                         "bool& critical)", combat)
            + "\n};\n"
            + definition("class RendPeriodicProvider final : public UnitScript", combat) + ";\n"
            + "} // namespace DC::Combat\n\n"
            + "struct EliteScript : UnitScript\n{\n"
              "    EliteScript() : UnitScript(\"dc_rift_elites\", true, {UNITHOOK_ON_DAMAGE}) {}\n"
            + definition("void OnDamage(Unit* attacker, Unit* victim, uint32& damage) override", ELITES)
            + "\n};\n")


def mutate(source, old, new):
    assert source.count(old) >= 1, "mutation target %r is gone" % old
    return source.replace(old, new)


# One rule at a time. Each must make the harness fail.
MUTATIONS = {
    "the tick is cut to 32 bits": (
        "damage = ExactDamage(adjusted);",
        "damage = uint32(std::clamp<double>(adjusted, 0.0, std::numeric_limits<uint32>::max()));"),
    "no clear on a zero-damage event": (
        "ClearPreCritHit(attacker->ToPlayer());", "(void)0;"),
    "the hook is not listed, so the core never calls it": (
        "{UNITHOOK_PROVIDE_FINAL_PERIODIC_DAMAGE, UNITHOOK_ON_DAMAGE}", "{UNITHOOK_PROVIDE_FINAL_PERIODIC_DAMAGE}"),
    "clears on a landed tick too": (
        "if (!damage && attacker)", "if (attacker)"),
    "a lengthened bleed stops at the base length": (
        "number > uint32(effect->GetTotalTicks())", "number > 5"),
    "a lengthened bleed spreads the same total over more ticks": (
        "ItemPower::BleedDamage(stacks, number)",
        "ItemPower::BleedTick(snapshot.total, effect->GetTotalTicks(), number)"),
    "clears every player's receipt": (
        "preCritHits.erase(player->GetGUID().GetRawValue());", "preCritHits.clear();"),
    "clears the victim's receipt too": (
        "void OnDamage(Unit* attacker, Unit*, uint32& damage) override\n"
        "            {\n"
        "                if (!damage && attacker)\n"
        "                    ClearPreCritHit(attacker->ToPlayer());",
        "void OnDamage(Unit* attacker, Unit* victim, uint32& damage) override\n"
        "            {\n"
        "                if (!damage && attacker)\n"
        "                    ClearPreCritHit(attacker->ToPlayer());\n"
        "                if (!damage && victim)\n"
        "                    ClearPreCritHit(victim->ToPlayer());"),
}


class RendReceiptTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.compiler = shutil.which("c++") or shutil.which("g++")
        if not cls.compiler:
            raise unittest.SkipTest("no C++ compiler")

    def build(self, name, extract_text):
        binary = harness_env.build([HARNESS / "rend_receipt_harness.cpp"], flags=["-std=c++17", "-O0", "-UNDEBUG", "-Wall"], files={"dc_rend_receipt_extract.h": extract_text}, includes=[HARNESS])
        return harness_env.run([str(binary)], capture_output=True, text=True)

    def test_a_fully_absorbed_tick_leaves_no_receipt_and_a_landed_one_keeps_it(self):
        """Today's code leaves the absorbed tick's receipt behind; this is red on it."""
        run = self.build("production", extract())
        self.assertEqual(run.returncode, 0, "a case failed:\n" + run.stderr[-4000:])
        self.assertEqual(run.stdout.strip(), "ok")

    def test_each_rule_fails_the_harness_when_broken(self):
        for name, (old, new) in MUTATIONS.items():
            with self.subTest(mutation=name):
                combat = mutate(COMBAT, old, new)
                run = self.build("mutation_" + re.sub(r"\W+", "_", name), extract(combat))
                self.assertNotEqual(run.returncode, 0, "the harness passed with %r" % name)
                self.assertIn("FAIL:", run.stderr)

    def test_the_double_stands_for_what_the_consumer_really_does(self):
        """EliteStruck in the harness only takes the receipt; this pins that production's does
        the same, first, before any of its affix branches."""
        body = definition("static void EliteStruck(Creature* elite, EliteState* state, Player* player, "
                          "uint32& damage)", ELITES)
        self.assertIn("auto const preCrit = DC::Combat::ConsumePreCritHit(player, elite);", body)
        self.assertLess(body.index("ConsumePreCritHit(player, elite)"), body.index("ShieldingAbsorbs("))


if __name__ == "__main__":
    unittest.main(verbosity=2)
