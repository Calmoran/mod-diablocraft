"""A skill that is on cooldown cannot be changed (diablocraft-7sh0, the designer "Wizard - Meteor Bug").

The designer: a spell on cooldown must not be changeable at all until the cooldown is done,
rune or spell; anything off cooldown swaps freely. Meteor kept its cooldown across a
rune swap (diablocraft-xfvx), which he called the wrong behaviour.

The rule is DC::Classes::SetSlot's, so the picker's DCSLOT message and `.dc skill` share
it. `swap_harness.cpp` runs the module's own SetSlot, its catalogue lookups and the
catalogue's data declarations - cut out of src/classes/dc_classes.cpp exactly as they are -
against doubles for the core (swap_shim.h: Player's cooldown map, the characters database),
with the catalogue loaded the way ClassWorld::OnStartup loads it from the rows the
generator wrote (the generated class_catalogue.sql, parsed here into a TSV). So the skills,
runes and ids it swaps are the shipped ones.

The mutants below each break one rule in the production text and require the named
scenarios to go red; they work on text in memory and a scratch folder, never on the tree.
"""
import re
import shutil
import unittest
from pathlib import Path

import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
import scripts_path  # noqa: E402,F401  (R5: every scripts/ folder on sys.path)
import harness_env

REPO_ROOT = Path(__file__).resolve().parents[4]
MODULE = REPO_ROOT / "mod-diablocraft"
HARNESS = MODULE / "tests" / "swap_on_cooldown"
CLASSES_CPP = MODULE / "src" / "classes" / "dc_classes.cpp"
CATALOGUE_SQL = MODULE / "data" / "generated" / "class_catalogue.sql"
CORE = REPO_ROOT / "azerothcore-wotlk"
# Scratch belongs in the build tree (AGENTS.md), not the system temp.
SCRATCH = CORE / "build" / "_agent-scratch" / "swap_on_cooldown"

SET_SLOT = "bool SetSlot(Player* player, unsigned slot, std::string const& skill, std::string const& rune,"
COOLDOWN_LEFT = "std::uint32_t SkillCooldownLeft(Player* player, std::uint32_t skillId)"

# In the order they have to compile in. The catalogue's data declarations and its two
# structs come first; Key is used by ShellFor, ClassId by Entry.
STRUCTS = ("struct PairHash", "struct CatalogueEntry")
DATA_FROM, DATA_TO = "std::mutex dataMutex;", "bool dataReady = false;"
PRIVATE = (
    "std::uint32_t ClassId(Player const* player)",
    "CatalogueEntry const* Entry(Player const* player, std::string const& label)",
    "std::string Key(std::string const& skill, std::string const& rune)",
    "bool ShellFor(Player const* player, std::string const& skill, std::string const& rune,",
    "std::pair<std::string, std::string> LabelFor(std::uint32_t spellId)",
)
PUBLIC = (
    "bool Playable(Player const* player)",
    "bool SkillUnlocked(Player const* player, std::string const& skill)",
    "bool RuneUnlocked(Player const* player, std::string const& skill, std::string const& rune)",
    SET_SLOT,
)


def definition(marker, source):
    """The whole function, braces balanced, exactly as the module has it."""
    assert source.count(marker) == 1, "%r is not unique in dc_classes.cpp (%d)" % (marker, source.count(marker))
    start = source.index(marker)
    end = source.index("{", start) + 1
    depth = 1
    while depth:
        depth += (source[end] == "{") - (source[end] == "}")
        end += 1
    return source[start:end]


def struct_definition(marker, source):
    text = definition(marker, source)
    end = source.index(text) + len(text)
    assert source[end] == ";", "%s has no closing semicolon" % marker
    return text + ";"


def between(first, last, source):
    assert source.count(first) == 1 and source.count(last) == 1, "%r .. %r" % (first, last)
    return source[source.index(first):source.index(last) + len(last)]


def extract_header(source):
    """The production text the harness runs, in the namespaces production has it in.

    SkillCooldownLeft is taken when the module has it. On a tree without the gate the harness
    still builds, so the scenarios fail on behaviour (the swap goes through) and not on a
    missing symbol; test_the_gate_exists says plainly that it is missing."""
    private = list(PRIVATE) + ([COOLDOWN_LEFT] if COOLDOWN_LEFT in source else [])
    pieces = [struct_definition(marker, source) for marker in STRUCTS]
    pieces.append(between(DATA_FROM, DATA_TO, source))
    pieces += [definition(marker, source) for marker in private]
    public = [definition(marker, source) for marker in PUBLIC]
    return ("// Generated by scripts/tests/classes/test_swap_on_cooldown.py from the module's own source.\n"
            "// Do not edit; edit the module and run the suite.\n"
            "#pragma once\n#include \"swap_shim.h\"\n\n"
            "namespace DC::Classes\n{\nnamespace\n{\n" + "\n\n".join(pieces) + "\n} // namespace\n\n"
            + "\n\n".join(public) + "\n}\n")


SQL_TABLE = re.compile(r"^INSERT INTO `(\w+)`")
STRING = r"'((?:[^']|'')*)'"  # a SQL string; an apostrophe inside it is written ''
CATALOGUE_ROW = re.compile(r"^\((\d+), (\d+), (\d+), (\d+), (\d+), (\d+)\)[,;]$")
LABEL_ROW = re.compile(r"^\((\d+), (\d+), %s, %s, %s, %s\)[,;]$" % ((STRING,) * 4))
MAP_ROW = re.compile(r"^\((\d+), %s, %s, (\d+), %s, %s, %s\)[,;]$" % ((STRING,) * 5))


def catalogue_tsv():
    """The generated catalogue as the harness loads it: the same JOIN the server runs
    (dc_class_catalogue to dc_class_label on spell_id and class_id), plus dc_class_map."""
    rows = {"dc_class_catalogue": [], "dc_class_label": [], "dc_class_map": []}
    table = None
    for line in CATALOGUE_SQL.read_text(encoding="utf-8").splitlines():
        found = SQL_TABLE.match(line)
        if found:
            table = found.group(1)
        elif line.startswith("(") and table in rows:
            pattern = {"dc_class_catalogue": CATALOGUE_ROW, "dc_class_label": LABEL_ROW, "dc_class_map": MAP_ROW}[table]
            parsed = pattern.match(line)
            assert parsed, "unreadable %s row: %s" % (table, line)
            rows[table].append(tuple(group.replace("''", "'") for group in parsed.groups()))
        if line.endswith(";"):
            table = None
    labels = {(int(spell), int(klass)): (skill, rune, category)
              for spell, klass, skill, rune, category, _element in rows["dc_class_label"]}
    out = ["M\t%s\t%s" % (mapped[3], mapped[0]) for mapped in rows["dc_class_map"]]  # wow class -> class id
    joined = 0
    for klass, skill_id, rune_id, spell_id, unlock, indicator in rows["dc_class_catalogue"]:
        label = labels.get((int(spell_id), int(klass)))
        if label:                      # an inner join, as the loader's query is
            skill, rune, category = label
            out.append("\t".join(["C", klass, skill_id, rune_id, spell_id, unlock, indicator, category, skill, rune]))
            joined += 1
    return "\n".join(out) + "\n", len(rows["dc_class_catalogue"]), joined


def mutate(text, old, new):
    assert text.count(old) == 1, "mutation target %r occurs %d times" % (old, text.count(old))
    return text.replace(old, new)


class SwapOnCooldown(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.compiler = shutil.which("c++") or shutil.which("g++")
        if not cls.compiler:
            raise unittest.SkipTest("no C++ compiler")
        SCRATCH.mkdir(parents=True, exist_ok=True)
        cls.source = CLASSES_CPP.read_text(encoding="utf-8")
        text, cls.catalogue_rows, cls.joined_rows = catalogue_tsv()
        cls.tsv = SCRATCH / "catalogue.tsv"
        cls.tsv.write_text(text, encoding="utf-8")

    def build_and_run(self, variant, source):
        """Compile the harness against `source`'s extracted text and run it. Returns
        (exit code, {scenario: passed}, output)."""
        folder = SCRATCH / variant
        folder.mkdir(parents=True, exist_ok=True)
        (folder / "dc_swap_extract.h").write_text(extract_header(source), encoding="utf-8")
        binary = folder / "swap_harness"
        if binary.exists():
            binary.unlink()
        binary = harness_env.build([HARNESS / "swap_harness.cpp"], flags=["-std=c++17", "-O0", "-UNDEBUG", "-pthread"], includes=[folder, HARNESS, MODULE / "src"])
        ran = harness_env.run([str(binary), str(self.tsv)], capture_output=True, text=True)
        results = {}
        for line in ran.stdout.splitlines():
            if line.startswith("PASS "):
                results[line[5:]] = True
            elif line.startswith("FAILED "):
                results[line[7:]] = False
        return ran.returncode, results, ran.stdout + ran.stderr

    def assertRed(self, variant, source, scenarios):
        code, results, output = self.build_and_run(variant, source)
        self.assertNotEqual(code, 0, "%s: the harness still passed:\n%s" % (variant, output[-2000:]))
        for scenario in scenarios:
            self.assertIs(results.get(scenario), False, "%s: %s did not go red:\n%s" % (variant, scenario, output[-3000:]))

    # ---- the data feeding the harness ------------------------------------------------

    def test_every_generated_catalogue_row_reaches_the_harness(self):
        self.assertEqual(self.catalogue_rows, self.joined_rows, "a catalogue row has no label")
        self.assertGreater(self.joined_rows, 250)
        text = self.tsv.read_text(encoding="utf-8")
        for wanted in ("\tMeteor\tMolten Impact\n", "\tMeteor\tComet\n", "\tMeteor\t\n", "M\t8\t2\n", "M\t1\t1\n"):
            self.assertIn(wanted, text)

    # ---- the production change --------------------------------------------------------

    def test_the_gate_exists(self):
        """SetSlot asks the skill's cooldown, and asks it before anything is written."""
        self.assertIn(COOLDOWN_LEFT, self.source, "dc_classes.cpp has no SkillCooldownLeft: the gate is missing")
        set_slot = definition(SET_SLOT, self.source)
        self.assertIn("SkillCooldownLeft(", set_slot)
        self.assertLess(set_slot.index("SkillCooldownLeft("), set_slot.index("BeginTransaction"))
        self.assertLess(set_slot.index("SkillCooldownLeft("), set_slot.index("AsyncCommitTransaction"))
        self.assertLess(set_slot.index("SkillCooldownLeft("), set_slot.index("WriteActionBar("))

    def test_production_passes_every_scenario(self):
        code, results, output = self.build_and_run("production", self.source)
        self.assertEqual(code, 0, "scenarios failed:\n" + output[-6000:])
        self.assertEqual(len(results), 11, output[-2000:])
        self.assertTrue(all(results.values()), output[-2000:])

    # ---- single-rule mutants: each breaks one rule and names what must go red --------

    def test_mutant_the_gate_never_asks_the_cooldown(self):
        mutated = mutate(self.source, "SkillCooldownLeft(player, held.skillId)", "0u")
        self.assertRed("mutant_no_gate", mutated, (
            "rune_swap_refused_while_the_skill_is_on_cooldown",
            "spell_swap_refused_while_the_skill_is_on_cooldown",
            "a_move_with_another_rune_is_a_rune_swap",
            "every_skill_is_one_unit_whatever_its_runes"))

    def test_mutant_only_the_slotted_shell_is_asked(self):
        mutated = mutate(self.source, "SkillCooldownLeft(player, held.skillId)",
                         "player->GetSpellCooldownDelay(held.spellId)")
        self.assertRed("mutant_slotted_shell_only", mutated, (
            "a_cooldown_on_any_rune_of_the_skill_counts",
            "the_longest_cooldown_of_the_skill_is_quoted",
            "every_skill_is_one_unit_whatever_its_runes"))

    def test_mutant_only_the_base_shell_counts(self):
        mutated = mutate(self.source, "entry.skillId == skillId", "entry.spellId == skillId")
        self.assertRed("mutant_base_shell_only", mutated, (
            "rune_swap_refused_while_the_skill_is_on_cooldown",
            "a_cooldown_on_any_rune_of_the_skill_counts"))

    def test_mutant_any_skills_cooldown_blocks(self):
        mutated = mutate(self.source, "entry.skillId == skillId", "true")
        self.assertRed("mutant_any_skill_blocks", mutated, (
            "off_cooldown_skills_swap_freely_whatever_else_is_cooling",
            "every_skill_is_one_unit_whatever_its_runes"))

    def test_mutant_a_move_hides_a_rune_swap(self):
        mutated = mutate(self.source, "(held.slot != slot && held.skillId != skillId)", "(held.slot != slot)")
        self.assertRed("mutant_target_slot_only", mutated, ("a_move_with_another_rune_is_a_rune_swap",))

    def test_mutant_the_replaced_skill_is_not_asked(self):
        mutated = mutate(self.source, "(held.slot != slot && held.skillId != skillId)", "(held.skillId != skillId)")
        self.assertRed("mutant_moved_skill_only", mutated, (
            "spell_swap_refused_while_the_skill_is_on_cooldown",
            "a_move_replaces_a_skill_which_is_checked"))

    def test_mutant_the_same_shell_is_refused_too(self):
        mutated = mutate(self.source, " || held.spellId == spellId)", ")")
        self.assertRed("mutant_same_shell_refused", mutated, ("moving_the_same_shell_is_not_a_change",))

    def test_mutant_the_refusal_still_writes(self):
        mutated = mutate(self.source, 's left).";\n            return false;', 's left).";\n            break;')
        self.assertRed("mutant_writes_anyway", mutated, (
            "rune_swap_refused_while_the_skill_is_on_cooldown",
            "spell_swap_refused_while_the_skill_is_on_cooldown"))

    def test_mutant_the_time_left_rounds_down(self):
        mutated = mutate(self.source, "(left + 999) / 1000", "left / 1000")
        self.assertRed("mutant_rounds_down", mutated, ("the_time_left_rounds_up_and_zero_is_ready",))

    def test_mutant_the_refusal_names_the_incoming_skill(self):
        mutated = mutate(self.source, "error = held.skill + ", "error = skill + ")
        self.assertRed("mutant_wrong_name", mutated, (
            "spell_swap_refused_while_the_skill_is_on_cooldown",
            "a_move_replaces_a_skill_which_is_checked"))


if __name__ == "__main__":
    unittest.main(verbosity=2)
