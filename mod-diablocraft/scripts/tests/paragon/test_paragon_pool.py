"""PoolFor follows the player's Hardcore mode (GitHub #77, 10-paragon P3/section 4).

`PoolFor` returned `Pool::Normal` unconditionally, so a Hardcore character's
Paragon reads and awards went to the Normal account pool instead of its own
(the gap recorded in decisions.md 2026-09-23). No Hardcore realm exists yet,
so this proves the fix offline, the way tests/hardcore_realm proves 11-hardcore:
`pool_harness.cpp` runs the module's own `PoolFor`, `PoolName` and `Key` - cut
out of src/paragon/dc_paragon.cpp exactly as they are - against fixture
players, with `Hardcore::IsHardcore` doubled (pool_shim.h). 11-hardcore's own
answer is proven elsewhere; this suite is only about whether PoolFor, and the
account key every read and write is keyed by, follow that answer.
"""
import shutil
import subprocess
import unittest
from pathlib import Path

import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
import scripts_path  # noqa: E402,F401  (R5: every scripts/ folder on sys.path)
import harness_env

REPO_ROOT = Path(__file__).resolve().parents[4]
MODULE = REPO_ROOT / "mod-diablocraft"
HARNESS = MODULE / "tests" / "paragon_pool"
CORE = REPO_ROOT / "azerothcore-wotlk"
# Scratch belongs in the build tree (AGENTS.md), not the system temp.
SCRATCH = CORE / "build" / "_agent-scratch" / "paragon_pool"

PARAGON = (MODULE / "src" / "paragon" / "dc_paragon.cpp").read_text(encoding="utf-8")

# In the order they have to compile in: Key calls PoolFor.
EXTRACTED = (
    "Pool PoolFor(",
    "char const* PoolName(",
    "AccountKey Key(",
)


def definition(marker, source=PARAGON):
    """The whole function, braces balanced, exactly as the module has it."""
    assert source.count(marker) == 1, "%s is not unique" % marker
    start = source.index(marker)
    end = source.index("{", start) + 1
    depth = 1
    while depth:
        depth += (source[end] == "{") - (source[end] == "}")
        end += 1
    return source[start:end]


class ParagonPoolTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.compiler = shutil.which("c++") or shutil.which("g++")
        if not cls.compiler:
            raise unittest.SkipTest("no C++ compiler")
        SCRATCH.mkdir(parents=True, exist_ok=True)
        header = ("// Generated by scripts/tests/paragon/test_paragon_pool.py from the module's own\n"
                  "// source. Do not edit; edit the module and run the suite.\n"
                  "#pragma once\n#include \"pool_shim.h\"\n\n")
        (SCRATCH / "dc_paragon_pool_extract.h").write_text(
            header + "\n\n".join(definition(marker) for marker in EXTRACTED) + "\n",
            encoding="utf-8")
        binary = SCRATCH / "pool_harness"
        built = subprocess.run(
            [cls.compiler, "-std=c++17", "-O0", "-UNDEBUG",
             "-I", str(SCRATCH), "-I", str(HARNESS),
             str(HARNESS / "pool_harness.cpp"), "-o", str(binary)],
            capture_output=True, text=True)
        if built.returncode:
            raise AssertionError("pool_harness.cpp did not compile:\n%s" % built.stderr[-4000:])
        cls.binary = binary

    def test_a_hardcore_fixture_earns_hardcore_a_normal_fixture_earns_normal(self):
        """PoolFor, and the account key every read/write is keyed by, follow
        Hardcore::IsHardcore; today's always-Normal code fails this."""
        run = harness_env.run([str(self.binary)], capture_output=True, text=True)
        self.assertEqual(run.returncode, 0, "a case failed:\n" + run.stderr[-4000:])
        self.assertEqual(run.stdout.strip(), "ok")


if __name__ == "__main__":
    unittest.main(verbosity=2)
