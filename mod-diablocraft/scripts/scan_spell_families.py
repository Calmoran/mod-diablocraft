"""Reproduce the full pinned Warrior DBC/SQL and effect-mask collision evidence."""
import csv
import hashlib
import io
import re
import struct
import subprocess
from pathlib import Path

import scripts_path  # noqa: E402,F401  (R5: every scripts/ folder on sys.path)
import generate_spells as g

PIN = (g.REPO_ROOT / 'core-commit.txt').read_text().split()[0]
SQL_PATH = 'data/sql/base/db_world/spell_dbc.sql'

def scan():
    sql = subprocess.check_output(['git', '-C', str(g.REPO_ROOT/'azerothcore-wotlk'),
                                   'show', f'{PIN}:{SQL_PATH}']).decode()
    columns = re.findall(r'^  `([^`]+)`', sql, re.M)
    assert len(columns) == 234
    names = ['SpellClassMask_'+str(i) for i in range(1,4)]
    names += [f'EffectSpellClassMask{w}_{i}' for w in 'ABC' for i in range(1,4)]
    rows = []
    for origin, records in (
        ('DBC', ([str(x) for x in struct.unpack('<234I', r)] for r in g.load_dbc('Spell.dbc')[0].values())),
        ('SQL', (next(csv.reader([line[1:-2]], quotechar="'", escapechar='\\'))
                 for line in sql.splitlines() if line.startswith('('))),
    ):
        for record in records:
            assert len(record) == len(columns), (origin, record[0], len(record))
            if int(record[columns.index('SpellClassSet')]) != 4:
                continue
            rows.append([origin, int(record[0])] + [int(record[columns.index(n)]) for n in names])
    return sql, names, rows

def main():
    sql, names, rows = scan()
    evidence = g.REPO_ROOT/'docs/research/primaries-warrior-masks.csv'
    with evidence.open('w', newline='', encoding='utf-8') as f:
        out = csv.writer(f, lineterminator='\n')
        out.writerow(['source','spell_id']+names)
        out.writerows(rows)
    union = [0,0,0]
    effect = [0,0,0]
    for row in rows:
        for i in range(3):
            union[i] |= row[2+i]
            for e in range(3):
                effect[i] |= row[5+i*3+e]
    # The bits this used to reserve in word 3 of family 4, and the
    # data/d3/spell_families.csv it used to write them into, are retired:
    # step 6 made the record writer's family pass the one home for the family
    # and the mask (Architect, 2026-09-20), and it puts every shell in family
    # 20 - which no stock record uses - with the skill's own bit in word one.
    # The evidence dump below is what this script is still for: it is what
    # proves nothing of the stock Warrior vocabulary is being reused.
    free = [1 << i for i in range(31) if not (union[2] | effect[2]) & (1 << i)]
    assert len(free) >= 4
    text = f'''# Primaries Warrior mask evidence

Generated by `mod-diablocraft/scripts/scan_spell_families.py`.
Core pin: `{PIN}`. SQL is read with git show from `{SQL_PATH}` at that pin.
Extracted Spell.dbc SHA-256: `{hashlib.sha256((g.DBC/'Spell.dbc').read_bytes()).hexdigest()}`.
Pinned SQL SHA-256: `{hashlib.sha256(sql.encode()).hexdigest()}`.
Full dump: [all Warrior rows and all three modifier effect masks](primaries-warrior-masks.csv).
Counts: {sum(r[0]=='DBC' for r in rows)} DBC; {sum(r[0]=='SQL' for r in rows)} SQL.
Combined spell masks: {' / '.join(f'{x:08X}' for x in union)}.
Combined effect masks: {' / '.join(f'{x:08X}' for x in effect)}.
Allocated word-3 bits: {', '.join(f'{x:08X}' for x in free[:4])}.

Both inputs are included independently, including overridden IDs. Allocation
excludes the union of spell and effect masks. Tests verify each skill's mask
matches its six selectable shells and no other skill or stock Warrior row.
No Primary rune is a native family modifier (ruling 2026-09-12).
The extracted input also contains older module rows outside family 4; it is
identified by hash rather than described as a pristine Blizzard binary. The
client generator replaces its own IDs instead of appending duplicate shells.

Pinned native Warrior special cases inspected: SpellEffects.cpp school damage
case (348) and weapon damage case (3418), SpellInfo.cpp positivity (1995),
Spell.cpp cast validation (6241), plus Warrior handlers in Unit.cpp,
SpellAuraEffects.cpp and scripts/Spells/spell_warrior.cpp. The damage flag
special cases use words 1/2; custom spells use word 3 and no stock IDs.
The generator clears inherited effect masks and unrelated effects.
'''
    (evidence.with_suffix('.md')).write_text(text, encoding='utf-8', newline='\n')
    print(text)

if __name__ == '__main__':
    main()
