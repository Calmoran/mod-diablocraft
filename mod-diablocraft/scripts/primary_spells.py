def inputs(g):
    # primary_mechanics.csv is the designer's, not D3's, so the FILE moved to
    # data/tunables/ (Architect 2026-09-19, second-table ruling). It keeps
    # this generator and dc_barbarian_primary_data.h; only the folder changed.
    return ({r['key']: float(r['value']) for r in g.read_tunables_csv('primary_mechanics.csv')},
            g.read_csv('primary_effects.csv'))

def write_header(g):
    mechanics, rows = inputs(g)
    behaviors = sorted({r['behavior'] for r in rows})
    text = '// Generated by generate_spells.py from data/d3/primary_effects.csv and data/tunables/primary_mechanics.csv.\n#pragma once\n#include <cstdint>\nnamespace DC::Combat::PrimaryData {\n'
    text += 'enum class Behavior { '+', '.join(behaviors)+' };\n'
    text += 'struct Row { uint32_t id; char const* skill; double damage, fury; Behavior behavior; double chance; uint32_t duration; double magnitude; unsigned cap; uint32_t lockout; };\n'
    text += 'inline constexpr Row Rows[] = {\n'
    for r in rows:
        text += '    {'+r['spell_id']+', "'+r['skill']+'", '+', '.join([
            r['damage_pct'],r['fury'],'Behavior::'+r['behavior'],r['proc_pct'],r['duration_ms'],r['magnitude'],r['max_stacks'],r['lockout_ms']])+'},\n'
    text += '};\ninline Row const* Find(uint32_t id) { for (auto const& row : Rows) if (row.id == id) return &row; return nullptr; }\n'
    for key, value in mechanics.items():
        text += f'inline constexpr double {key} = {value:g};\n'
    for key in ('RUPTURE','FROSTBITE','SMITE','HAMMER','STUPEFY','ONSLAUGHT','FROST_LOCKOUT','VANGUARD','FRENZY_BUFF','GATHERING','PULVERIZE','SIDEARM','SCATTERING','KNOCKUP'):
        text += f'inline constexpr uint32_t {key} = {globals()[key]};\n'
    text += '}\n'
    (g.MODULE_ROOT/'src/classes/barbarian/dc_barbarian_primary_data.h').write_text(text, encoding='utf-8', newline='\n')

def configure(values, columns, name, primary, mechanics, targeting, ranges, radii, durations, closest, rows):
    def put(column, value): values[columns.index(column)] = value
    if primary:
        put('Effect_1',31)  # WEAPON_PERCENT_DAMAGE: nonzero launch seed
        put('EffectBasePoints_1',99)
        put('EffectDieSides_1',1)
        put('PowerType',FURY_POWER)  # Fury's slot (class resource registry); cost zero, Fury generated by module
        # SpellClassSet and SpellClassMask are not written here. The record
        # writer's family pass in generate_spells.py is their one home - family
        # 20 plus the skill's own bit, shared by its runes and companions -
        # per the Architect ruling of 2026-09-20 (decisions.md). A second copy
        # here only disagreed with it.
        for i in range(1,4):
            for prefix in ('EffectAura_','EffectTriggerSpell_','EffectMechanic_',
                           'EffectChainTargets_','EffectSpellClassMaskA_',
                           'EffectSpellClassMaskB_','EffectSpellClassMaskC_'):
                put(prefix+str(i),0)
        skill = primary['skill_name']
        if skill != 'Weapon Throw': put('Speed',0) # retain donor 57755 Speed for Throws
        put('DefenseType',3 if skill == 'Weapon Throw' else 2)
        put('Mechanic',0)
        put('MaxTargets',0)
        # Audit row 116: Weapon Throw's range is skill_targeting.csv's own
        # range_yards cell, read here rather than repeated. A generator cannot
        # read dc_tunables, so the CSV is the single home for it.
        throw_yards = float(targeting['Weapon Throw']['range_yards'])
        put('RangeIndex',closest(ranges,throw_yards) if skill == 'Weapon Throw' else (1 if skill=='Cleave' else 2))
        if name == 'Cleave - Broad Sweep':
            put('ImplicitTargetA_1',15)
            put('EffectRadiusIndex_1',closest(radii,mechanics['broad_sweep_radius_yards']))
        if name == 'Weapon Throw - Ricochet':
            # EffectChainTargets_1 is the values sheet's, written by the record
            # writer's chain pass: the sheet states three ADDITIONAL enemies and
            # the field carries four because the core's ChainTarget counts the
            # primary (Architect, decisions.md 2026-09-20). primary_mechanics.csv
            # held a second, derived copy of that four; it is retired.
            put('EffectChainAmplitude_1',1)
            put('AttributesEx4',0x00040000) # BOUNCY_CHAIN_MISSILES
    elif values[columns.index('ID')] in range(RUPTURE, KNOCKUP+1):
        for i in range(1,4):
            for prefix in ('Effect_','EffectAura_','EffectTriggerSpell_','EffectMechanic_',
                           'EffectChainTargets_','EffectSpellClassMaskA_',
                           'EffectSpellClassMaskB_','EffectSpellClassMaskC_'):
                put(prefix+str(i),0)
        put('Speed',0)
        put('DefenseType',1)
        put('Mechanic',0)
        put('MaxTargets',0)
        put('RangeIndex',13) # anywhere; exclusively module-triggered
        put('ImplicitTargetA_1',6)
        put('ImplicitTargetB_1',0)
        key = {HAMMER:'Hammer', FROST_LOCKOUT:'Frost Lockout', FRENZY_BUFF:'Frenzy', GATHERING:'Gathering Storm'}.get(values[columns.index('ID')],name)
        sid = values[columns.index('ID')]
        if sid == KNOCKUP:
            put('Effect_1',98) # real knockback; module selects approved vertical executor
            put('EffectBasePoints_1',1)
        elif sid in DAMAGE_SECONDARIES:
            put('Effect_1',2)
            put('EffectBasePoints_1',1)
            put('EffectDieSides_1',1)
            if sid in (PULVERIZE,SIDEARM):
                put('ImplicitTargetA_1',104) # native finite-line provider 0011
                put('EffectRadiusIndex_1',0) # provider supplies exact dimensions
                if sid == SIDEARM:
                    # Existing sourced Heroic Throw axe projectile mapping.
                    put('Speed',mechanics['sidearm_projectile_speed'])
            else:
                put('ImplicitTargetA_1',8) # DEST_AREA_ENEMY
                put('EffectRadiusIndex_1',closest(radii,mechanics['rupture_radius_yards' if sid==RUPTURE else 'scattering_radius_yards']))
        else:
            behavior = {'Hammer':'hammer','Frost Lockout':'frostbite','Frenzy':'plain','Gathering Storm':'gathering'}.get(key,key.lower())
            row = next(r for r in rows if r['behavior']==behavior)
            milliseconds = int(mechanics['frenzy_duration_ms']) if key in ('Vanguard','Frenzy') else int(row['lockout_ms' if key=='Frost Lockout' else 'duration_ms'])
            matching=[i for i,r in durations.items() if __import__('struct').unpack_from('<i',r,4)[0]==milliseconds]
            if not matching: raise ValueError(f'No exact stock duration for {key}')
            put('DurationIndex',min(matching))
            put('Effect_1',6)
            put('EffectAura_1',12 if key in ('Frostbite','Smite','Hammer') else 4)
            put('EffectBasePoints_1',0)
            put('Attributes',values[columns.index('Attributes')] | 0x04000000)
            if key == 'Frostbite': put('Mechanic',13) # FREEZE
            elif key in ('Smite','Hammer'): put('Mechanic',12) # STUN
            elif key == 'Stupefy':
                put('EffectAura_1',177) # AOE_CHARM, single target
                put('Mechanic',1) # MECHANIC_CHARM (the core's 1; 30 is Sapped), the mechanic the Juggernaut and the Guardian refuse
            elif key == 'Vanguard':
                # DUMMY: a display buff only (diablocraft-aura-fixes, aura review row 4). The run speed is the sheet's one
                # aggregate MOD_INCREASE_SPEED (82408); a second speed carrier here would win UpdateSpeed if the aggregate
                # ever fell below it.
                put('EffectAura_1',4)
                put('ImplicitTargetA_1',1)
                put('Attributes',values[columns.index('Attributes')] & ~0x04000000)
            elif key == 'Frost Lockout':
                put('Attributes',values[columns.index('Attributes')] | 0x80) # internal marker only; no client display
            elif key == 'Frenzy':
                put('ImplicitTargetA_1',1)
                put('CumulativeAura',int(mechanics['frenzy_max_stacks']))
                put('Attributes',values[columns.index('Attributes')] & ~0x04000000)
                put('SpellVisualID_1',0)
                put('SpellVisualID_2',0)
            elif key == 'Gathering Storm':
                put('EffectAura_1',33) # native movement slow
                put('EffectBasePoints_1',-int(mechanics['gathering_chill_pct'])-1)
                put('EffectDieSides_1',1)
                put('Effect_2',6)
                put('EffectAura_2',87) # native non-module damage taken, all schools
                put('EffectBasePoints_2',int(row['magnitude'])-1)
                put('EffectDieSides_2',1)
                put('EffectMiscValue_2',127)
                put('ImplicitTargetA_2',6)

